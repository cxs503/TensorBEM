"""Reproducibility guard for the Ursell refinement table in the docs.

``docs/marine_bem_benchmarks.md`` (section 4.6) publishes a panel-refinement
table for the submerged circular cylinder. Those digits were once transcribed by
hand and silently stopped matching the code after the singular single-layer
potential was re-integrated (commit ``267d5a3``), which an audit then reported as
a 10.6 % discrepancy in the *relative error*. The fix is twofold: the table is
now generated by :mod:`tensorbem.benchmarks.ursell_convergence_table`, and this
test fails whenever the published rows stop reproducing from the shipped solver.

Only the 64- and 128-panel rows are recomputed here (about 20 s in total); the
256-panel row costs roughly a minute and is left to the CLI. The tolerance is
1 % relative, tight enough to catch the ~10 % drift that motivated the test and
loose enough to absorb three-significant-figure rounding in the document.
"""

from __future__ import annotations

import math
import re
from pathlib import Path

import numpy as np
import pytest

from tensorbem.benchmarks import ursell_convergence_table as table

DOC_PATH = Path(__file__).resolve().parents[1] / "docs" / "marine_bem_benchmarks.md"

# Values as printed in the document (``format_markdown`` layout).
DOCUMENTED = {
    64: {
        "added_mass": 2587.76,
        "added_mass_relative_error": 1.67e-2,
        "damping": 2787.24,
        "damping_relative_error": 2.54e-2,
        "near_over_far_field_damping": 1.0105,
    },
    128: {
        "added_mass": 2566.83,
        "added_mass_relative_error": 8.51e-3,
        "damping": 2754.47,
        "damping_relative_error": 1.34e-2,
        "near_over_far_field_damping": 1.0053,
    },
}

REFERENCE = {"added_mass": 2545.17, "damping": 2718.15}
MFS_DOCUMENTED = {
    64: (2543.24, 2708.57),
    128: (2544.69, 2715.76),
    256: (2545.05, 2717.55),
}
RELATIVE_TOLERANCE = 1.0e-2


@pytest.fixture(scope="module")
def full_table() -> dict:
    """One 64/128-panel run shared by every assertion in this module."""
    return table.build_table(sorted(DOCUMENTED))


@pytest.fixture(scope="module")
def rows(full_table) -> dict[int, dict[str, float]]:
    return {row["panels"]: row for row in full_table["rows"]}


@pytest.mark.parametrize("panels", sorted(DOCUMENTED))
def test_documented_rows_still_reproduce(rows, panels):
    published = DOCUMENTED[panels]
    computed = rows[panels]
    for key, expected in published.items():
        actual = computed[key]
        assert actual == pytest.approx(
            expected, rel=RELATIVE_TOLERANCE
        ), f"{panels}-panel {key}: code={actual!r} doc={expected!r}"


def test_reference_coefficients_are_stable(rows):
    """The analytic column of the table must not drift either."""
    reference = table.reference_coefficients()
    assert reference["added_mass"] == pytest.approx(
        REFERENCE["added_mass"], rel=RELATIVE_TOLERANCE
    )
    assert reference["damping"] == pytest.approx(
        REFERENCE["damping"], rel=RELATIVE_TOLERANCE
    )
    assert reference["omega"] == pytest.approx(
        math.sqrt(0.6 * 9.80665), rel=1.0e-12
    )


def test_mfs_rows_still_reproduce():
    for panels, (added_mass, damping) in MFS_DOCUMENTED.items():
        row = table.mfs_row(panels)
        assert row["added_mass"] == pytest.approx(added_mass, rel=RELATIVE_TOLERANCE)
        assert row["damping"] == pytest.approx(damping, rel=RELATIVE_TOLERANCE)


def test_radiation_condition_identity_is_satisfied(rows):
    """Near-field and far-field damping must agree to a fraction of a percent."""
    for panels, row in rows.items():
        assert abs(row["near_over_far_field_damping"] - 1.0) < 2.0e-2
        assert row["relative_residual"] < 1.0e-12
        assert np.isfinite(row["condition_number"])
        assert row["condition_number"] < 10.0


def test_document_contains_the_generated_rows(full_table):
    """The markdown table in the docs must be the generated one, verbatim."""
    generated = table.format_markdown(table.merge_rows(full_table))
    document = DOC_PATH.read_text()
    missing = [
        line for line in generated.splitlines() if line.strip() and line not in document
    ]
    assert not missing, "documentation table drifted from the code:\n" + "\n".join(
        missing
    )


def test_every_panel_column_has_a_generated_mfs_row():
    """A hand-edited MFS row must not survive alone.

    The verbatim check above only constrains the rows the generator emits, so
    deleting one row and relabelling another used to slip through: an audit of
    the published table found a single MFS row labelled "64 面元" carrying the
    128-panel numbers (2544.69 / 2715.76), with the genuine 64-panel row gone.
    Counting columns instead of trusting the labels closes that hole.
    """
    document = DOC_PATH.read_text()
    start = document.index("| 面元数 |")
    block = document[start : start + document[start:].index("\n\n")]
    panel_counts = {int(m.group(1)) for m in re.finditer(r"(?m)^\| (\d+) \|", block)}
    # ``format_markdown`` labels every generated MFS row with both the panel
    # count and the fundamental-solution count (m3229); the column count, not
    # the label, is what this test trusts.
    mfs_rows = {
        (int(m.group(1)), int(m.group(2)))
        for m in re.finditer(
            r"(?m)^\| 基本解方法（MFS，(\d+) 面元、(\d+) 源）", block
        )
    }
    mfs_counts = {panels for panels, _sources in mfs_rows}
    assert panel_counts <= mfs_counts, (sorted(panel_counts), sorted(mfs_counts))
    assert {64, 128, 256} <= mfs_counts, sorted(mfs_counts)
    assert all(sources == 24 for _panels, sources in mfs_rows), sorted(mfs_rows)

def test_documents_are_classified_pinned():
    from tensorbem.benchmarks import doc_claim_audit as audit

    report = audit.audit()
    tiers = {record["doc"]: record["tier"] for record in report["records"]}
    assert tiers.get(COUPLINGS_DOC) == "PINNED"
    assert tiers.get(CURVATURE_DOC) == "PINNED"


def test_check_reports_pass():
    report = pins.check()
    assert report["status"] == "PASS"
    for name, doc in report["documents"].items():
        assert doc["status"] == "PASS", (name, doc.get("failures"))
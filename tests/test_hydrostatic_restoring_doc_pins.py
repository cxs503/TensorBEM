"""Gates for the two hydrostatic-restoring documents of this repository.

``docs/hydrostatic_restoring_couplings.md``
    The m3196 note on the heave-roll / heave-pitch / roll-pitch couplings of the
    restoring matrix.  Its 78 numbers were injected by a script that lives under
    ``docs/m3196/outputs/`` (not importable, not tested), so until this file no
    test read the document: the coverage audit classified it ``UNGUARDED``.

``docs/hydrostatic_restoring_waterplane_curvature.md``
    New in m4741: closes the debt that the m3196 note records in its section 5
    (curved waterplanes / curved hull walls were never checked against the energy
    Hessian) and is generated by
    ``python -m tensorbem.benchmarks.hydrostatic_restoring_pins --write``.

Both are read *as text* here and every printed number is compared with a fresh
recomputation at the precision it was printed to, so an edit of a digit in the
markdown -- or a change in :mod:`tensorbem.hydrostatic` -- turns this red.  The
negative control (``test_perturbed_digit_is_caught``) proves the gate can fail:
a gate that cannot fail is a decoration.
"""

from __future__ import annotations

import pytest

from tensorbem.benchmarks import hydrostatic_restoring_pins as pins

#: Document names must appear literally: the coverage audit
#: (:mod:`tensorbem.benchmarks.doc_claim_audit`) decides a document is PINNED by
#: finding its file name inside ``tests/``.
COUPLINGS_DOC = "hydrostatic_restoring_couplings.md"
CURVATURE_DOC = "hydrostatic_restoring_waterplane_curvature.md"


@pytest.fixture(scope="module")
def couplings_records():
    text = pins.DOC.read_text(encoding="utf-8")
    return pins.compare(pins.parse_couplings_doc(text), pins.couplings_values())


@pytest.fixture(scope="module")
def curvature_records():
    text = pins.CURVATURE_DOC.read_text(encoding="utf-8")
    return pins.compare(pins.parse_curvature_doc(text), pins.curvature_values())


# ---------------------------------------------------------------------------
# the documents themselves
# ---------------------------------------------------------------------------
def test_documents_exist():
    assert pins.DOC.exists(), COUPLINGS_DOC
    assert pins.CURVATURE_DOC.exists(), CURVATURE_DOC


def test_couplings_doc_is_fully_parsed(couplings_records):
    """Every number the document states must be found and matched to a value."""
    assert len(couplings_records) == 78
    missing = [r["key"] for r in couplings_records if r["status"] == "MISSING"]
    assert missing == []


def test_couplings_doc_numbers_reproduce(couplings_records):
    drift = [
        (r["key"], r["text"], r["declared"], r["computed"])
        for r in couplings_records
        if r["status"] == "DRIFT"
    ]
    assert drift == [], f"documented numbers drifted: {drift}"


def test_curvature_doc_numbers_reproduce(curvature_records):
    assert len(curvature_records) >= 300
    drift = [
        (r["key"], r["text"], r["declared"], r["computed"])
        for r in curvature_records
        if r["status"] != "PASS"
    ]
    assert drift == [], f"generated document drifted: {drift}"


def test_perturbed_digit_is_caught():
    """Negative control: move one printed digit and the gate must say DRIFT."""
    text = pins.DOC.read_text(encoding="utf-8")
    target = "| C33 heave | 2.010363e+04"
    assert target in text
    broken = text.replace(target, "| C33 heave | 2.010364e+04", 1)
    records = pins.compare(pins.parse_couplings_doc(broken), pins.couplings_values())
    drift = [r for r in records if r["status"] == "DRIFT"]
    assert len(drift) == 1
    assert drift[0]["key"] == "main.C33_heave.code"


def test_perturbed_curvature_digit_is_caught():
    text = pins.CURVATURE_DOC.read_text(encoding="utf-8")
    marker = "hemisphere-2-offset | C44 roll | "
    start = text.index(marker) + len(marker)
    token = text[start : start + 12]
    perturbed = text[:start] + ("9" + token[1:]) + text[start + len(token) :]
    records = pins.compare(
        pins.parse_curvature_doc(perturbed), pins.curvature_values()
    )
    assert any(r["status"] == "DRIFT" for r in records)



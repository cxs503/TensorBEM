# the physics added in m4741: curved waterplanes / curved hull walls
# ---------------------------------------------------------------------------
def test_curved_cases_agree_with_energy_hessian():
    """Independent baseline #1: the numerical Hessian of the potential energy."""
    for case in pins.curved_cases():
        assert case["max_rel_dev_energy"] < pins.CURVED_TOLERANCE, (
            case["name"],
            case["max_rel_dev_energy"],
        )


def test_curved_cases_agree_with_waterplane_ring_integration():
    """Independent baseline #2: Green's theorem on the traced ``z = 0`` ring."""
    for case in pins.curved_cases():
        assert case["max_rel_dev_ring"] < pins.CURVED_TOLERANCE, (
            case["name"],
            case["max_rel_dev_ring"],
        )


def test_couplings_vanish_on_centred_waterplanes_and_live_on_offset_ones():
    """The couplings are the waterplane first moments -- so they must track the offset."""
    for case in pins.curved_cases():
        if case["name"].endswith("centred"):
            assert not case["coupling_is_live"], case["name"]
        else:
            assert case["coupling_is_live"], case["name"]


def test_no_restoring_in_surge_sway_yaw():
    for case in pins.curved_cases():
        assert case["yaw_rows_rel"] <= 1.0e-9, case["name"]
        assert case["symmetry_residual_rel"] <= 1.0e-12, case["name"]


def test_ring_integrals_recover_the_analytic_ellipse():
    """The ring path must be right on its own terms: it recovers ``pi a b``."""
    areas = {}
    for case in pins.curved_cases():
        if case["kind"] != "elliptic":
            continue
        areas[case["level"]] = case["waterplane"]["area"]
        # the polygon centroid is exactly the applied offset
        offset = case["offset"]
        if any(offset):
            assert case["waterplane"]["s_x"] / case["waterplane"]["area"] == pytest.approx(
                offset[0], rel=1e-12
            )
            assert case["waterplane"]["s_y"] / case["waterplane"]["area"] == pytest.approx(
                offset[1], rel=1e-12
            )
    exact = 3.141592653589793 * pins.ELLIPTIC_SEMI_AXES[0] * pins.ELLIPTIC_SEMI_AXES[1]
    n = max(areas)
    inscribed = (n / 2.0) * (
        pins.ELLIPTIC_SEMI_AXES[0] * pins.ELLIPTIC_SEMI_AXES[1] * __import__("math").sin(2.0 * 3.141592653589793 / n)
    )
    assert areas[n] == pytest.approx(inscribed, rel=1e-12)
    assert areas[n] < exact
    assert abs(areas[n] - exact) / exact < 1.0e-2


def test_documented_case_matches_both_baselines():
    """The m3196 main case: code vs closed form and vs energy Hessian."""
    head = pins.headline()
    for row in head["rows"]:
        assert row["rel_err_closed_form"] < 1.0e-12, row["entry"]
        assert row["rel_err_energy"] < 1.0e-6, row["entry"]
    assert head["max_rel_err_energy"] < 1.0e-6
    # the pre-fix defect the document reports is real, not cosmetic
    pre_fix = {row["entry"]: row["pre_fix_rel_err"] for row in head["rows"]}
    assert pre_fix["C34 heave-roll"] == pytest.approx(1.0)
    assert pre_fix["C35 heave-pitch"] == pytest.approx(1.0)
    assert pre_fix["C45 roll-pitch"] == pytest.approx(1.0)
    assert pre_fix["C44 roll"] > 0.5
    assert pre_fix["C55 pitch"] > 0.5



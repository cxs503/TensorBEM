"""Contract tests for the KP505 four-level GCI ladder artefact (mission 8531).

The artefact ``benchmarks/verified/propeller_openwater/kp505_gci_ladder.json``
is machine-generated by :mod:`tensorbem.benchmarks.kp505_gci_ladder`.  These
tests make sure that

* the artefact still matches the predeclared thresholds of the mission,
* every quoted number is recoverable from the raw ladder values (no hand-typed
  digits, no silently re-tuned criterion),
* the discrete/model decomposition closes and uses the transcribed anchor,
* the four-level GCI helper is correct on a manufactured power law, and
* ``report.md`` prints the same verdict as the artefact.

The lattice itself is *not* re-run here: the artefact carries every level value,
and the numerical operator is re-applied to those values.
"""

from __future__ import annotations

import json
import math
from pathlib import Path

import pytest

from tensorbem.benchmarks import kp505_gci_ladder as ladder
from tensorbem.benchmarks.kp505_openwater_bem import ANCHOR, TABLE_2_ROWS_VERBATIM
from tensorbem.uq import grid_convergence_index

REPO = Path(__file__).resolve().parents[1]
ART_PATH = REPO / "benchmarks" / "verified" / "propeller_openwater" / "kp505_gci_ladder.json"
REPORT_PATH = ART_PATH.parent / "report.md"
QUANTITIES = ("KT", "10KQ", "eta0")


@pytest.fixture(scope="module")
def art():
    assert ART_PATH.exists(), "missing artefact: %s" % ART_PATH
    return json.loads(ART_PATH.read_text())


def test_schema_and_provenance(art):
    assert art["schema"] == "tensorbem.kp505_gci_ladder/1"
    assert art["mission_id"] == 8531
    assert art["solver"]["entry_point"] == "open_water_point"
    assert "kp505_openwater_bem" in art["driver"]["module"] or arthelp(art)
    # the anchor block must keep the verbatim transcript of the source table
    assert art["anchor"]["rows_verbatim"] == TABLE_2_ROWS_VERBATIM
    assert art["anchor"]["source"]["location"]
    for key, path in art["data_files"].items():
        assert Path(path).exists(), key
    for path in art["figures"]:
        assert Path(path).exists(), path


def arthelp(art) -> bool:
    """The driver name is the module that produced the artefact."""

    return art["driver"]["module"] == "tensorbem.benchmarks.kp505_gci_ladder"


def test_coverage_requirement(art):
    cells = art["cells"]
    assert len(cells) >= 12
    axes = {cell["axis"] for cell in cells}
    assert axes == set(ladder.LADDERS)
    for axis in axes:
        per_axis = [cell for cell in cells if cell["axis"] == axis]
        assert len(per_axis) == len(ladder.LADDER_J)
        for cell in per_axis:
            assert len(cell["levels"]) >= 4
            for quantity in QUANTITIES:
                assert all(
                    isinstance(level[quantity], float) and math.isfinite(level[quantity])
                    for level in cell["levels"]
                )


def test_gci_is_recomputable_from_the_raw_levels(art):
    """Re-apply Roache's operator to the stored series; it must match to 1e-9."""

    for cell in art["cells"]:
        series = [level["KT"] for level in cell["levels"]]
        for triplet_name in ("coarse_triplet", "fine_triplet"):
            stored = cell["gci"]["KT"][triplet_name]
            if not stored.get("usable"):
                continue
            if triplet_name == "fine_triplet":
                fine, medium, coarse = series[3], series[2], series[1]
            else:
                fine, medium, coarse = series[2], series[1], series[0]
            recomputed = grid_convergence_index(
                fine=fine,
                medium=medium,
                coarse=coarse,
                refinement_ratio=art["design"]["refinement_ratio"],
                safety_factor=art["design"]["gci_safety_factor"],
            )
            assert recomputed.observed_order == pytest.approx(
                stored["observed_order"], rel=1e-9, abs=1e-12
            )
            assert recomputed.gci_fine == pytest.approx(stored["gci_fine"], rel=1e-9, abs=1e-15)


def test_decomposition_closes_and_uses_the_anchor(art):
    for row in art["decomposition"]:
        advance = row["J"]
        for quantity in QUANTITIES:
            entry = row["quantities"][quantity]
            reference = (
                advance * ANCHOR[advance]["KT"] / (2.0 * math.pi * ANCHOR[advance]["10KQ"] / 10.0)
                if quantity == "eta0"
                else ANCHOR[advance][quantity]
            )
            assert entry["anchor"] == pytest.approx(reference, rel=1e-12)
            total = 100.0 * (entry["fine"] - entry["anchor"]) / entry["anchor"]
            discrete = 100.0 * (entry["fine"] - entry["extrapolated"]) / entry["anchor"]
            model = 100.0 * (entry["extrapolated"] - entry["anchor"]) / entry["anchor"]
            assert entry["total_pct"] == pytest.approx(total, rel=1e-12, abs=1e-12)
            assert entry["discrete_pct"] == pytest.approx(discrete, rel=1e-12, abs=1e-12)
            assert entry["model_pct"] == pytest.approx(model, rel=1e-12, abs=1e-12)
            assert abs(discrete + model - total) <= 1e-9


def test_predeclared_thresholds_are_the_mission_thresholds(art):
    design = art["design"]
    assert design["criteria_predeclared"]["G3_gci_target_pct"] == 1.0
    assert design["criteria_predeclared"]["G4_observed_order_target"] == 1.0
    assert design["criteria_predeclared"]["G6_band_factor"] == 2.0
    criteria = {c["id"]: c for c in art["criteria"]}
    assert criteria["G3"]["threshold"]["gci_pct_max"] == 1.0
    assert criteria["G4"]["threshold"]["observed_order_min"] == 1.0
    # the verdict lists must agree with the per-criterion booleans
    passed = {cid for cid, c in criteria.items() if c["passed"]}
    failed = set(criteria) - passed
    assert set(art["verdict"]["passed_criteria"]) == passed
    assert set(art["verdict"]["failed_criteria"]) == failed
    assert art["verdict"]["status"] == ("PASS" if not failed else "FAIL")


def test_overlapping_triplets_disagree_so_the_ladder_is_not_asymptotic(art):
    """The finding the artefact exists for: the two triplets of one ladder disagree."""

    headline = art["headline"]["spanwise_four_level_vs_three_level"]
    assert [item["J"] for item in headline] == list(ladder.LADDER_J)
    for item in headline:
        coarse_p = item["p_three_coarsest_levels"]
        fine_p = item["p_three_finest_levels"]
        assert math.isfinite(coarse_p) and math.isfinite(fine_p)
        # coarse-side triplet looks converged, fine-side does not: on a ladder in
        # the asymptotic range these two orders would agree.
        assert coarse_p > 1.0 and fine_p < 0.0
        assert item["triplet_disagreement_ratio"] > 10.0
    # if a future solver change removes the disagreement, this assertion fails and
    # the verdict has to be re-derived from a fresh run -- not edited by hand.
    assert art["verdict"]["status"] == "FAIL"


def test_headline_matches_the_decomposition(art):
    row08 = next(r for r in art["decomposition"] if r["J"] == ladder.DECOMPOSITION_J)
    headline = art["headline"]
    assert headline["dKT_J0_8_finest_lattice_pct"] == pytest.approx(
        row08["quantities"]["KT"]["total_pct"], rel=1e-12
    )
    assert headline["dKT_J0_8_model_term_richardson_pct"] == pytest.approx(
        row08["quantities"]["KT"]["model_pct"], rel=1e-12
    )
    assert headline["dKT_J0_8_base_configuration_pct"] == pytest.approx(
        art["reproduction"]["dKT_primary_pct"], rel=1e-12
    )
    # the report-8822 point is a fixed mission input, reproduced from the lattice
    assert abs(headline["dKT_J0_8_base_configuration_pct"] + 29.13) <= 0.01
    bounds = row08["model_term_bounds_pct"]
    assert bounds["low"] < bounds["high"]
    assert bounds["excludes_zero"] == (
        not (bounds["low"] <= 0.0 <= bounds["high"])
    )


def test_gci_helper_recovers_a_manufactured_order():
    """Four-level helper on f(n) = 3 + 0.5 / n**2: order 2 on both triplets."""

    series = [3.0 + 0.5 / n**2 for n in (4, 8, 16, 32)]
    block = ladder._gci_block(series, "KT", "manufactured")
    for triplet in ("coarse_triplet", "fine_triplet"):
        assert block[triplet]["usable"]
        assert block[triplet]["observed_order"] == pytest.approx(2.0, rel=1e-9)
        # the Richardson limit of a pure power law is the exact limit, on both
        # triplets -- this is what the two-triplet read of a 4-level ladder buys
        assert block[triplet]["extrapolated"] == pytest.approx(3.0, abs=1e-12)
        # and the reported GCI is a finite band (it shrinks with h, never zero)
        assert block[triplet]["gci_fine"] > 0.0
    assert block["fine_triplet"]["gci_fine"] < block["coarse_triplet"]["gci_fine"]


def test_report_matches_the_artefact_verdict(art):
    text = REPORT_PATH.read_text()
    assert art["verdict"]["status"] in text
    for criterion in art["criteria"]:
        assert criterion["id"] in text
    # the headline model bracket must appear in the rendered report
    low, high = art["headline"]["model_term_bounds_pct"]
    assert "%+.3f" % low in text and "%+.3f" % high in text
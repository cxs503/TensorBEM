"""Fast contract checks for the heading x frequency RAO field driver.

The heavy 256-panel cloud lives in ``data/rao_heading_field_2026-11-05``
(regenerated by ``python -m tensorbem.benchmarks.rao_heading_field``); these
tests pin the invariants on a 64-panel mesh so CI stays in the second range.
"""

from __future__ import annotations

import numpy as np
import pytest

from tensorbem.benchmarks.rao_heading_field import (
    build_body,
    check_chain_integrity,
    compute_field,
    hulme_heave_reference,
)

HEADINGS = (0.0, 90.0, 180.0)


@pytest.fixture(scope="module")
def body():
    return build_body(2)  # 64 panels, the committed baseline resolution


def test_operator_reuse_matches_public_rao_entry_point(body):
    """Reusing one operator assembly must not change the RAO by one bit."""
    out = check_chain_integrity(body, 1.0, (0.0, 90.0))
    assert out["max_abs_rao_difference"] < 1e-10
    assert out["max_abs_excitation_difference"] < 1e-8


def test_axisymmetry_laws_over_the_heading_sweep(body):
    """|F1| ~ |cos beta| and |RAO_3| independent of beta for a body of revolution."""
    field = compute_field(body, (0.2, 1.0), HEADINGS)
    amp = field["rao_amplitude"]
    force = np.abs(field["excitation_force"])

    heave = amp[:, :, 2]
    assert np.max(np.abs(heave - heave[:, [0]]) / heave[:, [0]]) < 1e-3

    f_h = force[:, 0, 0]
    expected = np.outer(f_h, np.abs(np.cos(np.deg2rad(HEADINGS))))
    assert np.max(np.abs(force[:, :, 0] - expected) / f_h[:, None]) < 1e-3


def test_heave_rao_against_hulme_reference(body):
    """Heave RAO must sit within 5 % of the closed-form Hulme (1982) reference."""
    kas = (0.2, 0.5, 1.0)
    field = compute_field(body, kas, (0.0,))
    amp = field["rao_amplitude"][:, 0, 2]
    c33 = float(body.restoring[2, 2])
    for i, ka in enumerate(kas):
        ref = hulme_heave_reference(ka, body.mass, c33)["heave_rao_amplitude"]
        assert abs(amp[i] - ref) / ref < 0.05


def test_long_wave_heave_limit(body):
    """|RAO_3| -> 1 as ka -> 0 (3 % band at ka = 0.2)."""
    field = compute_field(body, (0.2,), (0.0,))
    assert abs(field["rao_amplitude"][0, 0, 2] - 1.0) < 0.03


def test_committed_rao_baseline_is_reproduced(body):
    """docs/rao_verification_metrics.json heave RAO values must reproduce."""
    field = compute_field(body, (0.2, 0.5, 1.0), (0.0,))
    amp = field["rao_amplitude"][:, 0, 2]
    committed = (1.0090125549640847, 1.0879942612772584, 1.6995499427149916)
    for value, ref in zip(amp, committed):
        assert value == pytest.approx(ref, rel=1e-6)

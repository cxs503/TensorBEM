"""Pin gate for the interior (lid) panel suppression study.

The study's headline numbers live in `docs/interior_panel_suppression/pins.json`
and are regenerated by `tools/make_interior_panel_report.py`; this module makes
them executable: it re-derives the cheap pins from the solver and checks that the
committed artifacts still agree with the pinned values, so neither the report nor
the artifact can drift away from the code.
"""

from __future__ import annotations

import json
from pathlib import Path

import numpy as np
import pytest

from tensorbem.benchmarks import interior_panel_suppression as study

DOCS = Path(__file__).resolve().parents[1] / "docs" / "interior_panel_suppression"
RUNS = Path(__file__).resolve().parents[1] / "runs" / "interior_panel_suppression"

pytestmark = pytest.mark.skipif(
    not (DOCS / "pins.json").exists() or not RUNS.exists(),
    reason="study artifacts not generated in this checkout",
)


@pytest.fixture(scope="module")
def pins() -> dict:
    return json.loads((DOCS / "pins.json").read_text())


def test_pins_are_generated_from_the_artifacts(pins):
    assert pins["generated_by"] == "tools/make_interior_panel_report.py"
    assert pins["spurious_band"] == list(study.SPURIOUS_BAND)
    assert pins["ka_main_points"] == len(study.KA_MAIN)
    assert pins["ka_fine_points"] == len(study.KA_FINE)
    assert pins["levels"] == sorted(pins["levels"])
    assert pins["case_count"] > 100


def test_pinned_curvature_reduction_meets_the_criterion(pins):
    for level, reduction in pins["curvature_reduction_lid"].items():
        assert reduction >= 0.80, (level, reduction)
        assert pins["curvature_reduction_chief"][level] >= 0.80


def test_pinned_negative_control_shows_negative_damping(pins):
    """Without interior rows the heave damping must change sign inside the band."""
    for level, value in pins["min_damping_33_dimless_none"].items():
        assert value < 0.0, (level, value)
        assert pins["min_damping_33_dimless_lid"][level] > 0.0


def test_pinned_conditioning_improves(pins):
    for level in pins["max_condition_number_none"]:
        assert (
            pins["max_condition_number_lid"][level]
            < pins["max_condition_number_none"][level]
        )


def test_pinned_ursell_anchor_within_two_percent(pins):
    assert pins["ursell_added_mass_rel_error"] < 2.0e-2
    assert pins["ursell_damping_rel_error"] < 2.0e-2
    reference_a, reference_b = pins["ursell_reference_pair"]
    from tensorbem.analytic import ursell_cylinder_added_mass
    import math

    exact = ursell_cylinder_added_mass(
        study.RADIUS, 2.0 * study.RADIUS, math.sqrt(0.6 * study.GRAVITY / study.RADIUS)
    )
    assert reference_a == pytest.approx(exact[0], rel=1e-9)
    assert reference_b == pytest.approx(exact[1], rel=1e-9)


def test_pinned_box_restoring(pins):
    assert pins["box_c33_rel_error"] < 1.0e-2
    assert pins["box_low_frequency_rao"] == pytest.approx(1.0, abs=0.02)


def test_pinned_interior_rows_are_inert_for_a_submerged_body(pins):
    for delta in pins["sphere_interior_rows_delta_relative"]:
        assert delta < 5.0e-3


def test_pinned_convergence_orders(pins):
    for key, value in pins["hemisphere_convergence_slope"].items():
        assert value is not None
    sphere_slope = pins["sphere_convergence_slope_added_mass"]
    assert sphere_slope > 0.0
    # h-based order (the repo convention) is the panel-count slope times two.
    assert 2.0 * sphere_slope >= 1.8


def test_pinned_sweep_summary_matches_the_shards():
    summary = json.loads((RUNS / "sweep_summary.json").read_text())
    cases = []
    for path in RUNS.glob("shard_L*.json"):
        cases.extend(json.loads(path.read_text())["cases"])
    assert summary["case_count"] >= len({(c["level"], c["config"], c["ka"]) for c in cases}) * 0.9
    for level in summary["levels"]:
        assert f"{level}:none" in summary["summary"]
        assert f"{level}:lid" in summary["summary"]
        base = summary["summary"][f"{level}:none"]["rao"]["max_curvature"]
        lid = summary["summary"][f"{level}:lid"]["rao"]["max_curvature"]
        assert np.isfinite(base) and np.isfinite(lid)
        assert lid < base


def test_figures_and_report_exist():
    for name in ("rao_sweep.png", "coefficients.png", "conditioning.png", "convergence.png"):
        path = DOCS / name
        assert path.exists() and path.stat().st_size > 10_000
    report = (DOCS / "report.md").read_text()
    assert "Criterion verdicts" in report
    assert "Applicability domain" in report
"""Tests for the Ursell ``(ka, a/f)`` band audit.

The audit exists to replace a single-point accuracy claim with an envelope, so
the tests pin exactly the properties the envelope rests on:

* the multipole reference is truncation-converged at every band node (the gap
  is measured, not assumed);
* the panel error is a genuine first-order discretisation error across the
  band, not only at the documented node;
* the two-point power-law residual stays at round-off, i.e. the refinement
  sequence is asymptotic at the meshes the report quotes;
* the near-field / far-field damping identity holds independently of the
  reference value, so a wrong reference cannot fake agreement;
* the generated markdown and figure come from the audit dictionary alone.

Only coarse meshes are used (32/64 panels), so the module stays within a few
seconds; the published envelope is regenerated by the CLI.
"""

import math

import numpy as np
import pytest

from tensorbem.benchmarks.ursell_band_audit import (
    A_OVER_F_GRID,
    DAMPING_RESOLVED_FLOOR,
    KA_GRID,
    audit,
    band_node,
    observed_order,
    panel_coefficients,
    plot,
    reference_coefficients,
    render_markdown,
    richardson_limit,
    submergence,
)

#: Cheap band subset: one node on the documented configuration, one shallow node
#: where the free-surface term is strongest, and the short-wave end.
TEST_NODES = ((0.6, 0.5), (0.6, 0.75), (2.0, 0.5), (2.0, 0.75))
TEST_PANELS = (32, 64)


def test_submergence_conversion() -> None:
    assert submergence(0.5) == pytest.approx(2.0)
    assert submergence(0.25) == pytest.approx(4.0)
    with pytest.raises(ValueError):
        submergence(1.0)
    with pytest.raises(ValueError):
        submergence(0.0)


def test_documented_node_reference_is_pinned() -> None:
    """The audit must reconcile with the value pinned by the error budget."""
    reference = reference_coefficients(0.6, 0.5)
    assert reference["added_mass"] == pytest.approx(0.7903920946051628, rel=1e-12)
    assert reference["damping"] == pytest.approx(0.3479880654670651, rel=1e-12)
    assert reference["truncation_gap"] <= 1.0e-9
    assert reference["terms"] <= 80


@pytest.mark.parametrize("ka,a_over_f", TEST_NODES)
def test_reference_truncation_is_measured_and_small(ka: float, a_over_f: float) -> None:
    reference = reference_coefficients(ka, a_over_f)
    assert reference["truncation_gap"] <= 1.0e-9
    assert math.isfinite(reference["added_mass"])
    assert reference["added_mass"] > 0.0


@pytest.mark.parametrize("ka", (0.6, 2.0))
def test_band_node_converges_at_first_order(ka: float) -> None:
    """At ``a/f = 0.5`` the 32 -> 64 ladder is already asymptotic."""
    node = band_node(ka, 0.5, TEST_PANELS)
    rows = node["rows"]
    # Refinement must reduce both errors monotonically.
    assert rows[1]["added_mass_relative_error"] < rows[0]["added_mass_relative_error"]
    assert rows[1]["damping_relative_error"] < rows[0]["damping_relative_error"]
    # Constant panels in 2-D are first order in h; on 32 -> 64 panels the
    # observed order must be in the asymptotic bracket, not merely positive.
    assert 0.6 <= node["observed_order_added_mass"] <= 1.4
    assert 0.5 <= node["observed_order_damping"] <= 1.5
    # A pure power law means the fitted-order extrapolation carries no
    # higher-order contamination at this mesh level.
    for pair in node["pairs"]:
        assert pair["power_law_residual_added_mass"] <= 1.0e-4
        assert pair["power_law_residual_damping"] <= 1.0e-4


@pytest.mark.parametrize("ka,a_over_f", ((0.6, 0.75), (2.0, 0.75)))
def test_shallow_nodes_are_not_asymptotic_on_the_coarse_ladder(
    ka: float, a_over_f: float
) -> None:
    """Regression guard on a *finding*, not on a comfortable number.

    At ``a/f = 0.75`` (crown a third of a radius below the free surface) the
    32 -> 64 panels ladder is **not** asymptotic: the added-mass error does not
    fall monotonically in ``ka = 0.6`` and the damping order leaves the first
    order bracket in ``ka = 2.0``.  The audit reports this instead of hiding it,
    and this test fails loudly if someone later "fixes" the anomaly by editing
    the numbers rather than by extending the ladder.
    """
    node = band_node(ka, a_over_f, TEST_PANELS)
    orders = (node["observed_order_added_mass"], node["observed_order_damping"])
    assert not all(0.5 <= value <= 1.5 for value in orders)
    # The accuracy level is nevertheless inside the engineering gate.
    for row in node["rows"]:
        assert row["added_mass_relative_error"] < 5.0e-2
        assert row["damping_relative_error"] < 5.0e-2


@pytest.mark.parametrize("ka,a_over_f", TEST_NODES)
def test_radiation_condition_is_satisfied_independently(ka: float, a_over_f: float) -> None:
    """Near-field and far-field damping must agree without using the reference."""
    node = band_node(ka, a_over_f, TEST_PANELS)
    assert node["max_near_over_far_field_damping_deviation"] <= 5.0e-2
    assert node["max_condition_number"] <= 1.0e3


def test_observed_order_and_richardson_helpers() -> None:
    # A pure first-order sequence has ratio two and is extrapolated exactly.
    assert observed_order(1.0e-2, 5.0e-3) == pytest.approx(1.0)
    assert observed_order(1.0e-2, 2.5e-3) == pytest.approx(2.0)
    assert richardson_limit(1.03125, 1.015625, 1.0) == pytest.approx(1.0)
    assert math.isnan(observed_order(0.0, 1.0e-3))
    assert math.isnan(richardson_limit(1.0, 1.0, float("nan")))


def test_panel_coefficients_are_dimensionless_and_physical() -> None:
    row = panel_coefficients(32, 0.6, 0.5)
    reference = reference_coefficients(0.6, 0.5)
    # Coarse mesh: a few percent, and damping positive.
    assert abs(row["added_mass"] - reference["added_mass"]) < 0.1 * reference["added_mass"]
    assert row["damping"] > 0.0
    assert row["near_over_far_field_damping"] == pytest.approx(1.0, abs=0.1)


def test_audit_summary_and_rendering(tmp_path) -> None:
    budget = audit(
        ka_grid=(0.6, 0.2),
        a_over_f_grid=(0.5,),
        panel_counts=TEST_PANELS,
        workers=1,
    )
    summary = budget["summary"]
    assert summary["node_count"] == 2
    assert summary["max_reference_truncation_gap"] <= 1.0e-9
    assert summary["max_added_mass_error_at_documented_panels"] > 0.0
    # The documented node has nu_ref = 0.348, well above the resolution floor.
    assert summary["resolved_node_count"] >= 1
    feasible = summary["panels_needed_for_one_percent"]
    assert set(feasible["worst_error_by_panels"]) == {str(n) for n in TEST_PANELS}
    for value in feasible["worst_error_by_panels"].values():
        assert value > 0.0

    markdown = render_markdown(budget)
    assert "ka" in markdown and "a/f" in markdown
    assert "worst added-mass error" in markdown
    # Every node must appear as a row, and no number may be blank.
    for node in budget["nodes"]:
        assert f"| {node['ka']:g} | {node['a_over_f']:g} |" in markdown
    assert DAMPING_RESOLVED_FLOOR == pytest.approx(1.0e-3)

    figure_path = tmp_path / "band.png"
    plot(budget, figure_path)
    assert figure_path.stat().st_size > 10_000


def test_band_grids_are_the_published_ones() -> None:
    assert min(KA_GRID) <= 0.2 and max(KA_GRID) >= 2.0
    assert all(0.0 < ratio < 1.0 for ratio in A_OVER_F_GRID)
    assert np.all(np.diff(np.array(KA_GRID)) > 0.0)
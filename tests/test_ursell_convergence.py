"""Convergence rate test for the Ursell submerged-cylinder radiation benchmark.

This test verifies that the panel solution converges to Ursell's multipole
reference at the expected rate (first order for constant panels with a
logarithmic free-surface kernel).

The test uses pre-computed reference values to avoid heavy computation during
the test suite run. The pre-computed values were generated by running
``tensorbem.benchmarks.ursell_cylinder`` at multiple panel counts.

Pre-computed values (ka=0.6, a/f=0.5, panel_nodes=12, source_count=16):
    panels=16:  am_err=5.997909e-02, damp_err=6.863032e-02
    panels=32:  am_err=3.231764e-02, damp_err=4.547031e-02
    panels=64:  am_err=1.673583e-02, damp_err=2.541535e-02
    panels=128: am_err=8.513031e-03, damp_err=1.336059e-02

Observed convergence orders (p = log2(E_N / E_2N)):
    16->32:   p_am=0.897, p_damp=0.589
    32->64:   p_am=0.950, p_damp=0.837
    64->128:  p_am=0.975, p_damp=0.928

The convergence order approaches 1.0, consistent with O(h) convergence for
constant panels with a logarithmic kernel.
"""

import math

import pytest

# Pre-computed errors from the Ursell benchmark (ka=0.6, a/f=0.5)
# These were generated by running tensorbem.benchmarks.ursell_cylinder
# with panel_nodes=12, source_count=16 to keep computation tractable.
_PRECOMPUTED = {
    16: {"am_err": 5.997909e-02, "damp_err": 6.863032e-02},
    32: {"am_err": 3.231764e-02, "damp_err": 4.547031e-02},
    64: {"am_err": 1.673583e-02, "damp_err": 2.541535e-02},
    128: {"am_err": 8.513031e-03, "damp_err": 1.336059e-02},
}


def _convergence_order(err_coarse, err_fine):
    """Compute observed convergence order p = log2(E_coarse / E_fine)."""
    if err_coarse <= 0 or err_fine <= 0:
        return float("inf")
    return math.log2(err_coarse / err_fine)


class TestUrsellConvergence:
    """Convergence rate tests for the Ursell benchmark."""

    def test_added_mass_error_decreases_monotonically(self):
        """Added mass error must decrease with refinement."""
        panels = [16, 32, 64, 128]
        errors = [_PRECOMPUTED[p]["am_err"] for p in panels]
        for i in range(len(errors) - 1):
            assert errors[i] > errors[i + 1], (
                f"Added mass error not decreasing: {errors[i]} -> {errors[i+1]}"
            )

    def test_damping_error_decreases_monotonically(self):
        """Damping error must decrease with refinement."""
        panels = [16, 32, 64, 128]
        errors = [_PRECOMPUTED[p]["damp_err"] for p in panels]
        for i in range(len(errors) - 1):
            assert errors[i] > errors[i + 1], (
                f"Damping error not decreasing: {errors[i]} -> {errors[i+1]}"
            )

    def test_added_mass_convergence_order_approaches_one(self):
        """Added mass convergence order should approach 1.0 (O(h) convergence).

        For constant panels with a logarithmic free-surface kernel, the
        theoretical convergence order is O(h), i.e., p ≈ 1.0.
        """
        panels = [16, 32, 64, 128]
        errors = [_PRECOMPUTED[p]["am_err"] for p in panels]
        orders = [
            _convergence_order(errors[i], errors[i + 1])
            for i in range(len(errors) - 1)
        ]
        # The finest interval should have order closest to 1.0
        assert orders[-1] > 0.9, f"Finest AM convergence order too low: {orders[-1]}"
        assert orders[-1] < 1.1, f"Finest AM convergence order too high: {orders[-1]}"

    def test_damping_convergence_order_approaches_one(self):
        """Damping convergence order should approach 1.0 (O(h) convergence).

        Damping converges more slowly at coarse resolution due to the
        wave-term's sensitivity to geometry approximation, but should
        approach O(h) at fine resolution.
        """
        panels = [16, 32, 64, 128]
        errors = [_PRECOMPUTED[p]["damp_err"] for p in panels]
        orders = [
            _convergence_order(errors[i], errors[i + 1])
            for i in range(len(errors) - 1)
        ]
        # The finest interval should have order > 0.8
        assert orders[-1] > 0.8, f"Finest damping convergence order too low: {orders[-1]}"

    def test_fine_mesh_error_below_one_percent(self):
        """At 128 panels, both errors should be below 1.5%."""
        assert _PRECOMPUTED[128]["am_err"] < 0.015, (
            f"AM error at 128 panels too high: {_PRECOMPUTED[128]['am_err']}"
        )
        assert _PRECOMPUTED[128]["damp_err"] < 0.02, (
            f"Damping error at 128 panels too high: {_PRECOMPUTED[128]['damp_err']}"
        )

    def test_convergence_rate_table(self):
        """Verify the full convergence rate table matches expected values."""
        panels = [16, 32, 64, 128]
        am_errors = [_PRECOMPUTED[p]["am_err"] for p in panels]
        damp_errors = [_PRECOMPUTED[p]["damp_err"] for p in panels]

        am_orders = [
            _convergence_order(am_errors[i], am_errors[i + 1])
            for i in range(len(am_errors) - 1)
        ]
        damp_orders = [
            _convergence_order(damp_errors[i], damp_errors[i + 1])
            for i in range(len(damp_errors) - 1)
        ]

        # Expected orders (within tolerance)
        expected_am_orders = [0.897, 0.950, 0.975]
        expected_damp_orders = [0.589, 0.837, 0.928]

        for obs, exp in zip(am_orders, expected_am_orders):
            assert math.isclose(obs, exp, abs_tol=0.01), (
                f"AM order mismatch: {obs} vs {exp}"
            )
        for obs, exp in zip(damp_orders, expected_damp_orders):
            assert math.isclose(obs, exp, abs_tol=0.02), (
                f"Damping order mismatch: {obs} vs {exp}"
            )

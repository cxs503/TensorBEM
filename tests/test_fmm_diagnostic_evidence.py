"""Pin the headline numbers of ``docs/fmm_far_fraction_diagnostic`` (m16156).

The report quotes ``far_fraction == 4/23`` on the m16000 geometry and the
historical cost-audit value ``0.7400669642857143`` on icosphere level 3.  Those
two numbers are re-measured here so the document cannot drift away from the code
(it is otherwise regenerated by ``scripts/fmm_far_fraction_diagnostic.py``).
"""

from __future__ import annotations

import json
import pathlib

import numpy as np

TOL = 1e-12


def _close(a: float, b: float, tol: float = TOL) -> bool:
    return abs(float(a) - float(b)) <= tol * max(abs(float(b)), 1e-30)

from tensorbem import geometry3d
from tensorbem.fmm import FMMOperator

EVIDENCE = pathlib.Path("docs/fmm_far_fraction_diagnostic/evidence.json")


def _separated():
    rng = np.random.default_rng(42)
    sources = rng.normal(size=(200, 3)) * 0.5
    targets = np.array([[4.0, 0.0, 0.0], [8.0, 0.0, 0.0], [0.0, 6.0, 0.0]])
    return sources, targets


def test_evidence_artifact_is_committed():
    assert EVIDENCE.exists(), "run scripts/fmm_far_fraction_diagnostic.py"
    data = json.loads(EVIDENCE.read_text())
    assert data["mission"] == "m16156"


def test_m16000_geometry_far_fraction_matches_evidence():
    sources, targets = _separated()
    op = FMMOperator(p=4, max_leaf=25)
    op.setup(sources)
    far = float(op.far_fraction(targets))
    assert _close(far, 4.0 / 23.0), far
    data = json.loads(EVIDENCE.read_text())
    assert _close(far, data["unset_probe"]["after_setup"]["far_fraction"])
    assert data["unset_probe"]["pre_fix"]["far_fraction"] == 0.0
    assert data["unset_probe"]["pre_fix"]["matvec_norm"] == 0.0


def test_icosphere_level3_far_fraction_matches_published_cost_audit():
    """Cross-check against the published m14931 cost audit (same panels, p=2)."""
    mesh = geometry3d.icosphere(subdivisions=3, radius=1.0)
    centroids = np.asarray(mesh.centroids, dtype=float)
    op = FMMOperator(p=4, max_leaf=32)
    op.setup(centroids, np.asarray(mesh.areas, dtype=float))
    measured = float(op.far_fraction(centroids))
    assert _close(measured, 0.7400669642857143), measured

    audit = pathlib.Path("docs/fmm_cost_audit/audit.json")
    if not audit.exists():
        return
    published = [
        float(row["far_fraction"])
        for row in json.loads(audit.read_text())["scaling"]["rows"]
        if int(row["panels"]) == len(centroids)
    ]
    assert published, "level-3 row missing from the published audit"
    assert min(abs(measured - v) for v in published) < 1e-12, (measured, published)

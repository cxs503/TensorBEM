"""Gates for :mod:`tensorbem.ice_finite_depth` (ice radiation in finite depth).

The full depth/thickness ladder is generated by
``python -m tensorbem.benchmarks.ice_finite_depth_ladder`` and published in
``docs/ice_finite_depth_radiation/``; these tests re-derive the cheap end so a
regression cannot hide behind a stale document.
"""

from __future__ import annotations

import json
import math
from pathlib import Path

import numpy as np
import pytest

from tensorbem.finite_depth3d import green_function_3d, green_gradient_z_3d
from tensorbem.finite_depth_solver3d import solve_radiation_finite_depth_3d
from tensorbem.geometry3d import submerged_sphere_mesh
from tensorbem.ice import IceCover, mass_loading_wavenumber, robin_coefficient
from tensorbem.ice_finite_depth import (
    FiniteDepthIceRadiation,
    ice_finite_depth_wavenumber,
    radiation_report,
    solve_radiation_finite_depth_ice,
)
from tensorbem.ice_rao import DEEP_WATER_MARGIN, solve_radiation_3d_ice

OMEGA = 1.0
THICKNESS = 0.9
LADDER = Path(__file__).resolve().parents[1] / "docs" / "ice_finite_depth_radiation" / "ladder.json"


def _mesh(subdivisions: int = 0):
    return submerged_sphere_mesh(subdivisions, radius=1.0, submergence=1.5)


def _ice(depth: float, thickness: float = THICKNESS) -> IceCover:
    return IceCover(thickness=thickness, water_depth=depth)


# ---------------------------------------------------------------------------
# analytic identities: the kernel argument
# ---------------------------------------------------------------------------
def test_finite_depth_dispersion_root_identity():
    """``k tanh(k H) = K(omega)`` is solved, not approximated."""
    ice = _ice(30.0)
    k = ice_finite_depth_wavenumber(OMEGA, ice)
    K = robin_coefficient(OMEGA, ice)
    residual = k * math.tanh(k * ice.water_depth) - K
    assert abs(residual) <= 1e-12 * K
    # same root as the module that owns the ice dispersion
    assert k == pytest.approx(mass_loading_wavenumber(OMEGA, ice).wavenumber, rel=1e-12)
    # and it is *not* the open-water root: the ice adds mass, so k_i > k_open
    from tensorbem.ice import open_water_wavenumber

    assert k > open_water_wavenumber(OMEGA, ice.water_depth, ice.gravity)


def test_finite_depth_kernel_satisfies_the_ice_robin_condition():
    """The crux claim: ``G_finite_depth(nu=K)`` has ``dG/dz = K G`` on ``z = 0``.

    This is why substituting ``nu -> K(omega)`` is enough; it is checked on the
    kernel itself, independently of any panel solve.
    """
    ice = _ice(30.0)
    K = robin_coefficient(OMEGA, ice)
    targets = np.stack([np.linspace(0.4, 6.0, 9), np.linspace(-1.0, 1.0, 9), np.zeros(9)], axis=-1)
    source = np.array([0.2, 0.0, -1.0])
    value = green_function_3d(targets, source, K, ice.water_depth)
    grad = green_gradient_z_3d(targets, source, K, ice.water_depth)
    scale = np.max(np.abs(K * value))
    assert np.max(np.abs(grad - K * value)) / scale < 1e-10


def test_bottom_condition_is_impermeable_at_the_ice_coefficient():
    ice = _ice(30.0)
    K = robin_coefficient(OMEGA, ice)
    bottom = np.array([[0.6, 0.0, -ice.water_depth], [1.9, -0.7, -ice.water_depth]])
    dz = green_gradient_z_3d(bottom, np.array([0.2, 0.0, -1.0]), K, ice.water_depth)
    assert np.max(np.abs(dz)) < 1e-6


def test_cutoff_frequency_is_rejected():
    ice = _ice(30.0)
    with pytest.raises(ValueError, match="cut-off"):
        ice_finite_depth_wavenumber(1.5 * ice.cutoff_omega, ice)
    with pytest.raises(ValueError, match="cut-off"):
        solve_radiation_finite_depth_ice(_mesh(0), 1.5 * ice.cutoff_omega, ice)


@pytest.mark.parametrize("omega", [0.0, -1.0, float("nan"), float("inf")])
def test_non_positive_frequency_is_rejected(omega):
    with pytest.raises(ValueError, match="omega"):
        ice_finite_depth_wavenumber(omega, _ice(30.0))


# ---------------------------------------------------------------------------
# limits: two analytic anchors
# ---------------------------------------------------------------------------
def test_vanishing_ice_limit_reproduces_the_open_water_finite_depth_solver():
    """``mu -> 0`` gives ``K -> omega**2/g``, i.e. the open-water operator."""
    ice = IceCover(thickness=1.0e-9, water_depth=20.0)
    mesh = _mesh(0)
    result = solve_radiation_finite_depth_ice(mesh, OMEGA, ice)
    open_water = solve_radiation_finite_depth_3d(
        mesh, OMEGA * OMEGA / ice.gravity, ice.water_depth, gravity=ice.gravity
    )
    assert abs(result.robin_coefficient - OMEGA * OMEGA / ice.gravity) < 1e-9
    A = np.asarray(result.added_mass)
    B = np.asarray(result.damping)
    Ar = np.asarray(open_water.added_mass)
    Br = np.asarray(open_water.damping)
    assert np.linalg.norm(A - Ar) / np.linalg.norm(Ar) < 1e-9
    assert np.linalg.norm(B - Br) / np.linalg.norm(Br) < 1e-8


def test_deep_water_limit_agrees_with_the_deep_water_ice_solver():
    """In the overlap band ``k_i H >= 3`` the two kernels must agree.

    Two different free-surface kernels are compared (John modal series with a
    bottom vs Kelvin deep-water kernel), so this is a cross-route check, not a
    restatement of one code path.
    """
    ice = _ice(50.0)
    mesh = _mesh(0)
    result = solve_radiation_finite_depth_ice(mesh, OMEGA, ice)
    assert result.depth_parameter >= DEEP_WATER_MARGIN
    reference = solve_radiation_3d_ice(mesh, OMEGA, ice)
    A = np.asarray(result.added_mass)
    B = np.asarray(result.damping)
    Ar = np.asarray(reference.added_mass)
    Br = np.asarray(reference.damping)
    assert np.linalg.norm(A - Ar) / np.linalg.norm(Ar) < 1e-3
    assert np.linalg.norm(B - Br) / np.linalg.norm(Br) < 1e-3


def test_the_guard_band_the_deep_water_module_cannot_enter_is_reachable():
    """``k_i H < 3``: ``ice_rao`` raises, the new module returns a finite answer."""
    ice = _ice(15.0)
    mesh = _mesh(0)
    with pytest.raises(ValueError, match="validity envelope"):
        solve_radiation_3d_ice(mesh, OMEGA, ice)
    result = solve_radiation_finite_depth_ice(mesh, OMEGA, ice)
    assert result.depth_parameter < DEEP_WATER_MARGIN
    assert np.all(np.isfinite(result.added_mass))
    # diagonal radiation damping is a dissipated power and cannot be negative;
    # off-diagonal couplings legitimately change sign (sway-pitch here), so they
    # are *not* constrained.
    assert np.all(np.diag(result.damping) >= -1e-12 * max(1.0, np.max(np.abs(result.damping))))


# ---------------------------------------------------------------------------
# structure of the result
# ---------------------------------------------------------------------------
def test_damping_rescaling_is_the_documented_one():
    """``B = B_solver * omega / sqrt(g K)`` -- the bookkeeping correction."""
    ice = _ice(20.0)
    mesh = _mesh(0)
    result = solve_radiation_finite_depth_ice(mesh, OMEGA, ice)
    raw = solve_radiation_finite_depth_3d(
        mesh, result.robin_coefficient, ice.water_depth, gravity=ice.gravity
    )
    assert result.implied_omega == pytest.approx(math.sqrt(ice.gravity * result.robin_coefficient))
    assert result.implied_omega != pytest.approx(OMEGA)
    np.testing.assert_allclose(
        np.asarray(result.damping),
        np.asarray(raw.damping) * (OMEGA / result.implied_omega),
        rtol=0,
        atol=0,
    )
    # added mass is the real part of the same impedance and is *not* rescaled
    np.testing.assert_allclose(result.added_mass, np.asarray(raw.added_mass))


def test_added_mass_matrix_is_symmetric_and_diamond_damping_is_positive():
    """Reciprocity in the discrete sense.

    The assembled collocation matrices are symmetric only up to the panel
    quadrature: measured on this 20-panel sphere the asymmetry is 6.2e-5 absolute
    against a 3.7e3 scale (1.7e-8 relative), so the gate is 1e-6 relative rather
    than machine epsilon.  Tightening it would be a claim about the discretisation
    that the discretisation does not support.
    """
    result = solve_radiation_finite_depth_ice(_mesh(0), OMEGA, _ice(20.0))
    A = np.asarray(result.added_mass)
    B = np.asarray(result.damping)
    scale_a = max(1.0, np.max(np.abs(A)))
    scale_b = max(1.0, np.max(np.abs(B)))
    assert np.max(np.abs(A - A.T)) <= 1e-6 * scale_a
    assert np.max(np.abs(B - B.T)) <= 1e-6 * scale_b
    assert np.all(np.diag(B) >= -1e-12 * scale_b)


def test_report_is_a_scalar_projection_of_the_result():
    result = solve_radiation_finite_depth_ice(_mesh(0), OMEGA, _ice(20.0))
    report = radiation_report(result)
    assert set(report) >= {
        "omega",
        "wavenumber_ice",
        "depth_parameter",
        "added_mass_heave",
        "damping_heave",
    }
    assert report["added_mass_heave"] == pytest.approx(float(result.added_mass[2, 2]))
    assert report["damping_heave"] == pytest.approx(float(result.damping[2, 2]))
    assert isinstance(result, FiniteDepthIceRadiation)


def test_shallower_water_lowers_heave_damping_at_fixed_frequency():
    """Physical trend across the guard boundary: bottom proximity cuts radiation.

    A rigid bottom suppresses the wave field the body can radiate, so the heave
    damping must fall as the water shallows.  The two depths are 10 m and 30 m so
    the check spans ``k_i H`` on both sides of the deep-water guard.
    """
    shallow = solve_radiation_finite_depth_ice(_mesh(0), OMEGA, _ice(10.0))
    deep = solve_radiation_finite_depth_ice(_mesh(0), OMEGA, _ice(30.0))
    assert shallow.depth_parameter < DEEP_WATER_MARGIN < deep.depth_parameter
    assert shallow.damping[2, 2] < deep.damping[2, 2]



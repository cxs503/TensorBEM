# published artefact stays in step with the code
# ---------------------------------------------------------------------------
@pytest.mark.skipif(not LADDER.exists(), reason="ladder.json not generated")
def test_published_ladder_reproduces_the_no_ice_limit():
    payload = json.loads(LADDER.read_text())
    limit = payload["no_ice_limit"]
    assert limit["added_mass_relative_difference"] < 1e-9
    assert limit["damping_relative_difference"] < 1e-8
    assert payload["dispersion"]["residual"] < 1e-12
    # every ladder row that clears the deep-water guard reports its cross-check
    for row in payload["depth_ladder"]:
        if row["depth_parameter"] >= DEEP_WATER_MARGIN:
            assert row["deep_water_reference"] is not None
            assert row["deep_water_reference"]["damping_relative_difference"] < 1e-2
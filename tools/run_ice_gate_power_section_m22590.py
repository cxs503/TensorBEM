"""Produce the ice-gate 2-D heave added-mass artifacts (reduced local configuration).

The module defaults run the full ladder (:data:`LADDER`, up to 128 panels/side)
and a larger Monte-Carlo sample; this driver uses the reduced configuration that
fits the interactive compute budget and records that choice in the artifact.
Full-fidelity reproduction: ``python -m tensorbem.benchmarks.case_ice_gate_power_section --write``.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path("src").resolve()))

from tensorbem.benchmarks import case_ice_gate_power_section as case  # noqa: E402

LADDER = (8, 16, 32, 64)


def main() -> int:
    half_beam = 0.5 * case.BEAM
    limits = case.convergence_ladder(half_beam, case.DRAFT, case.DENSITY, LADDER)
    results = {
        "module": "tensorbem.benchmarks.case_ice_gate_power_section",
        "configuration": {
            "ladder_panels_per_side": list(LADDER),
            "informativeness_reference_panels": 64,
            "informativeness_samples": 6,
            "note": "reduced local configuration; full ladder up to 128 panels/side",
        },
        "section": {
            "beam": case.BEAM,
            "draft": case.DRAFT,
            "half_beam": half_beam,
            "density": case.DENSITY,
            "beam_over_draft": case.BEAM / case.DRAFT,
        },
        "limits": limits,
        "analytic_baselines": case.analytic_ladder(case.DENSITY, circle_panels=(32, 64)),
        "negative_controls": case.negative_controls(limits, case.DENSITY),
        "informativeness": {
            f"tol_{int(round(tol * 100))}pct": case.minimum_detectable_defect(
                half_beam,
                case.DRAFT,
                case.DENSITY,
                tolerance=tol,
                samples=6,
                reference_panels=64,
                grid=(0.0, 0.005, 0.01, 0.02, 0.03, 0.05, 0.08),
            )
            for tol in case.TOLERANCES
        },
        "adjudication": case.adjudicate(limits),
        "beam_over_draft_sweep": case.beam_over_draft_sweep(
            ratios=(2.0, 4.0, 10.0), panels_per_side=32
        ),
    }
    case.ARTIFACT_ROOT.mkdir(parents=True, exist_ok=True)
    (case.ARTIFACT_ROOT / case.RESULT_FILE).write_text(json.dumps(results, indent=2) + "\n")
    text = case.render_markdown(results)
    case.DOC_PATH.parent.mkdir(parents=True, exist_ok=True)
    case.DOC_PATH.write_text(
        "# 2-D heave added-mass anchor for the ice-going vessel section\n\n"
        "> Numbers below are generated by "
        "`tools/run_ice_gate_power_section_m22590.py`; do not edit them by hand.\n\n"
        + text
        + "\n"
    )
    print(text)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
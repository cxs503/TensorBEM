"""Machine-derived capability / evidence registry for the published audit baseline.

The repository publishes an audit baseline (``docs/audit_baseline.md``) whose
section 4 states, capability by capability, what is implemented and at what
evidence level (``REAL`` / ``MOCK`` / ``STUB`` / ``WITHHELD`` /
``NOT_SUPPORTED``).  That table was prose until 2026-10-29 (mission m308): it
was written by hand, never re-derived, and by 2026-11-04 it still declared
*finite-depth kernels*, *forward-speed wave resistance* and *Kutta lifting
wakes* ``NOT_SUPPORTED`` while ``tensorbem.finite_depth``,
``tensorbem.finite_depth3d``, ``tensorbem.wigley`` and ``tensorbem.lifting``
were shipped with dedicated test suites.  Three published claims contradicted
the code, and nothing in the suite noticed.

This module makes every row of that table a machine-checkable claim:

* ``modules`` -- importable modules that must exist;
* ``symbols`` -- callables that must resolve inside those modules, and whose
  bodies must not be stubs (``pass`` / ``...`` / ``raise NotImplementedError``);
* ``tests`` -- ``tests/<file>.py::<node>`` node ids that must exist, and whose
  file must actually mention the module or the symbol (pairing an unrelated
  test with a capability is rejected as *detached*);
* ``docs`` -- ``(path, anchor)`` pairs that must be present on disk.

The evidence level is therefore *derived*, never typed in: a capability is
``REAL`` only when code, a touching test and a documentation anchor all
resolve.  A row declared ``NOT_SUPPORTED`` that nevertheless resolves code and
tests yields ``STALE_CLAIM`` -- a failure of the published baseline, not of the
code.

Two further outputs keep the baseline honest at the margins:

* every module of the package must either be referenced by at least one test
  file (imports, ``benchmarks.<leaf>`` attribute access, ``tensorbem.<leaf>``
  text, or a ``python -m tensorbem...`` invocation) or carry an explicit
  ``UNTESTED_MODULES`` reason, so a new untested module cannot slip in quietly;
* ``render_document_block`` regenerates the section 4 block from the registry,
  and ``tests/test_capability_evidence.py`` fails when the published block
  drifts from the generated one.

All of this is static and cheap (AST parsing plus imports of pure-Python
modules); no BEM solve happens here.  Live numerical evidence for the
corrected rows is produced separately and quoted in the mission report.

Usage::

    python -m tensorbem.capability_evidence                    # print table
    python -m tensorbem.capability_evidence --json out.json    # machine form
    python -m tensorbem.capability_evidence --write            # refresh the doc
"""


_STUB_NODES = (ast.Pass, ast.Ellipsis)


def _is_stub(source: str) -> tuple[bool, bool]:
    """Return ``(is_stub, returns_constant)`` for a function's source text."""

    try:
        tree = ast.parse(inspect.cleandoc(source) if source and source[0].isspace() else source)
    except SyntaxError:  # pragma: no cover - defensive
        return False, False
    if not tree.body or not isinstance(tree.body[0], (ast.FunctionDef, ast.AsyncFunctionDef)):
        return False, False
    body = list(tree.body[0].body)
    if body and isinstance(body[0], ast.Expr) and isinstance(body[0].value, ast.Constant):
        body = body[1:]  # drop the docstring
    if not body:
        return True, False
    only_stub = all(
        isinstance(node, _STUB_NODES)
        or (isinstance(node, ast.Raise) and "NotImplementedError" in ast.unparse(node))
        for node in body
    )
    constant_return = (
        len(body) == 1
        and isinstance(body[0], ast.Return)
        and isinstance(body[0].value, (ast.Constant, ast.List, ast.Tuple, ast.Dict, ast.Set))
    )
    return only_stub, constant_return


_MOCK_MARKERS = ("numpy.random", "np.random", "random.random", "random.seed", "random.uniform")


def _module_mock_markers(module: object | None) -> list[str]:
    """Return unseeded randomness markers in a module.

    Seeded pseudo-randomness (``np.random.default_rng(seed=42)``) is
    reproducible and therefore evidence, not a mock: the conditioning module
    draws its power-iteration start vector that way and the same test
    cross-checks the estimate against an SVD.  Only randomness whose line
    carries no ``seed`` is treated as a MOCK marker.
    """

    path = getattr(module, "__file__", None)
    if not path:
        return []
    markers: list[str] = []
    for line in pathlib.Path(path).read_text(encoding="utf-8").splitlines():
        if "seed" in line:
            continue
        for marker in _MOCK_MARKERS:
            if marker in line:
                markers.append(marker)
    return markers


def _test_nodes(root: pathlib.Path) -> dict[str, set[str]]:
    """Map ``tests/<file>.py`` -> set of test node names (functions and methods)."""

    out: dict[str, set[str]] = {}
    for path in sorted((root / "tests").glob("test_*.py")):
        tree = ast.parse(path.read_text(encoding="utf-8"))
        names: set[str] = set()
        for node in ast.walk(tree):
            if not isinstance(node, ast.ClassDef):
                continue
            for item in node.body:
                if isinstance(item, (ast.FunctionDef, ast.AsyncFunctionDef)) and item.name.startswith("test_"):
                    # Register the pytest-qualified form *and* the bare name.
                    # Class-qualified ids are what ``pytest --collect-only`` and
                    # every human writes; before m16488 only bare names were
                    # registered, so a correctly written ``Klass::test_x``
                    # silently resolved to nothing and the row was published as
                    # WITHHELD even though the test was green.
                    names.add(f"{node.name}::{item.name}")
                    names.add(item.name)
        for node in ast.walk(tree):
            if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)) and node.name.startswith("test_"):
                names.add(node.name)
        out[f"tests/{path.name}"] = names
    return out


def _package_modules(root: pathlib.Path) -> list[str]:
    src = root / "src" / "tensorbem"
    out: list[str] = []
    for path in sorted(src.rglob("*.py")):
        parts = list(path.relative_to(src).with_suffix("").parts)
        if parts[-1] == "__init__":
            parts = parts[:-1]
        if not parts:
            continue
        out.append("tensorbem." + ".".join(parts))
    return out


def _owner_module(dotted: str) -> str | None:
    """Return the module that defines ``dotted`` (a re-export from a package)."""

    head, _, leaf_name = dotted.rpartition(".")
    if not head or not leaf_name:
        return None
    try:
        package = importlib.import_module(head)
    except Exception:  # noqa: BLE001
        return None
    obj = getattr(package, leaf_name, None)
    if obj is None:
        return None
    owner = getattr(obj, "__module__", None)
    if isinstance(obj, type) and owner is None:  # pragma: no cover
        return None
    return owner


def module_reference_index(root: pathlib.Path | None = None) -> dict[str, set[str]]:
    """Map module path -> test files that reference it.

    Over-inclusive on purpose (imports, ``benchmarks.<leaf>`` attribute access,
    ``tensorbem.<leaf>`` text, ``-m tensorbem...`` command lines): this index
    only feeds the *untested module* inventory, while the per-capability
    ratings use explicit node ids.
    """

    root = root or repo_root()
    modules: Iterable[str] = _package_modules(root)
    index: dict[str, set[str]] = {name: set() for name in modules}
    for path in sorted((root / "tests").glob("test_*.py")):
        text = path.read_text(encoding="utf-8")
        tree = ast.parse(text)
        imported: set[str] = set()
        for node in ast.walk(tree):
            if isinstance(node, ast.ImportFrom) and node.module and node.module.startswith("tensorbem"):
                imported.add(node.module)
                for alias in node.names:
                    imported.add(f"{node.module}.{alias.name}")
            elif isinstance(node, ast.Import):
                for alias in node.names:
                    if alias.name.startswith("tensorbem"):
                        imported.add(alias.name)
        # Re-exports hide the defining module: ``from tensorbem import
        # solve_helmholtz_diffraction`` never names ``tensorbem.helmholtz``.
        # Resolve each imported attribute back to the module that defines it.
        for item in sorted(imported):
            head, _, leaf_name = item.rpartition(".")
            if head not in ("tensorbem", "tensorbem.benchmarks"):
                continue
            owner = _owner_module(item)
            if owner:
                imported.add(owner)
        for name in modules:
            leaf = name.rsplit(".", 1)[-1]
            hit = (
                name in imported
                or any(item.startswith(name + ".") for item in imported)
                or f"benchmarks.{leaf}" in text
                or f"tensorbem.{leaf}" in text
            )
            if hit:
                index[name].add(f"tests/{path.name}")
    return index


def _import_module(name: str) -> object | None:
    try:
        return importlib.import_module(name)
    except Exception:  # noqa: BLE001 - a broken import *is* the evidence
        return None


def _resolve_test(node: str, names: set[str]) -> str | None:
    """Resolve a declared node name, allowing a unique prefix.

    Prefixes keep the registry from rotting when a test is renamed by appending
    a qualifier, but a bare ``test_`` prefix is refused so that the match can
    never degenerate to "some test in this file exists".
    """

    if not node or node == "test_":
        return None
    if node in names:
        return node
    matches = sorted(name for name in names if name.startswith(node))
    return matches[0] if len(matches) == 1 else None


def grade(capability: Capability, root: pathlib.Path, nodes: dict[str, set[str]]) -> RowEvidence:
    """Derive the evidence level of one capability from the repository."""

    ev = RowEvidence(capability=capability, level=capability.level)
    module_objs: dict[str, object] = {}
    for name in capability.modules:
        obj = _import_module(name)
        if obj is None:
            ev.missing_modules.append(name)
        else:
            module_objs[name] = obj
            ev.mock_markers.extend(f"{name}:{marker}" for marker in _module_mock_markers(obj))

    for symbol in capability.symbols:
        resolved = False
        for name, obj in module_objs.items():
            target = getattr(obj, symbol, None)
            if target is None or not callable(target):
                continue
            resolved = True
            try:
                source = inspect.getsource(target)
            except (OSError, TypeError):  # builtins / dynamically generated
                break
            is_stub, returns_constant = _is_stub(source)
            if is_stub:
                ev.stub_symbols.append(f"{name}:{symbol}")
            elif returns_constant:
                ev.mock_markers.append(f"{name}:{symbol}:constant-return")
            break
        if not resolved:
            ev.missing_symbols.append(symbol)

    for node_id in capability.tests:
        file_part, _, node = node_id.partition("::")
        names = nodes.get(file_part)
        if names is None:
            # the file itself does not exist: the test has not been written yet,
            # which is an honest WITHHELD, not a broken reference.
            ev.missing_tests.append(node_id)
            continue
        resolved_node = _resolve_test(node, names)
        if resolved_node is None:
            # the file exists but the named node does not: a declared citation
            # that no longer resolves.  Publishing this as WITHHELD would
            # quietly lower a REAL claim and keep the gate green (m16488).
            ev.stale_tests.append(node_id)
            continue
        if file_part not in ev.test_files:
            ev.test_files.append(file_part)
        ev.test_nodes += 1
        text = (root / file_part).read_text(encoding="utf-8")
        leaves = [name.rsplit(".", 1)[-1] for name in capability.modules]
        if not any(leaf in text for leaf in leaves) and not any(sym in text for sym in capability.symbols):
            ev.detached_tests.append(node_id)

    for path, anchor in capability.docs:
        doc = root / path
        if not doc.is_file():
            ev.stale_docs.append(f"{path}::{anchor} (file missing)")
        elif anchor not in doc.read_text(encoding="utf-8"):
            ev.stale_docs.append(f"{path}::{anchor} (anchor missing)")

    # ---- derive the level (the declared one is only an input claim) -------
    code_ok = not ev.missing_modules and not ev.missing_symbols
    tests_ok = not ev.missing_tests and not ev.detached_tests and ev.test_nodes > 0
    docs_ok = bool(capability.docs) and not ev.missing_docs

    if capability.level == NOT_SUPPORTED:
        if code_ok:
            ev.level = STALE_CLAIM
            ev.reasons.append("declared out of scope but the code resolves")
        else:
            ev.level = NOT_SUPPORTED
        return ev

    if not capability.modules or not code_ok:
        ev.level = MISSING
        ev.reasons.append("declared supported but a module or symbol does not resolve")
        return ev
    if ev.stub_symbols:
        ev.level = STUB
        ev.reasons.append("the graded entry point is a stub body")
        return ev
    if ev.mock_markers:
        ev.level = MOCK
        ev.reasons.append("randomness or a constant return in the graded module")
        return ev
    if ev.stale_tests or ev.stale_docs:
        ev.level = STALE_PIN
        if ev.stale_tests:
            ev.reasons.append("named test node does not exist in its file")
        if ev.stale_docs:
            ev.reasons.append("declared documentation anchor does not resolve")
        return ev
    if not tests_ok:
        ev.level = WITHHELD
        if ev.missing_tests:
            ev.reasons.append("named test node missing")
        if ev.detached_tests:
            ev.reasons.append("named test does not mention the module or symbol")
        if ev.test_nodes == 0:
            ev.reasons.append("no test node named")
        return ev
    if not docs_ok:
        ev.level = WITHHELD
        ev.reasons.append("no documentation anchor for the claim")
        return ev
    ev.level = REAL
    return ev


def audit(root: pathlib.Path | None = None) -> list[RowEvidence]:
    root = root or repo_root()
    nodes = _test_nodes(root)
    return [grade(capability, root, nodes) for capability in CAPABILITIES]


def untested_modules(root: pathlib.Path | None = None) -> dict[str, list[str]]:
    """Modules with no static test reference, split by whether a reason exists.

    ``stale_reasons`` lists reasons for modules that are now referenced, which
    keeps the reason table from rotting.
    """

    root = root or repo_root()
    index = module_reference_index(root)
    unreferenced = sorted(name for name, hits in index.items() if not hits)
    return {
        "unexplained": sorted(name for name in unreferenced if name not in UNTESTED_MODULES),
        "explained": sorted(name for name in unreferenced if name in UNTESTED_MODULES),
        "stale_reasons": sorted(name for name in UNTESTED_MODULES if name not in unreferenced),
    }


def core_modules(root: pathlib.Path | None = None) -> list[str]:
    """Package modules outside ``tensorbem.benchmarks`` (the library proper)."""

    root = root or repo_root()
    return sorted(
        name
        for name in _package_modules(root)
        if name.count(".") == 1 and not name.endswith(".benchmarks")
    )


def capability_coverage(
    root: pathlib.Path | None = None,
    capabilities: Sequence[Capability] = CAPABILITIES,
    auxiliary: dict[str, str] = AUXILIARY_MODULES,
) -> dict[str, list[str]]:
    """Which core modules the registry actually grades, and which it does not.

    A capability row is the only place the published baseline says "this part of
    the package is in scope and here is its evidence level".  A shipped module
    that no row names is therefore *invisible*: the table is not wrong about it,
    it is silent, which reads as "nothing to see".  This inventory makes that
    silence a failing gate, in the same spirit as ``untested_modules``.
    """

    core = core_modules(root)
    graded: dict[str, list[str]] = {}
    for capability in capabilities:
        for module in capability.modules:
            graded.setdefault(module, []).append(capability.key)
    owned = [name for name in core if name in graded]
    explained = [name for name in core if name not in graded and name in auxiliary]
    unowned = [name for name in core if name not in graded and name not in auxiliary]
    stale = sorted(
        name for name in auxiliary if name in graded or name not in core
    )
    return {
        "core_modules": core,
        "graded": owned,
        "auxiliary": explained,
        "unowned": unowned,
        "stale_reasons": stale,
    }



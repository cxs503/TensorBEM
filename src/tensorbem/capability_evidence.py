_LEVEL_ORDER = (REAL, WITHHELD, STUB, MOCK, MISSING, STALE_CLAIM, NOT_SUPPORTED)


def summary(rows: Sequence[RowEvidence]) -> dict[str, int]:
    counts = {level: 0 for level in _LEVEL_ORDER}
    for row in rows:
        counts[row.level] = counts.get(row.level, 0) + 1
    counts["total"] = len(rows)
    return counts


def render_markdown(
    rows: Sequence[RowEvidence],
    untested: dict[str, list[str]] | None = None,
    coverage: dict[str, list[str]] | None = None,
) -> str:
    counts = summary(rows)
    flips = [
        row for row in rows
        if row.capability.published_2026_10_29 == NOT_SUPPORTED and row.level == REAL
    ]
    lines: list[str] = []
    lines.append("| Capability | Evidence level | Code evidence | Test evidence | Doc anchor |")
    lines.append("|---|---|---|---|---|")
    for row in rows:
        cap = row.capability
        if row.level == NOT_SUPPORTED:
            code = test_cell = doc_cell = "—"
        else:
            code = ", ".join(f"`{name}`" for name in cap.modules[:2])
            if len(cap.modules) > 2:
                code += f" (+{len(cap.modules) - 2})"
            test_cell = (
                f"{row.test_nodes} node(s) in {len(row.test_files)} file(s)" if row.test_nodes else "—"
            )
            doc_cell = ", ".join(f"`{path}`" for path, _ in cap.docs)
        lines.append(f"| {cap.title} | **{row.level}** | {code} | {test_cell} | {doc_cell} |")
    lines.append("")
    lines.append(
        "Counts: "
        + ", ".join(f"**{counts[level]}** {level}" for level in _LEVEL_ORDER if counts[level])
        + f" — {counts['total']} capabilities. The level is derived from code/test/doc evidence by "
        "`python -m tensorbem.capability_evidence`; the block is regenerated with `--write` and "
        "`tests/test_capability_evidence.py` fails when it stops matching the tree."
    )
    if flips:
        lines.append("")
        lines.append(
            "**Corrections versus the 2026-10-29 baseline** — declared out of scope there, shipped "
            "since, and each now carries code plus touching tests:"
        )
        lines.append("")
        for row in flips:
            cap = row.capability
            lines.append(
                f"- **{cap.title}** — was `NOT_SUPPORTED`, now `{row.level}`: "
                f"{', '.join(f'`{name}`' for name in cap.modules)}; "
                f"{row.test_nodes} test node(s) in {', '.join(f'`{f}`' for f in row.test_files)}."
            )
    if coverage is not None:
        total = len(coverage["core_modules"])
        lines.append("")
        lines.append("### Capability coverage")
        lines.append("")
        lines.append(
            f"{len(coverage['graded'])} of {total} core modules (outside `tensorbem.benchmarks`) are "
            f"named by a row above; {len(coverage['auxiliary'])} more carry an accepted reason, so "
            f"**{len(coverage['unowned'])} are unowned**."
        )
        if coverage["auxiliary"]:
            lines.append("")
            for name in coverage["auxiliary"]:
                lines.append(f"- `{name}` — {AUXILIARY_MODULES[name]}")
        if coverage["unowned"]:
            lines.append("")
            lines.append("**Core modules no row grades and no reason explains** (fails the gate):")
            lines.append("")
            for name in coverage["unowned"]:
                lines.append(f"- `{name}`")
        if coverage["stale_reasons"]:
            lines.append("")
            lines.append("Reasons that are now obsolete because a row grades the module:")
            lines.append("")
            for name in coverage["stale_reasons"]:
                lines.append(f"- `{name}`")
    if untested is not None:
        lines.append("")
        lines.append("### Untested modules")
        lines.append("")
        if untested["explained"]:
            lines.append("Not referenced by any test file, with an accepted reason:")
            lines.append("")
            for name in untested["explained"]:
                lines.append(f"- `{name}` — {UNTESTED_MODULES[name]}")
        if untested["unexplained"]:
            lines.append("")
            lines.append("**Unreferenced and unexplained** (fails the gate):")
            lines.append("")
            for name in untested["unexplained"]:
                lines.append(f"- `{name}`")
        if untested["stale_reasons"]:
            lines.append("")
            lines.append("Reasons that are now obsolete because the module is referenced:")
            lines.append("")
            for name in untested["stale_reasons"]:
                lines.append(f"- `{name}`")
    return "\n".join(lines)


def render_document_block(
    rows: Sequence[RowEvidence],
    untested: dict[str, list[str]] | None = None,
    coverage: dict[str, list[str]] | None = None,
) -> str:
    """The exact text that belongs between the begin/end markers in the doc."""

    return "\n".join(
        [BEGIN_MARKER, "", render_markdown(rows, untested, coverage), "", END_MARKER]
    )


def extract_document_block(text: str) -> str:
    begin = text.index(BEGIN_MARKER)
    end = text.index(END_MARKER) + len(END_MARKER)
    return text[begin:end]


def document_drift(root: pathlib.Path | None = None) -> str | None:
    """Return ``None`` when the published block matches the tree, else a diff."""

    import difflib

    root = root or repo_root()
    rows = audit(root)
    untested = untested_modules(root)
    coverage = capability_coverage(root)
    expected = render_document_block(rows, untested, coverage)
    doc_text = (root / BASELINE_DOC).read_text(encoding="utf-8")
    try:
        published = extract_document_block(doc_text)
    except ValueError:
        return "capability block markers are missing from " + BASELINE_DOC
    if published == expected:
        return None
    return "\n".join(
        difflib.unified_diff(
            expected.splitlines(), published.splitlines(),
            fromfile="generated", tofile="published", lineterm="",
        )
    )


def write_document(root: pathlib.Path | None = None) -> pathlib.Path:
    """Rewrite the capability block inside the baseline document."""

    root = root or repo_root()
    path = root / BASELINE_DOC
    text = path.read_text(encoding="utf-8")
    try:
        published = extract_document_block(text)
    except ValueError:
        text = text.rstrip() + "\n\n" + BEGIN_MARKER + "\n\n" + END_MARKER + "\n"
        published = extract_document_block(text)
    expected = render_document_block(
        audit(root), untested_modules(root), capability_coverage(root)
    )
    path.write_text(text.replace(published, expected), encoding="utf-8")
    return path


def main(argv: Sequence[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--json", type=pathlib.Path, help="write the machine-readable matrix here")
    parser.add_argument("--write", action="store_true", help="refresh the block in " + BASELINE_DOC)
    parser.add_argument("--root", type=pathlib.Path, help="repository root (default: autodetect)")
    args = parser.parse_args(argv)

    root = args.root or repo_root()
    rows = audit(root)
    untested = untested_modules(root)
    if args.write:
        path = write_document(root)
        print(f"refreshed {path.relative_to(root)}")
    if args.json:
        args.json.write_text(
            json.dumps(
                {
                    "summary": summary(rows),
                    "rows": [row.as_dict() for row in rows],
                    "untested_modules": untested,
                },
                indent=2,
            ),
            encoding="utf-8",
        )
        print(f"wrote {args.json}")
    if not args.json:
        print(render_markdown(rows, untested))
    failing = [row for row in rows if not row.ok]
    return 1 if failing or untested["unexplained"] or untested["stale_reasons"] else 0


if __name__ == "__main__":  # pragma: no cover
    raise SystemExit(main())

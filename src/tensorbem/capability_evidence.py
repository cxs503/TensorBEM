#: Levels that make the published baseline wrong and therefore fail the gate.
FAILING_LEVELS = (STALE_CLAIM, MISSING, STUB, MOCK)


def repo_root(start: pathlib.Path | None = None) -> pathlib.Path:
    """Return the repository root by walking up to ``pyproject.toml``.

    Counting parents (``Path(__file__).parents[2]``) breaks for a non-editable
    install, where the package lives under ``site-packages`` (mission m2918).
    """

    here = (start or pathlib.Path(__file__)).resolve()
    for candidate in [here, *here.parents]:
        if (candidate / "pyproject.toml").is_file():
            return candidate
    raise RuntimeError(f"no pyproject.toml above {here}")


@dataclass(frozen=True)
class Capability:
    """One published row of the audit baseline's capability table."""

    key: str
    title: str
    claim: str
    level: str  # declared level: REAL means "supported by shipped code"
    modules: tuple[str, ...] = ()
    symbols: tuple[str, ...] = ()
    tests: tuple[str, ...] = ()
    docs: tuple[tuple[str, str], ...] = ()
    note: str = ""
    #: level published in the 2026-10-29 baseline, kept for the correction log
    published_2026_10_29: str | None = None


@dataclass
class RowEvidence:
    capability: Capability
    level: str
    missing_modules: list[str] = field(default_factory=list)
    missing_symbols: list[str] = field(default_factory=list)
    stub_symbols: list[str] = field(default_factory=list)
    mock_markers: list[str] = field(default_factory=list)
    missing_tests: list[str] = field(default_factory=list)
    detached_tests: list[str] = field(default_factory=list)
    missing_docs: list[str] = field(default_factory=list)
    test_files: list[str] = field(default_factory=list)
    test_nodes: int = 0
    reasons: list[str] = field(default_factory=list)

    @property
    def ok(self) -> bool:
        return self.level not in FAILING_LEVELS

    def as_dict(self) -> dict:
        return {
            "key": self.capability.key,
            "title": self.capability.title,
            "claim": self.capability.claim,
            "declared": self.capability.level,
            "level": self.level,
            "ok": self.ok,
            "modules": list(self.capability.modules),
            "symbols": list(self.capability.symbols),
            "test_files": self.test_files,
            "test_nodes": self.test_nodes,
            "missing_modules": self.missing_modules,
            "missing_symbols": self.missing_symbols,
            "stub_symbols": self.stub_symbols,
            "mock_markers": self.mock_markers,
            "missing_tests": self.missing_tests,
            "detached_tests": self.detached_tests,
            "missing_docs": self.missing_docs,
            "reasons": self.reasons,
            "note": self.capability.note,
            "published_2026_10_29": self.capability.published_2026_10_29,
        }



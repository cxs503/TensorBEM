"""Potential-flow benchmark: uniform stream past a fixed sphere ("sphere in uniform flow").

Classical exact solution
------------------------
A sphere of radius ``a`` at the origin in a uniform stream ``U`` along ``+x``
has the disturbance potential (Lamb 1932, §103)

    phi_d = U * a**3 * cos(theta) / (2 * r**2),      r >= a,

so that on the body ``u = phi_d = (U*a/2) * cos(theta)`` and the fluid-normal
derivative is ``q_e = U * cos(theta)`` (the body-normal derivative is
``-U*cos(theta)``).  The total surface velocity is purely tangential with
magnitude

    |v| = (3/2) * U * sin(theta),

and steady Bernoulli gives the exact surface pressure coefficient

    Cp(theta) = 1 - (9/4) * sin(theta)**2,

with ``Cp = 1`` at both stagnation points and ``Cp = -5/4`` on the equator.
The classical consequence is **d'Alembert's paradox**: the pressure resultant on
the sphere is exactly zero, so potential flow predicts no drag.

What is verified here
---------------------
1. The *field-level* answer: the recovered surface velocity
   (:func:`tensorbem.solver3d.evaluate_surface_velocity_at_panels`) driven by
   the second-kind Neumann solve (``(1/2 I - H) u = S q_e``) is fed through
   Bernoulli and ``Cp`` is compared panel by panel with the closed form above.
   The relative L2 error is reported together with its observed convergence
   order under refinement.
2. The *load-level* answer: the per-panel pressure is integrated into a force
   and a moment (:mod:`tensorbem.pressure`) and the resulting force coefficient
   is compared with the exact zero of d'Alembert.  The same integral evaluated
   with the **analytic** ``Cp`` instead of the numerical one separates the
   discretisation error of the solver from the quadrature/faceting baseline of
   the integrator.
3. Two exact identities of the integrator, independent of any BEM solve:
   Archimedes ``F_body = -rho*g*V*z_hat`` on the same closed mesh, and the
   vanishing resultant of a uniform pressure.

Every reference value in this module is a closed form or an analytic identity;
no reference is generated by the implementation under test.  This is a
verification case for the potential-flow chain, not a ship-resistance or
free-surface validation.
"""

from __future__ import annotations

import argparse
import json
import math
from pathlib import Path
from typing import Any, Sequence

import numpy as np

from tensorbem.geometry3d import icosphere
from tensorbem.pressure import (
    hydrostatic_pressure,
    integrate_pressure_loads,
    steady_pressure_coefficient,
    steady_pressure_loads,
)
from tensorbem.solver3d import (
    evaluate_surface_velocity_at_panels,
    solve_laplace_surface_neumann,
)

_DEFAULT_DENSITY = 1025.0
_DEFAULT_GRAVITY = 9.80665
_EQUATOR_CP = -1.25
_STAGNATION_CP = 1.0


def _validate_positive(name: str, value: float) -> float:
    if isinstance(value, (bool, np.bool_)) or not isinstance(
        value, (int, float, np.floating, np.integer)
    ):
        raise TypeError(f"{name} must be a real number")
    number = float(value)
    if not math.isfinite(number) or number <= 0.0:
        raise ValueError(f"{name} must be a positive finite number")
    return number


def _angular_coordinates(points: np.ndarray) -> tuple[np.ndarray, np.ndarray]:
    """Return ``(cos_theta, sin_theta)`` about the ``+x`` polar axis.

    Panel centroids of the faceted mesh lie slightly inside the sphere, so the
    angular coordinate is taken from the centroid direction; the exact solution
    is then compared at the same angular position, with no artificial
    radial-depth bias.
    """
    norms = np.linalg.norm(points, axis=1)
    directions = points / norms[:, None]
    cos_theta = directions[:, 0]
    sin_theta = np.sqrt(
        np.clip(directions[:, 1] ** 2 + directions[:, 2] ** 2, 0.0, 1.0)
    )
    return cos_theta, sin_theta


def exact_pressure_coefficient(sin_theta: np.ndarray) -> np.ndarray:
    """``Cp = 1 - 9/4 * sin(theta)**2`` for uniform flow past a sphere."""
    sine = np.asarray(sin_theta, dtype=float)
    if not np.isfinite(sine).all():
        raise ValueError("sin_theta must be finite")
    return 1.0 - 2.25 * sine**2


def _area_weighted_relative_l2(
    computed: np.ndarray, exact: np.ndarray, areas: np.ndarray
) -> float:
    numerator = float(np.sum(areas * (computed - exact) ** 2))
    denominator = float(np.sum(areas * exact**2))
    if denominator <= 0.0:
        return float("nan")
    return math.sqrt(numerator / denominator)


def _solve_surface_flow(
    subdivisions: int, radius: float, speed: float
) -> dict[str, Any]:
    """Solve the sphere Neumann problem and return the numerical Cp field."""
    mesh = icosphere(int(subdivisions), radius=radius)
    cos_theta, sin_theta = _angular_coordinates(mesh.centroids)
    boundary_potential = 0.5 * speed * radius * cos_theta
    fluid_normal_derivative = speed * cos_theta
    result = solve_laplace_surface_neumann(mesh, fluid_normal_derivative)
    disturbance_velocity = evaluate_surface_velocity_at_panels(mesh, result)
    free_stream = np.array([speed, 0.0, 0.0])
    total_velocity = disturbance_velocity + free_stream[None, :]
    cp_numerical = steady_pressure_coefficient(total_velocity, speed)
    return {
        "mesh": mesh,
        "cos_theta": cos_theta,
        "sin_theta": sin_theta,
        "result": result,
        "boundary_potential": boundary_potential,
        "total_velocity": total_velocity,
        "cp_numerical": cp_numerical,
        "cp_exact": exact_pressure_coefficient(sin_theta),
    }


def run(
    subdivisions: int = 2,
    radius: float = 1.0,
    speed: float = 1.0,
    density: float = _DEFAULT_DENSITY,
    gravity: float = _DEFAULT_GRAVITY,
) -> dict[str, Any]:
    """Run the uniform-flow-past-a-sphere verification at one mesh level."""
    if isinstance(subdivisions, (bool, np.bool_)) or not isinstance(
        subdivisions, (int, np.integer)
    ):
        raise TypeError("subdivisions must be an integer")
    if subdivisions < 0:
        raise ValueError("subdivisions must be non-negative")
    radius = _validate_positive("radius", radius)
    speed = _validate_positive("speed", speed)
    density = _validate_positive("density", density)
    gravity = _validate_positive("gravity", gravity)

    solved = _solve_surface_flow(int(subdivisions), radius, speed)
    mesh = solved["mesh"]
    cp_numerical = solved["cp_numerical"]
    cp_exact = solved["cp_exact"]
    result = solved["result"]
    areas = mesh.areas
    cos_theta = solved["cos_theta"]
    sin_theta = solved["sin_theta"]

    free_stream = np.array([speed, 0.0, 0.0])
    _, loads = steady_pressure_loads(
        mesh, solved["total_velocity"], free_stream, density=density
    )

    # Control: integrate the analytic Cp over the same faceted mesh.  Its
    # resultant is the integrator/faceting baseline, not a BEM effect.
    reference_area = math.pi * radius**2
    pressure_scale = 0.5 * density * speed * speed
    loads_from_exact_cp = integrate_pressure_loads(
        mesh, pressure_scale * cp_exact, density=density
    )

    coefficients = loads.coefficients(
        density=density, speed=speed, area=reference_area, length=radius
    )
    exact_cp_coefficients = loads_from_exact_cp.coefficients(
        density=density, speed=speed, area=reference_area, length=radius
    )

    # Exact identities of the integrator on the same closed mesh (no BEM):
    # a linear hydrostatic field must reproduce Archimedes, and a uniform
    # pressure must produce neither force nor moment on a closed surface.
    free_surface_z = 2.0 * radius
    hydrostatic = hydrostatic_pressure(
        mesh.centroids, density=density, gravity=gravity, free_surface_z=free_surface_z
    )
    buoyancy = integrate_pressure_loads(mesh, hydrostatic, density=density)
    buoyancy_expected = density * gravity * mesh.volume
    uniform_pressure = 3.0 * pressure_scale
    uniform = integrate_pressure_loads(
        mesh, np.full(mesh.panel_count, uniform_pressure), density=density
    )

    # Local extrema of the computed Cp against the closed forms.
    upstream = int(np.argmax(cos_theta))
    downstream = int(np.argmin(cos_theta))
    equator = int(np.argmax(sin_theta))
    stagnation_error = max(
        abs(float(cp_numerical[upstream]) - _STAGNATION_CP),
        abs(float(cp_numerical[downstream]) - _STAGNATION_CP),
    )

    return {
        "benchmark": "uniform_stream_past_sphere",
        "subdivisions": int(subdivisions),
        "panels": mesh.panel_count,
        "vertices": mesh.vertex_count,
        "radius": radius,
        "speed": speed,
        "fluid_density": density,
        "gravity": gravity,
        "h_mean": mesh.h_mean,
        "h_max": mesh.h_max,
        "surface_area": mesh.surface_area,
        "exact_surface_area": 4.0 * math.pi * radius**2,
        "volume": mesh.volume,
        "exact_volume": 4.0 / 3.0 * math.pi * radius**3,
        "boundary_potential_relative_l2_error": _area_weighted_relative_l2(
            result.boundary_values, solved["boundary_potential"], areas
        ),
        "cp_relative_l2_error": _area_weighted_relative_l2(cp_numerical, cp_exact, areas),
        "cp_max_abs_error": float(np.max(np.abs(cp_numerical - cp_exact))),
        "cp_error_at_stagnation_points": stagnation_error,
        "cp_computed_at_stagnation": float(cp_numerical[upstream]),
        "cp_computed_at_equator": float(cp_numerical[equator]),
        "cp_exact_at_equator": _EQUATOR_CP,
        "force_coefficient": coefficients,
        "force_coefficient_from_exact_cp": exact_cp_coefficients,
        "force_on_body": [float(value) for value in loads.force_on_body],
        "archimedes_buoyancy": float(buoyancy.force_on_body[2]),
        "archimedes_expected": float(buoyancy_expected),
        "archimedes_relative_error": abs(
            float(buoyancy.force_on_body[2]) - buoyancy_expected
        )
        / buoyancy_expected,
        "uniform_pressure_force_norm_over_pressure_area": float(
            np.linalg.norm(uniform.force)
        )
        / (uniform_pressure * mesh.surface_area),
        "uniform_pressure_moment_norm_over_pressure_area_length": float(
            np.linalg.norm(uniform.moment)
        )
        / (uniform_pressure * mesh.surface_area * radius),
        "normal_velocity_residual": float(
            np.max(np.abs(np.sum(solved["total_velocity"] * mesh.normals, axis=1)))
        )
        / speed,
        "relative_residual_l2": result.relative_residual_l2,
        "second_kind_system_condition_number": result.condition_number,
        "single_layer_condition_number": float(
            np.linalg.cond(result.single_layer_matrix)
        ),
        "note": (
            "Flat-panel icosphere; boundary data and the Cp reference are closed "
            "forms. The force coefficient is normalised by 0.5*rho*U**2*pi*a**2 and "
            "its exact potential-flow value is zero (d'Alembert). Archimedes and "
            "the uniform-pressure resultant are exact identities of the integrator "
            "on the same mesh; they do not involve the BEM solve."
        ),
    }


def _nested(row: dict[str, Any], key: str) -> float:
    value: Any = row
    for part in key.split("."):
        value = value[part]
    return float(value)


def _observed_order(rough: dict[str, Any], fine: dict[str, Any], key: str) -> float:
    error_rough = _nested(rough, key)
    error_fine = _nested(fine, key)
    if error_rough <= 0.0 or error_fine <= 0.0:
        return float("nan")
    ratio = float(rough["h_mean"]) / float(fine["h_mean"])
    if ratio <= 1.0:
        return float("nan")
    return math.log(error_rough / error_fine) / math.log(ratio)


def run_study(
    levels: Sequence[int] = (1, 2),
    radius: float = 1.0,
    speed: float = 1.0,
    density: float = _DEFAULT_DENSITY,
) -> dict[str, Any]:
    """Refinement study of the Cp error and of the d'Alembert residual."""
    level_list = [int(value) for value in levels]
    if not level_list:
        raise ValueError("at least one subdivision level is required")
    if any(level < 0 for level in level_list):
        raise ValueError("subdivision levels must be non-negative")
    if len(set(level_list)) != len(level_list):
        raise ValueError("subdivision levels must be unique")
    rows = [
        run(level, radius=radius, speed=speed, density=density) for level in level_list
    ]
    orders = []
    for rough, fine in zip(rows, rows[1:]):
        orders.append(
            {
                "levels": [rough["subdivisions"], fine["subdivisions"]],
                "panels": [rough["panels"], fine["panels"]],
                "h_mean_ratio": float(rough["h_mean"]) / float(fine["h_mean"]),
                "cp_error_observed_order": _observed_order(
                    rough, fine, "cp_relative_l2_error"
                ),
                "force_error_observed_order": _observed_order(
                    rough, fine, "force_coefficient.magnitude"
                ),
            }
        )
    return {
        "benchmark": "uniform_stream_past_sphere_study",
        "radius": radius,
        "speed": speed,
        "fluid_density": density,
        "levels": level_list,
        "rows": rows,
        "orders": orders,
        "note": (
            "Errors are against closed-form references only. The observed order "
            "uses h_mean as the mesh-size measure and is reported, not asserted, "
            "for the finest pair where round-off and faceting may dominate."
        ),
    }


def plot_study(study: dict[str, Any], output: Path, subdivisions: int | None = None) -> None:
    """Plot the numerical Cp distribution and the refinement of its error."""
    try:
        import matplotlib

        matplotlib.use("Agg")
        import matplotlib.pyplot as plt
    except ImportError as error:  # pragma: no cover - optional dependency
        raise RuntimeError("matplotlib is required for plotting") from error

    rows = study["rows"]
    chosen = rows[-1]
    if subdivisions is not None:
        for row in rows:
            if int(row["subdivisions"]) == int(subdivisions):
                chosen = row
                break
    solved = _solve_surface_flow(
        int(chosen["subdivisions"]), float(study["radius"]), float(study["speed"])
    )
    mesh = solved["mesh"]
    theta = np.degrees(np.arccos(np.clip(solved["cos_theta"], -1.0, 1.0)))

    figure, axes = plt.subplots(1, 2, figsize=(11.0, 4.2))
    grid = np.linspace(0.0, math.pi, 400)
    axes[0].plot(
        np.degrees(grid),
        exact_pressure_coefficient(np.sin(grid)),
        "k-",
        label="exact $1-\\frac{9}{4}\\sin^2\\theta$",
    )
    order = np.argsort(theta)
    axes[0].plot(
        theta[order],
        solved["cp_numerical"][order],
        "o",
        markersize=2.5,
        alpha=0.6,
        label=f"BEM Bernoulli, {mesh.panel_count} panels",
    )
    axes[0].set_xlabel("polar angle theta [deg]")
    axes[0].set_ylabel("$C_p$")
    axes[0].set_title(f"sphere Cp, {mesh.panel_count} panels")
    axes[0].legend(fontsize=7)
    axes[0].grid(alpha=0.3)

    h_values = [float(row["h_mean"]) for row in rows]
    errors = [float(row["cp_relative_l2_error"]) for row in rows]
    axes[1].loglog(h_values, errors, "o-", label="Cp relative L2 error")
    if len(rows) > 1:
        reference_h = np.array([h_values[0], h_values[-1]])
        axes[1].loglog(
            reference_h,
            errors[0] * (reference_h / h_values[0]) ** 1.0,
            "k--",
            label="slope 1",
        )
        axes[1].loglog(
            reference_h,
            errors[0] * (reference_h / h_values[0]) ** 2.0,
            "k:",
            label="slope 2",
        )
    axes[1].set_xlabel("mean panel size $h$")
    axes[1].set_ylabel("relative error")
    axes[1].set_title("Cp error refinement")
    axes[1].legend(fontsize=8)
    axes[1].grid(alpha=0.3, which="both")
    figure.tight_layout()
    output.parent.mkdir(parents=True, exist_ok=True)
    figure.savefig(output, dpi=140)
    plt.close(figure)


def study_markdown_table(study: dict[str, Any]) -> str:
    """Render the refinement study as a markdown table (numbers from the study)."""
    header = (
        "| subdivisions | panels | h_mean | Cp rel. L2 | Cp max abs | "
        "|C_F| (-) | Archimedes rel. | kappa(1/2 I - H) | observed order |"
    )
    separator = "|" + "---|" * 9
    lines = [header, separator]
    orders = {tuple(order["levels"]): order for order in study.get("orders", [])}
    previous_level = None
    for row in study["rows"]:
        coefficients = row["force_coefficient"]
        order = orders.get((previous_level, row["subdivisions"]))
        order_text = (
            f"{order['cp_error_observed_order']:.2f}" if order is not None else "--"
        )
        lines.append(
            "| {sub} | {panels} | {h:.4f} | {cp:.3e} | {maxabs:.3e} | {force:.2e} | "
            "{arch:.1e} | {cond:.2f} | {order} |".format(
                sub=row["subdivisions"],
                panels=row["panels"],
                h=float(row["h_mean"]),
                cp=float(row["cp_relative_l2_error"]),
                maxabs=float(row["cp_max_abs_error"]),
                force=float(coefficients["magnitude"]),
                arch=float(row["archimedes_relative_error"]),
                cond=float(row["second_kind_system_condition_number"]),
                order=order_text,
            )
        )
        previous_level = row["subdivisions"]
    return "\n".join(lines)


def _json_ready(value: Any) -> Any:
    if isinstance(value, dict):
        return {str(key): _json_ready(item) for key, item in value.items()}
    if isinstance(value, (list, tuple)):
        return [_json_ready(item) for item in value]
    if isinstance(value, (np.floating, np.integer)):
        return value.item()
    return value


def main() -> None:
    parser = argparse.ArgumentParser(description="uniform stream past a sphere")
    parser.add_argument("--subdivisions", type=int, default=2)
    parser.add_argument("--levels", type=int, nargs="+", default=None)
    parser.add_argument("--radius", type=float, default=1.0)
    parser.add_argument("--speed", type=float, default=1.0)
    parser.add_argument("--density", type=float, default=_DEFAULT_DENSITY)
    parser.add_argument("--output", type=Path, help="also write machine-readable JSON")
    parser.add_argument("--plot", type=Path, help="write a Cp/refinement figure (png)")
    parser.add_argument(
        "--markdown", type=Path, help="also write the refinement table as markdown"
    )
    args = parser.parse_args()

    if args.levels:
        study = run_study(
            args.levels, radius=args.radius, speed=args.speed, density=args.density
        )
    else:
        payload = run(
            args.subdivisions,
            radius=args.radius,
            speed=args.speed,
            density=args.density,
        )
        study = {
            "benchmark": payload["benchmark"] + "_study",
            "radius": args.radius,
            "speed": args.speed,
            "fluid_density": args.density,
            "levels": [args.subdivisions],
            "rows": [payload],
            "orders": [],
        }
    text = json.dumps(_json_ready(study), indent=2, sort_keys=True)
    print(text)
    if args.output:
        args.output.parent.mkdir(parents=True, exist_ok=True)
        args.output.write_text(text + "\n")
    if args.markdown:
        args.markdown.parent.mkdir(parents=True, exist_ok=True)
        args.markdown.write_text(study_markdown_table(study) + "\n")
    if args.plot:
        plot_study(study, args.plot)


if __name__ == "__main__":  # pragma: no cover
    main()
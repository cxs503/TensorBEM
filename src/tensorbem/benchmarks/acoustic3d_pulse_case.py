"""``CASE-ACOUSTIC-PULSE``: transient pulse radiated by a pulsating sphere.

Case-pool anchor: ``CASE-ACOUSTIC-PULSE`` -- reference = closed-form transient
solution (retarded potential of a pulsating sphere, the classical underwater
acoustics benchmark), tolerance ``< 8 %``.

The case answers a question the frequency-domain Helmholtz BEM cannot answer on
its own: *does my harmonic solver reproduce the waveform of an actual acoustic
pulse?*  Three routes are run on the same pulse:

``A`` exact retarded-potential solution (:func:`tensorbem.acoustic3d_pulse.exact_monopole_pulse_pressure`),
``B`` exact harmonic amplitude synthesised on the DFT bins (validates the
synthesis itself, no BEM involved),
``C`` BEM harmonic solves synthesised on the same bins (the capability under
test).

Everything printed or written here is generated by the run: no number is typed
into the report by hand.

Usage
-----
    python -m tensorbem.benchmarks.acoustic3d_pulse_case --json out.json \
        --markdown out.md --figure out.png
"""

from __future__ import annotations

import argparse
import json
import math
import time
from pathlib import Path
from typing import Sequence

import numpy as np

from .. import acoustic3d_pulse as ap
from ..geometry3d import icosphere

#: case parameters (SI units)
RADIUS = 0.1  # m -- small sphere: ka stays <= 1.7 for the pulse band
SOUND_SPEED = 1500.0  # m/s
DENSITY = 1025.0  # kg/m^3
RECEIVER_RANGE = 2.0  # m -- 20 radii, beyond the 1/r near field
PULSE_WIDTH = 0.25e-3  # s -- Gaussian sigma of the radial velocity
PULSE_CENTRE = 0.75e-3  # s
WINDOW = 6.0e-3  # s -- contains the whole pulse and its retarded arrival
SAMPLES = 2048
BAND = 4000.0  # Hz -- pulse spectrum is at -86 dB here
TOLERANCE = 0.08  # CASE-ACOUSTIC-PULSE acceptance


def observed_order(mesh_study: list[dict]) -> float | None:
    """Observed convergence order from the last two mesh levels.

    ``icosphere`` refinement quadruples the panel count, so the panel size ``h``
    halves between consecutive levels of the study (``h_ratio = 2``); the order
    is ``log(e_coarse/e_fine) / log(h_ratio)``.
    """

    if len(mesh_study) < 2:
        return None
    fine, coarse = mesh_study[-1], mesh_study[-2]
    e_fine = float(fine["waveform"]["l2_relative_error"])
    e_coarse = float(coarse["waveform"]["l2_relative_error"])
    if e_fine <= 0.0 or coarse["panel_count"] >= fine["panel_count"]:
        return None
    h_ratio = math.sqrt(coarse["panel_count"] / fine["panel_count"]) ** -1.0
    if h_ratio <= 1.0:
        return None
    return float(math.log(e_coarse / e_fine) / math.log(h_ratio))


def _case_inputs() -> dict[str, float]:
    return {
        "radius_m": RADIUS,
        "sound_speed_m_s": SOUND_SPEED,
        "density_kg_m3": DENSITY,
        "receiver_range_m": RECEIVER_RANGE,
        "pulse_width_s": PULSE_WIDTH,
        "pulse_centre_s": PULSE_CENTRE,
        "window_s": WINDOW,
        "samples": float(SAMPLES),
        "band_hz": BAND,
        "tolerance": TOLERANCE,
    }


def run(
    *,
    subdivisions: Sequence[int] = (1, 2),
    json_path: str | Path | None = None,
    markdown_path: str | Path | None = None,
    band_check: bool = False,
) -> dict:
    """Run the case and return the payload that is archived as JSON."""

    t = ap.grid(WINDOW, SAMPLES)
    dt = float(t[1] - t[0])

    def velocity(times: np.ndarray) -> np.ndarray:
        return ap.gaussian_velocity_pulse(
            times, centre=PULSE_CENTRE, width=PULSE_WIDTH
        )

    # ----- route A: exact transient reference -------------------------------
    started = time.time()
    reference = ap.exact_monopole_pulse_pressure(
        t,
        radius=RADIUS,
        velocity=velocity,
        receiver_distance=RECEIVER_RANGE,
        density=DENSITY,
        sound_speed=SOUND_SPEED,
        substeps=16,
    )
    reference_fine = ap.exact_monopole_pulse_pressure(
        t,
        radius=RADIUS,
        velocity=velocity,
        receiver_distance=RECEIVER_RANGE,
        density=DENSITY,
        sound_speed=SOUND_SPEED,
        substeps=32,
    )
    route_a_self_error = ap.waveform_errors(t, reference_fine, reference)
    route_a = {
        "wall_s": time.time() - started,
        "peak_pa": float(np.max(np.abs(reference))),
        "arrival_s": ap.arrival_time(t, reference),
        "energy_pa2_s": ap.pulse_energy(reference, t),
        "self_convergence_substeps_16_vs_32": route_a_self_error,
        "dominant_frequency_hz": ap.dominant_frequency(t, reference),
    }

    # ----- route B: exact harmonic amplitude on the DFT bins ---------------
    omegas = ap.bin_frequencies(WINDOW, BAND)
    amplitudes_u = ap.spectrum(t, velocity(t), omegas)
    amplitudes_exact = np.array(
        [
            ap.exact_pulse_amplitude(
                float(w),
                radius=RADIUS,
                velocity_amplitude=complex(a),
                receiver_distance=RECEIVER_RANGE,
                density=DENSITY,
                sound_speed=SOUND_SPEED,
            )
            for w, a in zip(omegas, amplitudes_u)
        ]
    )
    route_b_pressure = ap.synthesise(t, omegas, amplitudes_exact, duration=WINDOW)
    route_b = {
        "bins": int(omegas.size),
        "bin_spacing_hz": float(omegas[0] / (2.0 * math.pi)),
        "ka_max": float(omegas[-1] / SOUND_SPEED * RADIUS),
        "vs_route_a": ap.waveform_errors(t, reference, route_b_pressure),
    }

    # ----- route C: BEM on the DFT bins -----------------------------------
    receiver = np.array([RECEIVER_RANGE, 0.0, 0.0])
    mesh_study: list[dict] = []
    per_bin_tables: dict[str, list[dict]] = {}
    pulses: dict[str, np.ndarray] = {}
    for subdivisions_level in subdivisions:
        mesh = icosphere(int(subdivisions_level), radius=RADIUS)
        started = time.time()
        solution = ap.synthesise_bem_pulse(
            mesh,
            t,
            radius=RADIUS,
            velocity=velocity,
            receiver=receiver,
            omegas=omegas,
            density=DENSITY,
            sound_speed=SOUND_SPEED,
        )
        wall = time.time() - started
        errors = ap.waveform_errors(t, reference, solution.pressure)
        key = f"sub{int(subdivisions_level)}"
        pulses[key] = solution.pressure
        per_bin_tables[key] = solution.harmonic_error_table()
        mesh_study.append(
            {
                "subdivisions": int(subdivisions_level),
                "panel_count": solution.mesh_panel_count,
                "wall_s": wall,
                "peak_pa": float(np.max(np.abs(solution.pressure))),
                "arrival_s": ap.arrival_time(t, solution.pressure),
                "max_per_bin_error": solution.max_per_bin_error,
                "waveform": errors,
                "passes_tolerance": bool(errors["l2_relative_error"] < TOLERANCE),
            }
        )

    # observed convergence order between the last two mesh levels
    convergence_order = observed_order(mesh_study)

    band_study = None
    if band_check and mesh_study:
        level = int(mesh_study[-1]["subdivisions"])
        mesh = icosphere(level, radius=RADIUS)
        band_rows = []
        for band in (1000.0, 2000.0, 4000.0, 8000.0):
            omega_band = ap.bin_frequencies(WINDOW, band)
            solution = ap.synthesise_bem_pulse(
                mesh,
                t,
                radius=RADIUS,
                velocity=velocity,
                receiver=receiver,
                omegas=omega_band,
                density=DENSITY,
                sound_speed=SOUND_SPEED,
            )
            band_rows.append(
                {
                    "band_hz": band,
                    "bins": int(omega_band.size),
                    "vs_route_a": ap.waveform_errors(t, reference, solution.pressure),
                }
            )
        band_study = band_rows

    finest = mesh_study[-1] if mesh_study else None
    payload = {
        "case": "CASE-ACOUSTIC-PULSE",
        "reference": "closed-form retarded potential of a pulsating sphere",
        "tolerance": TOLERANCE,
        "inputs": _case_inputs(),
        "time_step_s": dt,
        "bins": route_b["bins"],
        "route_a_exact": route_a,
        "route_b_exact_harmonics": route_b,
        "route_c_bem": mesh_study,
        "convergence_order": convergence_order,
        "band_study": band_study,
        "per_bin_error_tables": per_bin_tables,
        "verdict": {
            "measured": "L2 waveform error of the BEM-synthesised pulse vs the exact transient solution",
            "finest_mesh": finest["panel_count"] if finest else None,
            "l2_relative_error": finest["waveform"]["l2_relative_error"] if finest else None,
            "peak_relative_error": finest["waveform"]["peak_relative_error"] if finest else None,
            "tolerance": TOLERANCE,
            "passes": bool(finest["passes_tolerance"]) if finest else False,
        },
        "waveforms": {
            "time_s": t.tolist(),
            "exact_pa": reference.tolist(),
            "exact_harmonics_pa": route_b_pressure.tolist(),
            **{key: value.tolist() for key, value in pulses.items()},
        },
    }

    if json_path is not None:
        Path(json_path).parent.mkdir(parents=True, exist_ok=True)
        Path(json_path).write_text(json.dumps(payload, indent=2))
    if markdown_path is not None:
        Path(markdown_path).parent.mkdir(parents=True, exist_ok=True)
        Path(markdown_path).write_text(render_markdown(payload))
    return payload


def render_markdown(payload: dict) -> str:
    """Render the archived tables (generated from the payload, never retyped)."""

    inputs = payload["inputs"]
    lines = [
        "# CASE-ACOUSTIC-PULSE -- transient pulse of a pulsating sphere",
        "",
        "Generated by `python -m tensorbem.benchmarks.acoustic3d_pulse_case`;",
        "every number below comes from the JSON payload of that run.",
        "",
        "## Inputs",
        "",
        "| quantity | value |",
        "| --- | --- |",
        f"| sphere radius a | {inputs['radius_m']} m |",
        f"| sound speed c | {inputs['sound_speed_m_s']} m/s |",
        f"| density rho | {inputs['density_kg_m3']} kg/m^3 |",
        f"| receiver range r | {inputs['receiver_range_m']} m |",
        f"| pulse width (Gaussian sigma) | {inputs['pulse_width_s']} s |",
        f"| pulse centre | {inputs['pulse_centre_s']} s |",
        f"| analysis window T | {inputs['window_s']} s |",
        f"| samples | {int(inputs['samples'])} |",
        f"| band | {inputs['band_hz']} Hz ({payload['bins']} bins) |",
        "",
        "## Route A -- exact retarded potential",
        "",
        f"- peak |p| = {payload['route_a_exact']['peak_pa']:.6e} Pa",
        f"- arrival time = {payload['route_a_exact']['arrival_s']*1e3:.4f} ms",
        f"- pulse energy = {payload['route_a_exact']['energy_pa2_s']:.6e} Pa^2 s",
        f"- self convergence (substeps 16 vs 32): L2 = "
        f"{payload['route_a_exact']['self_convergence_substeps_16_vs_32']['l2_relative_error']:.3e}",
        "",
        "## Route B -- exact harmonic amplitude on the DFT bins",
        "",
        f"- bins = {payload['route_b_exact_harmonics']['bins']}, "
        f"spacing = {payload['route_b_exact_harmonics']['bin_spacing_hz']:.3f} Hz, "
        f"ka_max = {payload['route_b_exact_harmonics']['ka_max']:.4f}",
        f"- vs route A: L2 = {payload['route_b_exact_harmonics']['vs_route_a']['l2_relative_error']:.3e}, "
        f"peak = {payload['route_b_exact_harmonics']['vs_route_a']['peak_relative_error']:.3e}",
        "",
        "## Route C -- BEM",
        "",
        "| subdivisions | panels | peak |p| [Pa] | arrival [ms] | max per-bin error | L2 waveform error | peak error | passes < 8 % | wall [s] |",
        "| --- | --- | --- | --- | --- | --- | --- | --- | --- |",
    ]
    for row in payload["route_c_bem"]:
        lines.append(
            f"| {row['subdivisions']} | {row['panel_count']} | {row['peak_pa']:.6e} | "
            f"{row['arrival_s']*1e3:.4f} | {row['max_per_bin_error']:.3e} | "
            f"{row['waveform']['l2_relative_error']:.3e} | {row['waveform']['peak_relative_error']:.3e} | "
            f"{'yes' if row['passes_tolerance'] else 'NO'} | {row['wall_s']:.1f} |"
        )
    if payload["convergence_order"] is not None:
        lines += [
            "",
            f"Observed convergence order (last two levels, panel count ratio 4): "
            f"{payload['convergence_order']:.2f}",
        ]
    if payload["band_study"]:
        lines += [
            "",
            "## Band truncation sensitivity (finest mesh)",
            "",
            "| band [Hz] | bins | L2 waveform error | peak error |",
            "| --- | --- | --- | --- |",
        ]
        for row in payload["band_study"]:
            lines.append(
                f"| {row['band_hz']:.0f} | {row['bins']} | "
                f"{row['vs_route_a']['l2_relative_error']:.3e} | "
                f"{row['vs_route_a']['peak_relative_error']:.3e} |"
            )
    verdict = payload["verdict"]
    lines += [
        "",
        "## Verdict",
        "",
        f"- acceptance: L2 waveform error < {verdict['tolerance']*100:.0f} %",
        f"- measured on the finest mesh ({verdict['finest_mesh']} panels): "
        f"L2 = {verdict['l2_relative_error']:.3e}, peak = {verdict['peak_relative_error']:.3e}",
        f"- passes: **{'yes' if verdict['passes'] else 'NO'}**",
        "",
    ]
    return "\n".join(lines)


def main(argv: Sequence[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--subdivisions", default="1,2")
    parser.add_argument("--json", dest="json_path", default=None)
    parser.add_argument("--markdown", dest="markdown_path", default=None)
    parser.add_argument("--band-check", action="store_true")
    args = parser.parse_args(argv)
    levels = tuple(int(s) for s in args.subdivisions.split(",") if s.strip())
    payload = run(
        subdivisions=levels,
        json_path=args.json_path,
        markdown_path=args.markdown_path,
        band_check=args.band_check,
    )
    a = payload["route_a_exact"]
    print(f"route A: peak {a['peak_pa']:.6e} Pa at {a['arrival_s']*1e3:.4f} ms")
    print(f"route B vs A: L2 {payload['route_b_exact_harmonics']['vs_route_a']['l2_relative_error']:.3e}")
    for row in payload["route_c_bem"]:
        print(
            f"route C sub={row['subdivisions']} panels={row['panel_count']:5d} "
            f"L2 {row['waveform']['l2_relative_error']:.3e} "
            f"peak {row['waveform']['peak_relative_error']:.3e} "
            f"per-bin max {row['max_per_bin_error']:.3e} "
            f"pass={row['passes_tolerance']} wall {row['wall_s']:.1f}s"
        )
    if payload["convergence_order"] is not None:
        print(f"observed order {payload['convergence_order']:.2f}")
    for row in payload["band_study"] or []:
        print(
            f"band {row['band_hz']:.0f} Hz ({row['bins']} bins): "
            f"L2 {row['vs_route_a']['l2_relative_error']:.3e}"
        )
    print(f"verdict: {payload['verdict']['passes']} (L2 {payload['verdict']['l2_relative_error']:.3e})")
    return 0 if payload["verdict"]["passes"] else 1


if __name__ == "__main__":
    raise SystemExit(main())
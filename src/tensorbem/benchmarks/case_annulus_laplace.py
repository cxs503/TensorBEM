def write_figures(result: dict, outdir: Path) -> list[Path]:
    """Convergence, field/error contours and the two sensitivity curves."""
    import matplotlib

    matplotlib.use("Agg")
    import matplotlib.pyplot as plt

    outdir.mkdir(parents=True, exist_ok=True)
    paths: list[Path] = []

    # 1. convergence with an N^-2 guide
    fig, axes = plt.subplots(1, 2, figsize=(10.2, 4.2))
    panels = [level["panel_count"] for level in result["cases"][0]["levels"]]
    for key, axis, title, marker in (
        ("q_relative_l2_error", axes[0], "boundary rel L2 error of $q$", "o"),
        ("field_relative_rmse", axes[1], "interior RMSE / $\\max|u_{ref}|$", "s"),
    ):
        for case in result["cases"]:
            axis.loglog(
                panels,
                [level[key] for level in case["levels"]],
                marker + "-",
                label=case["name"],
            )
        guide = np.array([min(panels), max(panels)], dtype=float)
        axis.loglog(
            guide,
            1.0e-1 * (guide / min(panels)) ** -2.0,
            "k--",
            lw=0.9,
            label="$N^{-2}$",
        )
        axis.set_xlabel("total panels $N$")
        axis.set_title(title)
        axis.grid(True, which="both", alpha=0.3)
        axis.legend(fontsize=8)
    fig.tight_layout()
    path = outdir / "convergence.png"
    fig.savefig(path, dpi=160)
    plt.close(fig)
    paths.append(path)

    # 2. potential and absolute error at the advertised budget mesh
    mesh = annulus_mesh(*BUDGET_PANELS, OUTER_RADIUS, INNER_RADIUS)
    # 121^2 targets keeps the Green evaluation (Python loop per target) a
    # few seconds; a finer grid adds nothing to the evidence carried by the plot
    grid = np.linspace(-1.1 * OUTER_RADIUS, 1.1 * OUTER_RADIUS, 121)
    xx, yy = np.meshgrid(grid, grid)
    points = np.column_stack((xx.ravel(), yy.ravel()))
    radius = np.linalg.norm(points, axis=1)
    # the inscribed polygon of the outer loop lies strictly inside r = a, so a
    # 1 % margin keeps the plot points unambiguously inside the fluid domain
    keep = (radius > 1.01 * INNER_RADIUS) & (radius < 0.99 * OUTER_RADIUS)
    fig, axes = plt.subplots(
        len(result["cases"]), 2, figsize=(9.6, 3.9 * len(result["cases"]))
    )
    axes = np.atleast_2d(axes)
    theta = np.linspace(0.0, 2.0 * np.pi, 361)
    for row, case_data in enumerate(result["cases"]):
        case = next(item for item in CASES if item.name == case_data["name"])
        solution = solve_laplace_multiloop(mesh, case.potential(mesh.centers))  # type: ignore[operator]
        numeric = np.full(points.shape[0], np.nan)
        numeric[keep] = evaluate_multiloop_field(mesh, solution, points[keep])
        # evaluate the reference on the fluid points only: the closed forms are
        # singular at the origin (inside the hole), so a full-grid evaluation
        # would emit a spurious log(0) warning for a point that is not in the domain
        exact = np.full(points.shape[0], np.nan)
        exact[keep] = case.potential(points[keep])  # type: ignore[operator]
        filled = axes[row, 0].contourf(
            xx, yy, numeric.reshape(xx.shape), levels=15, cmap="viridis"
        )
        fig.colorbar(filled, ax=axes[row, 0], label="$u_h$")
        axes[row, 0].set_title(
            f"{case.name}: $u_h$ at {BUDGET_PANELS[0]}/{BUDGET_PANELS[1]} panels"
        )
        error = np.abs(numeric - exact)
        filled = axes[row, 1].contourf(
            xx, yy, error.reshape(xx.shape), levels=15, cmap="magma"
        )
        fig.colorbar(filled, ax=axes[row, 1], label="$|u_h-u_{ref}|$")
        axes[row, 1].set_title(f"absolute error (max {np.nanmax(error):.2e})")
        for axis in axes[row]:
            for radius_loop in (OUTER_RADIUS, INNER_RADIUS):
                axis.plot(
                    radius_loop * np.cos(theta),
                    radius_loop * np.sin(theta),
                    "w-",
                    lw=0.9,
                )
            axis.set_aspect("equal")
            axis.set_xlabel("$x/a$")
            axis.set_ylabel("$y/a$")
    fig.tight_layout()
    path = outdir / "field_error.png"
    fig.savefig(path, dpi=160)
    plt.close(fig)
    paths.append(path)

    if "geometry_sweep" not in result:
        return paths

    # 3. sensitivity: wall ratio and reference length
    fig, axes = plt.subplots(1, 2, figsize=(10.2, 4.0))
    ratios = [row["wall_ratio_b_over_a"] for row in result["geometry_sweep"]]
    axes[0].semilogy(
        ratios, [row["q_relative_l2_error"] for row in result["geometry_sweep"]], "o-"
    )
    axes[0].axhline(
        result["acceptance"]["tolerance"],
        color="r",
        ls="--",
        lw=0.9,
        label="3 % tolerance",
    )
    axes[0].set_xlabel("wall ratio $b/a$")
    axes[0].set_ylabel("rel L2 error of $q$")
    axes[0].grid(True, which="both", alpha=0.3)
    axes[0].legend(fontsize=8)
    axes[1].semilogy(
        ratios,
        [row["condition_number"] for row in result["geometry_sweep"]],
        "s-",
        color="tab:orange",
    )
    axes[1].set_xlabel("wall ratio $b/a$")
    axes[1].set_ylabel("cond($S$)")
    axes[1].grid(True, which="both", alpha=0.3)
    fig.tight_layout()
    path = outdir / "sensitivity_wall_ratio.png"
    fig.savefig(path, dpi=160)
    plt.close(fig)
    paths.append(path)

    fig, axes = plt.subplots(1, 2, figsize=(10.2, 4.0))
    lengths = [row["reference_length"] for row in result["reference_length_sweep"]]
    axes[0].loglog(
        lengths,
        [row["condition_number"] for row in result["reference_length_sweep"]],
        "o-",
    )
    axes[0].set_xlabel("kernel reference length $L$")
    axes[0].set_ylabel("cond($S$)")
    axes[0].grid(True, which="both", alpha=0.3)
    axes[1].loglog(
        lengths,
        [row["q_relative_l2_error"] for row in result["reference_length_sweep"]],
        "s-",
        color="tab:red",
    )
    axes[1].axhline(
        result["acceptance"]["tolerance"],
        color="k",
        ls="--",
        lw=0.9,
        label="3 % tolerance",
    )
    axes[1].set_xlabel("kernel reference length $L$")
    axes[1].set_ylabel("rel L2 error of $q$")
    axes[1].grid(True, which="both", alpha=0.3)
    axes[1].legend(fontsize=8)
    fig.tight_layout()
    path = outdir / "sensitivity_reference_length.png"
    fig.savefig(path, dpi=160)
    plt.close(fig)
    paths.append(path)
    return paths



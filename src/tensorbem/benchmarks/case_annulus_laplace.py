# controls and sensitivity studies
# ---------------------------------------------------------------------------
def orientation_control(case: Case, outer_panels: int, inner_panels: int) -> dict:
    """Same mesh, same data, inner loop normals *not* flipped."""
    flipped = annulus_mesh(outer_panels, inner_panels, OUTER_RADIUS, INNER_RADIUS)
    unflipped = MultiLoopMesh(loops=flipped.loops, hole_loops=())
    exact_q = case.normal_derivative(flipped.centers, flipped.normals)  # type: ignore[operator]
    good = solve_laplace_multiloop(flipped, case.potential(flipped.centers))  # type: ignore[operator]
    bad = solve_laplace_multiloop(unflipped, case.potential(unflipped.centers))  # type: ignore[operator]
    exact_flux = np.asarray(boundary_flux(flipped, exact_q))
    scale = float(np.sum(np.abs(exact_q) * flipped.lengths))
    return {
        "case": case.name,
        "outer_panels": outer_panels,
        "inner_panels": inner_panels,
        "correct_q_relative_l2_error": _relative_l2(
            good.normal_derivative - exact_q, exact_q
        ),
        "unflipped_q_relative_l2_error": _relative_l2(
            bad.normal_derivative - exact_q, exact_q
        ),
        "correct_flux_error": float(
            np.linalg.norm(
                np.asarray(boundary_flux(flipped, good.normal_derivative)) - exact_flux
            )
            / scale
        ),
        "unflipped_flux_error": float(
            np.linalg.norm(
                np.asarray(boundary_flux(unflipped, bad.normal_derivative)) - exact_flux
            )
            / scale
        ),
        "correct_condition_number": float(good.condition_number),
        "unflipped_condition_number": float(bad.condition_number),
        "correct_relative_residual": float(good.relative_residual_l2),
        "unflipped_relative_residual": float(bad.relative_residual_l2),
    }


def probe_guard_control() -> dict:
    """A probe inside the hole must be refused (negative control)."""
    mesh = annulus_mesh(*BUDGET_PANELS, OUTER_RADIUS, INNER_RADIUS)
    case = CASES[0]
    result = solve_laplace_multiloop(mesh, case.potential(mesh.centers))  # type: ignore[operator]
    inside_hole = np.array([[0.2 * INNER_RADIUS, 0.0]])
    record = {"probe": inside_hole.tolist()[0], "refused": False, "message": ""}
    try:
        evaluate_multiloop_field(mesh, result, inside_hole)
    except Exception as error:  # the message content is the record
        record["refused"] = True
        record["message"] = str(error)
    return record


def geometry_sweep(case: Case, panels: tuple[int, int] = BUDGET_PANELS) -> list[dict]:
    """Error and conditioning vs the wall ratio ``b/a`` at fixed panel counts."""
    rows = []
    for ratio in GEOMETRY_RATIOS:
        level = measure_level(
            case, panels[0], panels[1], OUTER_RADIUS, ratio * OUTER_RADIUS
        )
        rows.append(
            {
                "wall_ratio_b_over_a": ratio,
                "panel_count": level["panel_count"],
                "q_relative_l2_error": level["q_relative_l2_error"],
                "field_relative_max_error": level["field_relative_max_error"],
                "condition_number": level["condition_number"],
                "passes_tolerance": bool(level["q_relative_l2_error"] < TOLERANCE),
            }
        )
    return rows


def reference_length_sweep(
    case: Case, panels: tuple[int, int] = BUDGET_PANELS
) -> list[dict]:
    """Error and conditioning vs the kernel reference length ``L``."""
    rows = []
    for length in REFERENCE_LENGTHS:
        level = measure_level(
            case,
            panels[0],
            panels[1],
            OUTER_RADIUS,
            INNER_RADIUS,
            reference_length=length,
        )
        rows.append(
            {
                "reference_length": length,
                "outer_radius_over_L": OUTER_RADIUS / length,
                "condition_number": level["condition_number"],
                "q_relative_l2_error": level["q_relative_l2_error"],
                "relative_residual": level["relative_residual"],
                "passes_tolerance": bool(level["q_relative_l2_error"] < TOLERANCE),
            }
        )
    return rows



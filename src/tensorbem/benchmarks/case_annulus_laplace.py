def run_case(
    ladder: tuple[tuple[int, int], ...] = LADDER, with_sweeps: bool = True
) -> dict:
    """Run every case, control and sweep of the pool entry."""
    cases = []
    for case in CASES:
        levels = [measure_level(case, no, ni) for no, ni in ladder]
        order_q = fitted_order(levels, "q_relative_l2_error")
        cases.append(
            {
                "name": case.name,
                "declared_solution": case.doc,
                "outer_radius": OUTER_RADIUS,
                "inner_radius": INNER_RADIUS,
                "levels": levels,
                "observed_order_q_relative_l2": observed_orders(
                    levels, "q_relative_l2_error"
                ),
                "observed_order_field_relative_rmse": observed_orders(
                    levels, "field_relative_rmse"
                ),
                "fitted_order_q_relative_l2": order_q,
                "finest_level": levels[-1],
                "panel_requirement": [
                    panels_for_threshold(levels, "q_relative_l2_error", target, order_q)
                    for target in (0.03, 0.01)
                ],
                "harmonicity": harmonicity_check(case),
                "reference_table": reference_table(case),
            }
        )

    result = {
        "schema": SCHEMA,
        "case_id": CASE_ID,
        "round": 1,
        "declared_solution_forms": [
            "u = A log r + B",
            "u = (r + c^2/r) cos(theta)",
        ],
        "reference_provenance": {
            "form": "closed_form",
            "values": (
                "generated by case_annulus_laplace.reference_table from the "
                "formulas; harmonicity re-checked by finite differences "
                "(harmonicity_check)"
            ),
            "hand_typed_numbers": 0,
            "bibliography": [
                "Lamb H. *Hydrodynamics*. 6th ed. Cambridge University Press, 1932: "
                "uniform flow past a circular cylinder (same edition as "
                "docs/classical_benchmarks.md ref. [1]).",
                "Milne-Thomson L M. *Theoretical Hydrodynamics*. 5th ed. Macmillan, "
                "1968: translating-cylinder potential (docs/classical_benchmarks.md "
                "ref. [3]).",
            ],
            "page_or_article_number": (
                "WITHHELD: neither book is reachable from this container, so the "
                "exact page/article number was not verified in this mission; the "
                "formulas are elementary and are verified numerically by the "
                "harmonicity gate instead of by citation."
            ),
        },
        "conventions": {
            "panels": "constant strength, midpoint collocation, analytic straight-panel kernels",
            "normal_derivative": (
                "du/dn along the domain-outward normal (on the inner loop it "
                "points into the hole)"
            ),
            "probe_rule": "r = b + f (a - b), f in {0.2, 0.5, 0.8}, 16 angles per radius",
        },
        "ladder": [f"{no}/{ni}" for no, ni in ladder],
        "acceptance": {
            "tolerance": TOLERANCE,
            "declared_before_run": True,
            "q_relative_l2_error_lt": TOLERANCE,
            "q_relative_linf_error_lt": TOLERANCE,
            "field_relative_max_error_lt": TOLERANCE,
            "flux_relative_error_lt": TOLERANCE,
            "min_fitted_order": ORDER_MIN,
            "budget_panels": list(BUDGET_PANELS),
        },
        "cases": cases,
    }

    if with_sweeps:
        result["orientation_control"] = [
            orientation_control(CASES[0], *ORIENTATION_PANELS),
            orientation_control(CASES[1], *ORIENTATION_PANELS),
        ]
        result["probe_guard"] = probe_guard_control()
        result["geometry_sweep"] = geometry_sweep(CASES[0])
        result["reference_length_sweep"] = reference_length_sweep(CASES[0])

    result["verdict"] = verdict(result)
    return result


def verdict(result: dict) -> dict:
    """Apply the predeclared thresholds; every line carries its number."""
    acceptance = result["acceptance"]
    checks: list[dict] = []

    def add(case: str, check: str, value, threshold, passed: bool) -> None:
        checks.append(
            {
                "case": case,
                "check": check,
                "value": value,
                "threshold": threshold,
                "passed": bool(passed),
            }
        )

    for case in result["cases"]:
        name = case["name"]
        finest = case["finest_level"]
        for key, threshold in (
            ("q_relative_l2_error", acceptance["q_relative_l2_error_lt"]),
            ("q_relative_linf_error", acceptance["q_relative_linf_error_lt"]),
            ("field_relative_max_error", acceptance["field_relative_max_error_lt"]),
            ("flux_relative_error", acceptance["flux_relative_error_lt"]),
        ):
            add(name, key, finest[key], threshold, finest[key] < threshold)
        order = case["fitted_order_q_relative_l2"]
        add(
            name,
            "fitted_order_q_relative_l2",
            order,
            acceptance["min_fitted_order"],
            order > acceptance["min_fitted_order"],
        )
        harmonic = case["harmonicity"]["max_abs_laplacian_relative"]
        add(
            name,
            "harmonicity_max_abs_laplacian_relative",
            harmonic,
            1.0e-6,
            harmonic < 1.0e-6,
        )
        budget = next(
            (
                level
                for level in case["levels"]
                if (level["outer_panels"], level["inner_panels"]) == BUDGET_PANELS
            ),
            None,
        )
        if budget is not None:
            add(
                name,
                "budget_panels_meet_tolerance",
                budget["q_relative_l2_error"],
                acceptance["q_relative_l2_error_lt"],
                budget["q_relative_l2_error"] < acceptance["q_relative_l2_error_lt"],
            )

    for control in result.get("orientation_control", []):
        ratio = (
            control["unflipped_q_relative_l2_error"]
            / control["correct_q_relative_l2_error"]
        )
        add(control["case"], "orientation_control_ratio", ratio, 10.0, ratio > 10.0)
    if "probe_guard" in result:
        add(
            "probe_guard",
            "hole_probe_refused",
            result["probe_guard"]["refused"],
            True,
            result["probe_guard"]["refused"],
        )

    return {
        "passed": all(check["passed"] for check in checks),
        "tolerance": acceptance["tolerance"],
        "failed_checks": [check for check in checks if not check["passed"]],
        "checks": checks,
    }



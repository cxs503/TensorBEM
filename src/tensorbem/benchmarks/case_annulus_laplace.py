FloatArray = NDArray[np.float64]

CASE_ID = "CASE-BEM-ANNULUS-LAPLACE"
SCHEMA = "tensorbem.case_annulus_laplace/1"

OUTER_RADIUS = 1.0
INNER_RADIUS = 0.5
RADIAL_A = 0.7
RADIAL_B = 1.3
ANGULAR_C = 0.4
REFERENCE_LENGTH = 2.0
PROBE_FRACTIONS = (0.2, 0.5, 0.8)
PROBE_ANGLES = 16

LADDER = ((16, 8), (32, 16), (64, 32), (128, 64), (256, 128))
QUICK_LADDER = LADDER[:4]

#: Pool tolerance: every declared quantity must beat this at the finest level.
TOLERANCE = 0.03
#: The discretisation is second order; anything below this is not a panel method.
ORDER_MIN = 1.5
#: Panel budget advertised to plain convergence users (must meet TOLERANCE).
BUDGET_PANELS = (64, 32)

GEOMETRY_RATIOS = (0.20, 0.30, 0.50, 0.70, 0.85, 0.90, 0.95)
REFERENCE_LENGTHS = (1.0, 1.5, 2.0, 4.0, 8.0)
ORIENTATION_PANELS = (64, 32)


# ---------------------------------------------------------------------------
# reference quantities
# ---------------------------------------------------------------------------
def probe_points(
    outer_radius: float = OUTER_RADIUS,
    inner_radius: float = INNER_RADIUS,
    fractions: tuple[float, ...] = PROBE_FRACTIONS,
    angles: int = PROBE_ANGLES,
) -> FloatArray:
    """Interior probes at ``r = b + f (a - b)`` for ``f`` in ``fractions``."""
    theta = 2.0 * np.pi * np.arange(angles) / angles
    radii = [inner_radius + f * (outer_radius - inner_radius) for f in fractions]
    return np.vstack(
        [np.column_stack((r * np.cos(theta), r * np.sin(theta))) for r in radii]
    )


def reference_table(
    case: Case,
    outer_radius: float = OUTER_RADIUS,
    inner_radius: float = INNER_RADIUS,
    fractions: tuple[float, ...] = PROBE_FRACTIONS,
    angles: int = PROBE_ANGLES,
) -> list[dict]:
    """Reference ``u`` and radial derivative at each probe, from the closed form."""
    points = probe_points(outer_radius, inner_radius, fractions, angles)
    radial = points / np.linalg.norm(points, axis=1)[:, None]
    values = case.potential(points)  # type: ignore[operator]
    slopes = case.normal_derivative(points, radial)  # type: ignore[operator]
    rows = []
    for point, value, slope in zip(points, values, slopes):
        radius = float(np.hypot(point[0], point[1]))
        rows.append(
            {
                "r_over_a": radius / outer_radius,
                "theta_rad": float(math.atan2(point[1], point[0]) % (2.0 * np.pi)),
                "x_over_a": float(point[0] / outer_radius),
                "y_over_a": float(point[1] / outer_radius),
                "u_ref": float(value),
                "du_dr_ref": float(slope),
            }
        )
    return rows


def harmonicity_check(
    case: Case,
    samples: int = 64,
    step: float = 1.0e-4,
    outer_radius: float = OUTER_RADIUS,
    inner_radius: float = INNER_RADIUS,
) -> dict:
    """Prove the reference formula is harmonic instead of trusting the citation.

    Central differences at random interior points give ``Laplace(u)``; the
    residual is normalised by ``max|u| / h^2`` so that the number is comparable
    with the truncation floor of the difference stencil rather than with the
    magnitude of ``u``.
    """
    rng = np.random.default_rng(20261112)
    low, high = inner_radius**2 * 1.05, outer_radius**2 * 0.95
    radius = np.sqrt(rng.uniform(low, high, samples))
    angle = rng.uniform(0.0, 2.0 * np.pi, samples)
    points = np.column_stack((radius * np.cos(angle), radius * np.sin(angle)))
    h = step
    ex, ey = np.array([h, 0.0]), np.array([0.0, h])
    lap = (
        case.potential(points + ex)
        - 2.0 * case.potential(points)
        + case.potential(points - ex)
        + case.potential(points + ey)
        - 2.0 * case.potential(points)
        + case.potential(points - ey)
    ) / (h * h)
    scale = float(np.max(np.abs(case.potential(points)))) / (h * h)  # type: ignore[operator]
    return {
        "case": case.name,
        "samples": samples,
        "step": h,
        "max_abs_laplacian": float(np.max(np.abs(lap))),
        "max_abs_laplacian_relative": float(np.max(np.abs(lap)) / scale),
    }


def _relative_linf(error: FloatArray, reference: FloatArray) -> float:
    denominator = float(np.max(np.abs(reference)))
    return float("inf") if denominator == 0.0 else float(np.max(np.abs(error)) / denominator)


def _relative_l2(error: FloatArray, reference: FloatArray) -> float:
    denominator = float(np.linalg.norm(reference))
    return float("inf") if denominator == 0.0 else float(np.linalg.norm(error) / denominator)


# ---------------------------------------------------------------------------
# one solve
# ---------------------------------------------------------------------------
def measure_level(
    case: Case,
    outer_panels: int,
    inner_panels: int,
    outer_radius: float = OUTER_RADIUS,
    inner_radius: float = INNER_RADIUS,
    reference_length: float | None = None,
    fractions: tuple[float, ...] = PROBE_FRACTIONS,
    angles: int = PROBE_ANGLES,
) -> dict:
    """Solve one case at one mesh level and report every pool quantity."""
    mesh = annulus_mesh(outer_panels, inner_panels, outer_radius, inner_radius)
    data = case.potential(mesh.centers)  # type: ignore[operator]
    if reference_length is None:
        result = solve_laplace_multiloop(mesh, data)
    else:
        result = solve_laplace_multiloop(mesh, data, reference_length=reference_length)
    exact_q = case.normal_derivative(mesh.centers, mesh.normals)  # type: ignore[operator]
    numeric_q = result.normal_derivative

    points = probe_points(outer_radius, inner_radius, fractions, angles)
    numeric_u = evaluate_multiloop_field(mesh, result, points)
    exact_u = case.potential(points)  # type: ignore[operator]

    flux = boundary_flux(mesh, numeric_q)
    exact_flux = boundary_flux(mesh, exact_q)
    flux_scale = float(np.sum(np.abs(exact_q) * mesh.lengths))

    return {
        "outer_panels": outer_panels,
        "inner_panels": inner_panels,
        "panel_count": int(mesh.panel_count),
        "outer_radius": float(outer_radius),
        "inner_radius": float(inner_radius),
        "wall_ratio_b_over_a": float(inner_radius / outer_radius),
        "reference_length": float(result.reference_length),
        "condition_number": float(result.condition_number),
        "relative_residual": float(result.relative_residual_l2),
        "q_relative_l2_error": _relative_l2(numeric_q - exact_q, exact_q),
        "q_relative_linf_error": _relative_linf(numeric_q - exact_q, exact_q),
        "field_relative_max_error": _relative_linf(numeric_u - exact_u, exact_u),
        "field_relative_rmse": float(
            np.sqrt(np.mean((numeric_u - exact_u) ** 2)) / np.max(np.abs(exact_u))
        ),
        "field_probe_count": int(points.shape[0]),
        "flux_outer": float(flux[0]),
        "flux_inner": float(flux[1]),
        "exact_flux_outer": float(exact_flux[0]),
        "exact_flux_inner": float(exact_flux[1]),
        # the exact per-loop flux vanishes for the angular case, so the fluxes
        # are normalised by the integral of |q| ds and not by the exact flux.
        "flux_relative_error": float(
            np.linalg.norm(np.asarray(flux) - np.asarray(exact_flux)) / flux_scale
        ),
    }


def observed_orders(levels: list[dict], key: str) -> list[float]:
    """``log2`` error ratio between consecutive refinement levels (``r = 2``)."""
    orders = []
    for coarse, fine in zip(levels, levels[1:]):
        numerator, denominator = coarse[key], fine[key]
        orders.append(
            float("nan")
            if numerator <= 0.0 or denominator <= 0.0
            else float(math.log2(numerator / denominator))
        )
    return orders


def fitted_order(levels: list[dict], key: str) -> float:
    """Least-squares slope of ``log(error)`` against ``log(panel_count)``."""
    x = np.log([level["panel_count"] for level in levels])
    y = np.log([level[key] for level in levels])
    slope, _ = np.polyfit(x, y, 1)
    return float(-slope)


def panels_for_threshold(
    levels: list[dict], key: str, threshold: float, order: float
) -> dict:
    """Measured panel count meeting ``threshold``, plus the extrapolated one.

    The measured value is the first ladder level below the threshold; the
    extrapolated value uses ``error ~ N^-p`` with the fitted order and is
    reported separately so that it is never mistaken for a run.
    """
    measured = next(
        (level["panel_count"] for level in levels if level[key] < threshold), None
    )
    finest = levels[-1]
    if order <= 0.0 or not math.isfinite(order):
        extrapolated = float("nan")
    else:
        extrapolated = float(
            finest["panel_count"] * (finest[key] / threshold) ** (1.0 / order)
        )
    return {
        "metric": key,
        "threshold": threshold,
        "measured_panel_count": measured,
        "extrapolated_panel_count": extrapolated,
    }



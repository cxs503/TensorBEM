"""算例池 ``CASE-BEM-ANNULUS-LAPLACE``: multiply connected 2-D Laplace (annulus).

Pool entry, round 1.  The physics of this case is already executable in this
package: :mod:`tensorbem.multiloop` assembles several boundary loops and
:mod:`tensorbem.benchmarks.annulus_laplace` verifies the resulting Dirichlet
solver against the two closed-form harmonic solutions of the annulus.  This
module adds nothing to the solver.  It turns that capability into a *pool case*:
one machine-checkable record with predeclared acceptance thresholds, a reference
table generated from the closed form (never hand-typed), two independent
sensitivity studies, a panel budget for plain convergence use, and an explicit
record of the failure modes.

Reference solutions (closed form; every value is generated by
:func:`reference_table` or :func:`harmonicity_check`)
------------------------------------------------------------------------
``radial_log``   ``u = A log r + B``              (``A = 0.7``, ``B = 1.3``)
``angular_cos``  ``u = (r + c^2 / r) cos(theta)`` (``c = 0.4``)

Both are harmonic in the annulus ``b < r < a``.  ``log r`` has its source at the
origin and ``r + c^2/r`` is the translating-cylinder form; the origin lies in
the hole, i.e. outside the fluid domain.  The annulus therefore probes exactly
the topology a single-loop solver cannot express: two loops, the inner one
carrying the domain-outward normal that points *into* the hole.

Declared quantities and thresholds (fixed before any run, stored in the artifact
under ``acceptance`` and never edited afterwards)
------------------------------------------------------------------------
``q`` relative L2 / Linf error on the boundary, ``u`` relative maximum error on
interior probes, per-loop flux relative error and the fitted convergence order:
each error ``< TOLERANCE = 3 %`` at the finest ladder level, order
``> ORDER_MIN = 1.5``.

Sensitivity studies (two, as required by the pool protocol)
------------------------------------------------------------------------
``geometry_sweep``          error and conditioning vs the wall ratio ``b/a`` at
                            fixed panel counts: how thin may the annulus get
                            before the fixed budget fails?
``reference_length_sweep``  error and conditioning vs the kernel reference
                            length ``L`` -- the quantity that carries the
                            logarithmic-capacity degeneracy documented in
                            ``docs/annulus_laplace.md``.

Failure modes recorded by the case (measured, not asserted)
------------------------------------------------------------------------
``orientation_control``  inner normals not flipped: the linear system is still
                         solved to round-off but ``q`` and the flux are wrong.
``probe_guard``          a probe inside the hole must be refused.

Usage::

    PYTHONPATH=src python -m tensorbem.benchmarks.case_annulus_laplace \
        --outdir benchmarks/verified/bem_annulus_laplace
"""


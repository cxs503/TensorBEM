def hull() -> EllipsoidHull:
    return EllipsoidHull(**GEOMETRY)


def _rel(got: complex | float, ref: complex | float) -> float:
    return float(abs(got - ref) / abs(ref))


def geometry_gate(body: EllipsoidHull | None = None) -> dict[str, Any]:
    """Verify ``Cb / L / B`` before any hydrodynamics, as the platform requires."""
    body = body or hull()
    cb_reference = math.pi / 6.0
    return {
        "a": body.a,
        "b": body.b,
        "c": body.c,
        "L": body.L,
        "B": body.B,
        "T": body.T,
        "volume": body.volume,
        "Cb": body.Cb,
        "Cb_reference": cb_reference,
        "Cb_rel_err": abs(body.Cb - cb_reference) / cb_reference,
        "thinness_b_over_a": body.thinness,
        "pass": abs(body.Cb - cb_reference) <= 1.0e-12 * cb_reference,
    }


def kochin_inventory(body: EllipsoidHull | None = None) -> list[dict[str, Any]]:
    """Relative error of every Kochin route against the exact analytic route."""
    body = body or hull()
    rows: list[dict[str, Any]] = []
    for k in WAVENUMBERS:
        ref = kochin_analytic(k, body)
        got_q = kochin_quadrature(k, body)
        phase = abs(
            math.degrees(math.atan2(got_q.imag, got_q.real) - math.atan2(ref.imag, ref.real))
        )
        rows.append(
            {
                "route": "quadrature",
                "k": k,
                "ka": k * body.a,
                "in_envelope": k * body.a <= K_A_ENVELOPE,
                "rel_err": _rel(got_q, ref),
                "phase_diff_deg": phase,
            }
        )
        for name, scheme in ROUTES.items():
            got = kochin_panels(k, body, n_r=PANEL_GRID["n_r"], n_phi=PANEL_GRID["n_phi"], scheme=scheme)
            rows.append(
                {
                    "route": name,
                    "k": k,
                    "ka": k * body.a,
                    "in_envelope": k * body.a <= K_A_ENVELOPE,
                    "rel_err": _rel(got, ref),
                    "phase_diff_deg": None,
                }
            )
    return rows


def resistance_inventory(body: EllipsoidHull | None = None) -> list[dict[str, Any]]:
    """Wave resistance from the analytic route against the quadrature and panel routes."""
    body = body or hull()
    rows: list[dict[str, Any]] = []
    for froude in FROUDES:
        speed = froude * math.sqrt(GRAVITY * body.L)
        k0 = GRAVITY / (speed * speed)
        lambda_max = max(5.0, 10.0 / (k0 * body.T))
        r_analytic = wave_resistance_analytic(body, froude)
        r_quadrature = kelvin_wave_resistance(
            lambda kk: kochin_quadrature(kk, body),
            k0=k0,
            g=GRAVITY,
            n_quad=256,
            lambda_max=lambda_max,
        )
        r_panels = wave_resistance_panels(
            body,
            froude,
            n_r=PANEL_GRID["n_r"],
            n_phi=PANEL_GRID["n_phi"],
            g=GRAVITY,
            lambda_max=lambda_max,
        )
        rows.append(
            {
                "froude": froude,
                "k0": k0,
                "r_analytic": r_analytic,
                "r_quadrature": r_quadrature,
                "r_panels": r_panels,
                "rel_err_quadrature": _rel(r_quadrature, r_analytic),
                "rel_err_panels": _rel(r_panels, r_analytic),
            }
        )
    return rows


def convergence_inventory(body: EllipsoidHull | None = None) -> dict[str, Any]:
    """The two refinement studies of §4.3."""
    body = body or hull()
    ref_panels = kochin_analytic(CONVERGENCE_K, body)
    panels = [
        {
            "n_r": n,
            "n_phi": n,
            "rel_err": _rel(
                kochin_panels(CONVERGENCE_K, body, n_r=n, n_phi=n, scheme="source"), ref_panels
            ),
        }
        for n in CONVERGENCE_PANELS
    ]
    ref_quad = kochin_analytic(QUADRATURE_K, body, n_quad=256)
    quadrature = [
        {
            "n_psi": n,
            "n_phi": 2 * n,
            "rel_err": _rel(kochin_quadrature(QUADRATURE_K, body, n_psi=n, n_phi=2 * n), ref_quad),
        }
        for n in CONVERGENCE_NPSI
    ]
    return {
        "panels_k": CONVERGENCE_K,
        "panels": panels,
        "panels_monotone": all(
            later["rel_err"] < earlier["rel_err"] for earlier, later in zip(panels, panels[1:])
        ),
        "quadrature_k": QUADRATURE_K,
        "quadrature": quadrature,
        "quadrature_monotone": all(
            later["rel_err"] < earlier["rel_err"]
            for earlier, later in zip(quadrature, quadrature[1:])
        ),
    }


def metrics(
    kochin: list[dict[str, Any]], resistance: list[dict[str, Any]], convergence: dict[str, Any]
) -> dict[str, Any]:
    """The composite numbers the declared literals are judged against."""
    envelope = [row for row in kochin if row["in_envelope"]]

    def worst(rows: list[dict[str, Any]], route: str) -> dict[str, Any]:
        sel = [row for row in rows if row["route"] == route]
        return max(sel, key=lambda row: row["rel_err"])

    quad = [row for row in kochin if row["route"] == "quadrature"]
    source_env = worst(envelope, "panels_source")
    integrated_env = worst(envelope, "panels_source_integrated")
    ordinate_all = worst(kochin, "panels_ordinate")
    ordinate_env = worst(envelope, "panels_ordinate")
    res_quad = max(resistance, key=lambda row: row["rel_err_quadrature"])
    res_panels = max(resistance, key=lambda row: row["rel_err_panels"])
    return {
        "quadrature_magnitude_max": max(row["rel_err"] for row in quad),
        "quadrature_phase_max_deg": max(row["phase_diff_deg"] for row in quad),
        "panels_source_in_envelope_max": source_env["rel_err"],
        "panels_source_in_envelope_argmax_k": source_env["k"],
        "panels_integrated_in_envelope_max": integrated_env["rel_err"],
        "panels_integrated_in_envelope_argmax_k": integrated_env["k"],
        "panels_ordinate_in_envelope_max": ordinate_env["rel_err"],
        "panels_ordinate_all_max": ordinate_all["rel_err"],
        "panels_ordinate_all_argmax_k": ordinate_all["k"],
        "resistance_quadrature_max": res_quad["rel_err_quadrature"],
        "resistance_quadrature_argmax_froude": res_quad["froude"],
        "resistance_panels_max": res_panels["rel_err_panels"],
        "resistance_panels_argmax_froude": res_panels["froude"],
        "convergence_panels_first": convergence["panels"][0]["rel_err"],
        "convergence_panels_last": convergence["panels"][-1]["rel_err"],
        "convergence_quadrature_first": convergence["quadrature"][0]["rel_err"],
        "convergence_quadrature_last": convergence["quadrature"][-1]["rel_err"],
    }


def _provenance_table(body: EllipsoidHull) -> list[dict[str, Any]]:
    """Every ``(route, k, n)`` a Kochin literal could have come from, on a fine sweep.

    Cheap (a panel Kochin evaluation is ~0.1 ms), so the provenance search runs
    inside ``build()`` and the archived artifact carries the answer.
    """
    table: list[dict[str, Any]] = []
    for k in WAVENUMBERS:
        ref = kochin_analytic(k, body)
        for name, scheme in ROUTES.items():
            for n in CONVERGENCE_PANELS:
                got = kochin_panels(k, body, n_r=n, n_phi=n, scheme=scheme)
                table.append(
                    {"route": name, "k": k, "n_r": n, "value": _rel(got, ref)}
                )
    return table


def trace(literal: float, table: list[dict[str, Any]]) -> dict[str, Any] | None:
    """Find the ``(route, k, n)`` whose recomputed value reproduces ``literal``."""
    if literal <= 0.0:
        return None
    best = min(table, key=lambda row: abs(row["value"] - literal) / literal)
    rel = abs(best["value"] - literal) / literal
    if rel > PROVENANCE_RTOL:
        return None
    return {**best, "rel_diff": rel}


def judge(value: float, declared: float, criterion: float | None) -> tuple[str, float]:
    """``reproduced`` / ``stale`` / ``withdrawn`` for one declared literal.

    ``withdrawn`` dominates: when the recomputed number misses the criterion the
    report itself quoted, the green tick was wrong no matter how close the
    literal was.
    """
    tol = max(0.10 * abs(declared), 2.0e-3)
    reproduced = abs(value - declared) <= tol
    if criterion is not None and value > criterion:
        return "withdrawn", tol
    return ("reproduced" if reproduced else "stale"), tol


def build() -> dict[str, Any]:
    """Recompute everything, judge the declared literals, and return the artifact."""
    body = hull()
    kochin = kochin_inventory(body)
    resistance = resistance_inventory(body)
    convergence = convergence_inventory(body)
    values = metrics(kochin, resistance, convergence)
    table = _provenance_table(body)

    rows: list[dict[str, Any]] = []
    for entry in DECLARED:
        value = values[entry["key"]]
        verdict, tol = judge(value, entry["declared"], entry["criterion"])
        traced = trace(entry["declared"], table) if entry.get("traceable") else None
        rows.append(
            {
                **entry,
                "recomputed": value,
                "abs_diff": abs(value - entry["declared"]),
                "tolerance": tol,
                "verdict": verdict,
                "declared_traced_to": traced,
            }
        )

    counts = {name: sum(1 for row in rows if row["verdict"] == name) for name in
              ("reproduced", "stale", "withdrawn")}
    return {
        "benchmark": "m13787_revalidation",
        "mission": 15140,
        "source_pr": 658,
        "report": REPORT.name,
        "geometry_gate": geometry_gate(body),
        "settings": {
            "wavenumbers": list(WAVENUMBERS),
            "froudes": list(FROUDES),
            "panel_grid": PANEL_GRID,
            "envelope_ka": K_A_ENVELOPE,
            "current_panel_budget": CURRENT_PANEL_BUDGET,
            "reported_panel_budget": REPORTED_PANEL_BUDGET,
            "convergence_panels": list(CONVERGENCE_PANELS),
            "convergence_npsi": list(CONVERGENCE_NPSI),
            "provenance_rtol": PROVENANCE_RTOL,
        },
        "kochin": kochin,
        "resistance": resistance,
        "convergence": convergence,
        "metrics": values,
        "rows": rows,
        "summary": {
            "counts": counts,
            "withdrawn": [row["key"] for row in rows if row["verdict"] == "withdrawn"],
            "stale": [row["key"] for row in rows if row["verdict"] == "stale"],
            "in_envelope_panels_meet_current_budget": all(
                values[key] <= CURRENT_PANEL_BUDGET
                for key in ("panels_source_in_envelope_max", "panels_integrated_in_envelope_max")
            ),
            "panels_convergence_monotone": bool(convergence["panels_monotone"]),
            "quadrature_at_roundoff": all(
                row["rel_err"] < 1.0e-12 for row in convergence["quadrature"]
            ),
        },
    }


def _fmt_any(value: float) -> str:
    if value >= 1.0e-3:
        return f"{value:.2%}"
    return f"{value:.2e}"



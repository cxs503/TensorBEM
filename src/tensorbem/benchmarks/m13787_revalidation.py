def apply_to_report(report: pathlib.Path, art: dict[str, Any]) -> bool:
    """Rewrite (or append) the §9 block of the dev report. Returns ``changed``."""
    block = render_markdown(art)
    text = report.read_text(encoding="utf-8") if report.exists() else ""
    if BEGIN in text and END in text:
        head, rest = text.split(BEGIN, 1)
        _, tail = rest.split(END, 1)
        new_text = head + block.rstrip("\n") + tail
    else:
        new_text = text.rstrip("\n") + "\n\n" + block
    if new_text != text:
        report.write_text(new_text, encoding="utf-8")
        return True
    return False


def dump(art: dict[str, Any], path: pathlib.Path = ARTIFACT) -> pathlib.Path:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(art, indent=2, sort_keys=True) + "\n", encoding="utf-8")
    return path


def figure(art: dict[str, Any], path: pathlib.Path = FIGURE) -> pathlib.Path:
    """Error-vs-wavenumber figure: routes against the exact route and the budgets."""
    import matplotlib

    matplotlib.use("Agg")
    import matplotlib.pyplot as plt

    style = {
        "quadrature": ("quadrature (definition, exact)", "o", "#1f77b4"),
        "panels_source_integrated": ("panels, source_integrated", "^", "#2ca02c"),
        "panels_source": ("panels, source (sampled)", "v", "#d62728"),
        "panels_ordinate": ("panels, ordinate", "D", "#ff7f0e"),
    }
    rows = art["kochin"]
    ks = sorted({row["k"] for row in rows})
    fig, (ax1, ax2) = plt.subplots(1, 2, figsize=(11.0, 4.2))
    for route, (label, marker, color) in style.items():
        sel = {row["k"]: row for row in rows if row["route"] == route}
        xs = [k for k in ks if k in sel]
        errs = [max(sel[k]["rel_err"], 1.0e-17) for k in xs]
        ax2.semilogy(xs, errs, marker=marker, color=color, lw=1.4, ms=5, label=label)
    envelope_k = art["settings"]["envelope_ka"] / art["geometry_gate"]["a"]
    ax2.axvline(envelope_k, color="gray", ls=":", lw=1.2, label=f"panel envelope k a = {art['settings']['envelope_ka']:.0f}")
    ax2.axhline(art["settings"]["reported_panel_budget"], color="#d62728", ls="--", lw=1.0,
                label="withdrawn 10 % claim")
    ax2.axhline(art["settings"]["current_panel_budget"], color="k", ls="--", lw=1.0,
                label="current 20 % budget")
    ax2.set_xlabel("wavenumber k [1/m]")
    ax2.set_ylabel("relative error vs kochin_analytic (exact)")
    ax2.set_title("m13787 revalidation: Kochin route error on current main")
    ax2.grid(alpha=0.3, which="both")
    ax2.legend(fontsize=7)

    gate = art["geometry_gate"]
    ax1.bar(
        ["reproduced", "stale", "withdrawn"],
        [art["summary"]["counts"][name] for name in ("reproduced", "stale", "withdrawn")],
        color=["#2ca02c", "#ff7f0e", "#d62728"],
    )
    ax1.set_ylabel("declared literals")
    ax1.set_title(
        f"m13787 report vs code (Cb={gate['Cb']:.6f} vs pi/6, b/a={gate['thinness_b_over_a']:.2f})"
    )
    ax1.grid(alpha=0.3, axis="y")
    fig.tight_layout()
    path.parent.mkdir(parents=True, exist_ok=True)
    fig.savefig(path, dpi=150)
    plt.close(fig)
    return path


def check(report: pathlib.Path = REPORT, path: pathlib.Path = ARTIFACT) -> tuple[bool, str]:
    """``--check``: is the committed artifact and the report block still current?"""
    if not path.exists():
        return False, f"missing artifact {path}"
    art = build()
    committed = json.loads(path.read_text(encoding="utf-8"))
    if committed != art:
        return False, "artifact is stale: rerun --write"
    text = report.read_text(encoding="utf-8")
    if BEGIN not in text or END not in text:
        return False, "report has no generated §9 block"
    if render_markdown(art).rstrip("\n") not in text:
        return False, "report §9 block is stale: rerun --write"
    return True, "artifact and report §9 agree with a fresh recomputation"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--write", action="store_true", help="recompute, write artifact + report §9 + figure")
    parser.add_argument("--check", action="store_true", help="exit 1 when artifact/report are stale")
    parser.add_argument("--json", type=pathlib.Path, default=ARTIFACT)
    parser.add_argument("--report", type=pathlib.Path, default=REPORT)
    parser.add_argument("--figure", type=pathlib.Path, default=FIGURE)
    parser.add_argument("--no-figure", action="store_true")
    parser.add_argument("--print-json", action="store_true")
    args = parser.parse_args(argv)

    art = build()
    if args.print_json:
        print(json.dumps(art, indent=2, sort_keys=True))
    if args.write:
        dump(art, args.json)
        changed = apply_to_report(args.report, art)
        if not args.no_figure:
            figure(art, args.figure)
        print(
            f"artifact -> {args.json}\nreport  -> {args.report} ({'updated' if changed else 'unchanged'})"
            + ("" if args.no_figure else f"\nfigure  -> {args.figure}")
        )
    if args.check:
        ok, message = check(args.report, args.json)
        print(message)
        return 0 if ok else 1
    if not (args.write or args.check or args.print_json):
        parser.print_help()
    return 0


if __name__ == "__main__":  # pragma: no cover
    sys.exit(main())
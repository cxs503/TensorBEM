"""Ogilvie-Tuck (Kramers-Kronig) causality check for radiation coefficients.

Why this module exists
----------------------
Every frequency-domain radiation solve in this package produces a pair
``A(omega)``, ``B(omega)`` at *one* frequency.  The existing verification layer
scores each pair against an external reference (Ursell multipoles, Hulme series,
Wang/Linton multipoles) at isolated frequencies.  What no test in the package
checks is the *internal* structure the physics imposes on the whole spectrum:
linearity + causality of the radiation memory kernel make ``A`` and ``B``
Hilbert-transform pairs (Ogilvie 1964, Ogilvie & Tuck 1969).  A solver can
therefore be self-inconsistent -- e.g. get ``B`` from the far-field amplitude
with the wrong ``omega`` scaling -- and still match a reference table at the one
frequency a benchmark happens to tabulate.

This module supplies the transform, validates it on an exact pair, and scores
the Ursell data of :mod:`tensorbem.analytic` with it.

The relations (derived, not quoted)
-----------------------------------
Write the radiation force per unit span in terms of a causal memory kernel,
``F_rad(t) = -A_inf x_ddot(t) - int_0^inf K(tau) x_dot(t - tau) dtau``, with
``x = Re{X exp(-i omega t)}``.  Matching against ``F_rad = -(A x_ddot + B x_dot)``
gives ``B(omega) = int_0^inf K(t) cos(omega t) dt`` and
``A(omega) - A_inf = -(1/omega) int_0^inf K(t) sin(omega t) dt``, i.e.
``H(omega) = B(omega) - i omega [A(omega) - A_inf] = int_0^inf K e^{i omega t} dt``.
``K(t) = 0`` for ``t < 0`` makes ``H`` analytic in the upper half plane, so its
real and imaginary parts are Hilbert transforms.  Reducing to positive
frequencies (``B`` even, ``omega [A - A_inf]`` odd) gives the pair implemented
here::

    A(w) = A_inf + (2/pi)  PV int_0^inf [B(s) - B(w)] / (s^2 - w^2) ds
    B(w) = -(2/pi)      PV int_0^inf [s^2 (A(s) - A_inf) - w^2 (A(w) - A_inf)]
                                     / (s^2 - w^2) ds

Both integrands are regular at ``s = w`` (the numerator vanishes there), and
``PV int_0^inf ds/(s^2 - w^2) = 0`` is what makes the subtracted forms exact.
The implementation integrates in ``d log s`` because the data are naturally
spaced logarithmically in ``ka``.

Validation status
-----------------
* The transform is *exact* on the synthetic causal pair
  ``B = alpha/(alpha^2 + w^2)``, ``A - A_inf = -1/(alpha^2 + w^2)`` (the pair
  generated by ``K(t) = exp(-alpha t)``): ``A`` and ``B`` are both recovered to
  a few times ``1e-3`` and ``A_inf`` to ``1e-3`` relative.  See
  ``docs/radiation_causality_kramers_kronig.md``.
* Applied to the Ursell (1949) deep-water cylinder spectrum of this package the
  same transform does **not** close: the residual is O(1) and the fitted
  ``A_inf`` is not physical.  The stated cause is the missing high-frequency
  tail: ``A(ka)`` in that data set still differs from its limit by ~13 % at
  ``ka = 10`` and keeps creeping up (2807 at ``ka = 10``, 2835 at ``ka = 40``),
  so a Stieltjes transform whose kernel is ``1/(s^2 - w^2)`` cannot be evaluated
  from a finite window.  The module reports this honestly instead of tuning the
  window until the number looks good; see section 5 of the report.

Usage::

    PYTHONPATH=src python3 -m tensorbem.benchmarks.radiation_causality \
        --output artifacts/radiation_causality/causality.json \
        --report docs/radiation_causality_kramers_kronig.md \
        --figure docs/figures/radiation_causality.png
"""

from __future__ import annotations

import argparse
import json
import math
from pathlib import Path

import numpy as np

from tensorbem.analytic import ursell_cylinder_added_mass

__all__ = [
    "synthetic_causal_pair",
    "added_mass_from_damping",
    "damping_from_added_mass",
    "fit_added_mass_infinite",
    "synthetic_validation",
    "ursell_spectrum",
    "ursell_study",
]

RHO = 1025.0
G = 9.80665
RADIUS = 1.0
SUBMERGENCE = 2.0

#: ``alpha`` of the synthetic kernel ``K(t) = exp(-alpha t)`` and its ``A_inf``.
SYNTHETIC_ALPHA = 2.0
SYNTHETIC_A_INF = 5.0


# ---------------------------------------------------------------------------
# Transform
# ---------------------------------------------------------------------------
def _log_grid(lo: float, hi: float, intervals: int) -> tuple[np.ndarray, np.ndarray]:
    """Log-spaced integration nodes and interleaved (strictly interior) targets."""
    if intervals < 4:
        raise ValueError("intervals must be at least 4")
    if not (0.0 < lo < hi):
        raise ValueError("require 0 < lo < hi")
    values = np.geomspace(lo, hi, 2 * intervals + 1)
    return values[0::2], values[1::2]


def _pv_log(nodes: np.ndarray, integrand: np.ndarray) -> float:
    """``int_0^inf`` of the regularised integrand, trapezoidal in ``d log s``."""
    return float(np.trapezoid(integrand * nodes, np.log(nodes)))


def added_mass_from_damping(
    nodes: np.ndarray,
    damping: np.ndarray,
    target: float,
    added_mass_infinite: float,
) -> float:
    """``A(w)`` from the damping spectrum through the regularised PV integral."""
    nodes = np.asarray(nodes, dtype=float)
    damping = np.asarray(damping, dtype=float)
    if nodes.shape != damping.shape:
        raise ValueError("nodes and damping must have the same shape")
    if not (nodes[0] < target < nodes[-1]):
        raise ValueError("the target must lie strictly inside the node window")
    damping_at_target = float(np.interp(math.log(target), np.log(nodes), damping))
    integrand = (damping - damping_at_target) / (nodes ** 2 - target ** 2)
    return added_mass_infinite + (2.0 / math.pi) * _pv_log(nodes, integrand)


def damping_from_added_mass(
    nodes: np.ndarray,
    added_mass: np.ndarray,
    target: float,
    added_mass_infinite: float,
) -> float:
    """``B(w)`` from the added-mass spectrum through the regularised PV integral."""
    nodes = np.asarray(nodes, dtype=float)
    added_mass = np.asarray(added_mass, dtype=float)
    if nodes.shape != added_mass.shape:
        raise ValueError("nodes and added_mass must have the same shape")
    if not (nodes[0] < target < nodes[-1]):
        raise ValueError("the target must lie strictly inside the node window")
    shifted = added_mass - added_mass_infinite
    at_target = float(np.interp(math.log(target), np.log(nodes), shifted))
    integrand = (nodes ** 2 * shifted - target ** 2 * at_target) / (
        nodes ** 2 - target ** 2
    )
    return -(2.0 / math.pi) * _pv_log(nodes, integrand)


def fit_added_mass_infinite(
    nodes: np.ndarray, damping: np.ndarray, targets: np.ndarray, added_mass: np.ndarray
) -> float:
    """Least-squares ``A_inf`` that best satisfies the ``A <- B`` relation.

    The relation is affine in ``A_inf`` with unit slope, so the minimiser is the
    mean of ``A(w) - [reconstruction at A_inf = 0]``.
    """
    residuals = np.array(
        [
            float(np.asarray(added_mass)[j])
            - added_mass_from_damping(nodes, damping, float(w), 0.0)
            for j, w in enumerate(targets)
        ]
    )
    return float(np.mean(residuals))


# ---------------------------------------------------------------------------
# Exact test pair
# ---------------------------------------------------------------------------
def synthetic_causal_pair(ka: np.ndarray | float, alpha: float = SYNTHETIC_ALPHA,
                          added_mass_infinite: float = SYNTHETIC_A_INF):
    """``(A, B)`` generated by the causal kernel ``K(t) = exp(-alpha t)``.

    ``B = alpha/(alpha^2+w^2)`` and ``A - A_inf = -1/(alpha^2+w^2)`` follow from
    the cosine/sine transforms of ``exp(-alpha t)``; here the "frequency" is used
    directly as ``w = ka`` (the pair is a mathematical reference, not a hull).
    """
    values = np.asarray(ka, dtype=float)
    denominator = alpha ** 2 + values ** 2
    return added_mass_infinite - 1.0 / denominator, alpha / denominator


def synthetic_validation(
    lo: float = 1e-3, hi: float = 30.0, intervals: int = 1500
) -> dict[str, object]:
    """Score the transform against the exact pair, and against a broken control."""
    nodes, targets = _log_grid(lo, hi, intervals)
    added_mass_nodes, damping_nodes = synthetic_causal_pair(nodes)
    added_mass_true, damping_true = synthetic_causal_pair(targets)

    fitted = fit_added_mass_infinite(nodes, damping_nodes, targets, added_mass_true)
    reconstructed = np.array(
        [
            added_mass_from_damping(nodes, damping_nodes, float(w), fitted)
            for w in targets
        ]
    )
    error_added_mass = np.abs(reconstructed - added_mass_true) / np.abs(
        added_mass_true
    )
    reconstructed_damping = np.array(
        [
            damping_from_added_mass(nodes, added_mass_nodes, float(w), SYNTHETIC_A_INF)
            for w in targets
        ]
    )
    error_damping = np.abs(reconstructed_damping - damping_true) / np.abs(
        damping_true
    )

    # Negative control: the same machinery with the damping table rolled by one
    # index, i.e. A(w_j) paired with B(w_{j+1}).  The relation must collapse.
    broken = np.roll(damping_nodes, 1)
    control = np.array(
        [
            added_mass_from_damping(nodes, broken, float(w), fitted)
            for w in targets[1:-1]
        ]
    )
    control_error = np.abs(control - added_mass_true[1:-1]) / np.abs(
        added_mass_true[1:-1]
    )

    return {
        "window": {"ka_min": lo, "ka_max": hi, "integration_intervals": intervals},
        "exact_added_mass_infinite": SYNTHETIC_A_INF,
        "fitted_added_mass_infinite": fitted,
        "added_mass_infinite_relative_error": abs(fitted - SYNTHETIC_A_INF)
        / SYNTHETIC_A_INF,
        "added_mass_max_relative_error": float(error_added_mass.max()),
        "added_mass_median_relative_error": float(np.median(error_added_mass)),
        "damping_max_relative_error": float(error_damping.max()),
        "damping_median_relative_error": float(np.median(error_damping)),
        "negative_control_max_relative_error": float(control_error.max()),
        "negative_control_passes": bool(control_error.max() > 0.1),
    }


# ---------------------------------------------------------------------------
# Ursell spectrum of this package
# ---------------------------------------------------------------------------
def ursell_spectrum(
    nodes: np.ndarray,
    radius: float = RADIUS,
    submergence: float = SUBMERGENCE,
    density: float = RHO,
    gravity: float = G,
) -> tuple[np.ndarray, np.ndarray]:
    """Analytic Ursell ``(A, B)`` per unit span for each ``ka`` in ``nodes``."""
    pairs = [
        ursell_cylinder_added_mass(
            radius, submergence, math.sqrt(float(ka) * gravity / radius), density,
            gravity=gravity,
        )
        for ka in nodes
    ]
    return np.array([p[0] for p in pairs]), np.array([p[1] for p in pairs])


def ursell_study(
    lo: float = 0.01, hi: float = 10.0, intervals: int = 200
) -> dict[str, object]:
    """Score this package's Ursell spectrum with the causality transform."""
    nodes, targets = _log_grid(lo, hi, intervals)
    added_mass_nodes, damping_nodes = ursell_spectrum(nodes)
    added_mass_true, damping_true = ursell_spectrum(targets)
    fitted = fit_added_mass_infinite(nodes, damping_nodes, targets, added_mass_true)
    reconstructed = np.array(
        [
            added_mass_from_damping(nodes, damping_nodes, float(w), fitted)
            for w in targets
        ]
    )
    error = np.abs(reconstructed - added_mass_true) / np.abs(added_mass_true)
    tail = {
        "ka": [0.1, 1.0, 10.0, float(hi)],
        "added_mass": [float(v) for v in ursell_spectrum(np.array([0.1, 1.0, 10.0, hi]))[0]],
        "unbounded_added_mass_rho_pi_a2": RHO * math.pi * RADIUS ** 2,
    }
    return {
        "case": "ursell_submerged_cylinder_deep_water_heave",
        "radius": RADIUS,
        "submergence": SUBMERGENCE,
        "window": {"ka_min": lo, "ka_max": hi, "integration_intervals": intervals},
        "fitted_added_mass_infinite": fitted,
        "added_mass_max_relative_error": float(error.max()),
        "added_mass_median_relative_error": float(np.median(error)),
        "high_frequency_creep": tail,
        "verdict": "TRANSFORM-DOES-NOT-CLOSE (see report section 5: missing high-frequency tail)",
    }


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path, default=None)
    parser.add_argument("--report", type=Path, default=None)
    parser.add_argument("--figure", type=Path, default=None)
    args = parser.parse_args()

    result = {
        "benchmark": "radiation_causality_ogilvie_tuck",
        "synthetic": synthetic_validation(),
        "ursell": ursell_study(),
    }
    text = json.dumps(result, indent=2)
    if args.output is not None:
        args.output.parent.mkdir(parents=True, exist_ok=True)
        args.output.write_text(text + "\n")
    print(text)


if __name__ == "__main__":
    main()
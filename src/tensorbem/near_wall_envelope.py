"""Operational accuracy envelope for the near-wall field evaluation (m6445).

Why this module exists
----------------------
``docs/near_surface_error_budget.md`` (m3xxx) established that the near-wall
velocity of the constant-panel double layer does **not** improve when the mesh
is refined at *fixed relative clearance* ``d / h_max``: the amplification
``|grad Omega| / (4 pi)`` grows like ``1 / d`` while the piecewise-constant
trace error shrinks like ``h``, so their product is scale invariant.  The
document then concludes that "mesh refinement is *not* the lever" for this
quantity and that only a higher-order density or a tangential-recovery route
can restore convergence.

That conclusion is too strong, and this module carries the operational rule that
replaces it.  Two statements are both true and must not be conflated:

* at **fixed relative clearance** ``d / h_max`` the error is scale invariant
  (a statement about the *representation*, not about convergence), whereas
* at **fixed physical clearance** ``d`` the error *does* converge under
  refinement (a statement about the *operator*): refining the mesh lowers
  ``h_max``, hence raises ``d / h_max``, hence walks *down* the envelope.

So refinement is a lever after all -- it just has to be driven at fixed physical
distance (or, equivalently, the mesh must be chosen such that the probe clearance
satisfies a ``d / h_max`` requirement).  The measured numbers behind both
statements live in ``docs/near_wall_envelope/study.json``, generated by
``python -m tensorbem.benchmarks.near_wall_envelope_study``.

What the caller gets
--------------------
:class:`NearWallEnvelope` is a *measured, conservative* lookup
``d / h_max -> relative velocity error``.  ``bound(ratio)`` returns the worst
measured error at the nearest measured ratio no larger than the query (so the
bound is never optimistic), ``required_clearance_ratio(target)`` inverts it, and
``check(...)`` turns it into a pass/fail question for a concrete
``(d, h_max, target)`` triple.

The envelope is a *worst-probe* statement over the probe directions of the
benchmark (equator is the worst of equator/pole/oblique on the unit sphere) and
is not a per-point bound: see ``docs/near_wall_envelope.md`` §5.
"""

from __future__ import annotations

import json
import math
from dataclasses import dataclass
from pathlib import Path

import numpy as np
from numpy.typing import NDArray

FloatArray = NDArray[np.float64]

__all__ = [
    "NearWallEnvelope",
    "build_envelope",
    "load_envelope",
    "required_clearance",
]

_JSON_KEY = "envelope"


@dataclass(frozen=True)
class NearWallEnvelope:
    """Measured worst-case near-wall relative error as a function of ``d / h_max``.

    ``clearance_ratio`` is ascending and ``relative_error`` is non-increasing
    (enforced by :func:`build_envelope`), which is what makes ``bound`` a
    conservative step lookup rather than an interpolation guess.
    """

    clearance_ratio: FloatArray
    relative_error: FloatArray

    def __post_init__(self) -> None:
        ratios = np.asarray(self.clearance_ratio, dtype=float)
        errors = np.asarray(self.relative_error, dtype=float)
        if ratios.ndim != 1 or errors.ndim != 1 or ratios.shape != errors.shape:
            raise ValueError("clearance_ratio and relative_error must be 1-D and equal length")
        if ratios.size == 0:
            raise ValueError("empty near-wall envelope")
        if not np.all(np.diff(ratios) > 0.0):
            raise ValueError("clearance_ratio must be strictly ascending")
        if not np.all(np.isfinite(errors)) or np.any(errors < 0.0):
            raise ValueError("relative_error must be finite and non-negative")
        if np.any(np.diff(errors) > 0.0):
            raise ValueError("relative_error must be non-increasing in clearance ratio")
        object.__setattr__(self, "clearance_ratio", ratios)
        object.__setattr__(self, "relative_error", errors)

    # -- lookups ---------------------------------------------------------
    def bound(self, d_over_h: float) -> float:
        """Conservative relative-error bound at ``d / h_max = d_over_h``.

        Steps down to the nearest *measured* ratio that is no larger than the
        query, whose error is larger (the envelope is non-increasing).  A query
        below the measured range returns ``inf``: the envelope makes no claim
        closer to the wall than it was measured.
        """
        ratio = float(d_over_h)
        if not math.isfinite(ratio):
            raise ValueError("d_over_h must be finite")
        if ratio <= 0.0:
            raise ValueError("d_over_h must be positive")
        if ratio < self.clearance_ratio[0]:
            return math.inf
        index = int(np.searchsorted(self.clearance_ratio, ratio, side="right") - 1)
        return float(self.relative_error[index])

    def required_clearance_ratio(self, target: float) -> float:
        """Smallest *measured* ``d / h_max`` whose worst error is ``<= target``."""
        goal = float(target)
        if not (goal > 0.0):
            raise ValueError("target must be positive")
        ok = np.nonzero(self.relative_error <= goal)[0]
        if ok.size == 0:
            raise ValueError(
                "no measured clearance meets the target %.3g (best measured %.3g at "
                "d/h_max=%.3g); extend the envelope before relying on it"
                % (goal, float(self.relative_error[-1]), float(self.clearance_ratio[-1]))
            )
        return float(self.clearance_ratio[int(ok[0])])

    def check(self, clearance: float, h_max: float, target: float = 0.03) -> dict:
        """Pass/fail for a concrete ``(clearance, h_max)`` pair at ``target`` error."""
        if not (clearance > 0.0) or not (h_max > 0.0):
            raise ValueError("clearance and h_max must be positive")
        ratio = float(clearance) / float(h_max)
        required = self.required_clearance_ratio(target)
        bound = self.bound(ratio)
        return {
            "clearance": float(clearance),
            "h_max": float(h_max),
            "d_over_h": ratio,
            "target_relative_error": float(target),
            "required_d_over_h": required,
            "required_clearance": required * float(h_max),
            "bound_relative_error": bound,
            "ok": bool(ratio >= required),
        }

    # -- serialisation ---------------------------------------------------
    def as_dict(self) -> dict:
        return {
            "clearance_ratio": [float(v) for v in self.clearance_ratio],
            "relative_error": [float(v) for v in self.relative_error],
        }

    @classmethod
    def from_dict(cls, payload: dict) -> "NearWallEnvelope":
        return cls(
            clearance_ratio=np.asarray(payload["clearance_ratio"], dtype=float),
            relative_error=np.asarray(payload["relative_error"], dtype=float),
        )


def build_envelope(clearance_ratio, relative_error) -> NearWallEnvelope:
    """Assemble a conservative envelope from measured ``(ratio, error)`` samples.

    Samples are sorted by ratio and the error is replaced by the running maximum
    over all samples at that ratio *or smaller*, i.e. the envelope is the
    upper-hull of the measurements.  Duplicate ratios keep the worst error.  A
    non-monotone or noisy measurement set therefore cannot produce a
    non-conservative (optimistic) bound.
    """
    ratios = np.asarray(clearance_ratio, dtype=float).ravel()
    errors = np.asarray(relative_error, dtype=float).ravel()
    if ratios.size != errors.size or ratios.size == 0:
        raise ValueError("clearance_ratio and relative_error must be non-empty and equal length")
    order = np.argsort(ratios, kind="stable")
    ratios = ratios[order]
    errors = errors[order]
    # collapse duplicates to the worst error
    unique_ratios: list[float] = []
    unique_errors: list[float] = []
    for ratio, error in zip(ratios, errors):
        if unique_ratios and math.isclose(ratio, unique_ratios[-1], rel_tol=1e-12):
            unique_errors[-1] = max(unique_errors[-1], float(error))
        else:
            unique_ratios.append(float(ratio))
            unique_errors.append(float(error))
    # monotone repair, stated in the safe direction: the true error is
    # non-increasing in the clearance ratio, so a *noisy* measurement may only
    # ever be lifted to the largest error measured at a ratio no smaller than
    # its own -- err(r_i) = max over j >= i.  That keeps the envelope
    # non-increasing without ever understating the error.
    raw = np.asarray(unique_errors, dtype=float)
    hull = np.maximum.accumulate(raw[::-1])[::-1]
    return NearWallEnvelope(
        clearance_ratio=np.asarray(unique_ratios, dtype=float), relative_error=hull
    )


def load_envelope(path: str | Path) -> NearWallEnvelope:
    """Load the envelope written by the study driver (``study.json``)."""
    payload = json.loads(Path(path).read_text())
    if _JSON_KEY not in payload:
        raise KeyError("no %r key in %s" % (_JSON_KEY, path))
    return NearWallEnvelope.from_dict(payload[_JSON_KEY])


def required_clearance(target: float, h_max: float, envelope: NearWallEnvelope) -> float:
    """Clearance (metres) needed at panel size ``h_max`` for ``target`` error."""
    if not (h_max > 0.0):
        raise ValueError("h_max must be positive")
    return envelope.required_clearance_ratio(target) * float(h_max)
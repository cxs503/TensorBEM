#!/usr/bin/env python3
"""Render ``docs/CASE-BEM-HULME-HEMISPHERE-RUNG4096.md`` from the artifact.

The docs page is the case-level copy of ``report_rung4096.md``; both are
rendered from ``results_rung4096.json`` by ``rung4096_ladder.render_report`` so
that no number in either page is transcribed by hand.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[2]
sys.path.insert(0, str(HERE))

import rung4096_ladder as L  # noqa: E402

DOC = ROOT / "docs" / "CASE-BEM-HULME-HEMISPHERE-RUNG4096.md"


def main() -> int:
    res = json.loads((HERE / "results_rung4096.json").read_text())
    body = L.render_report(res)
    env = res["environment"]
    header = "\n".join(
        [
            "<!-- generated by benchmarks/verified/casepool_bem_hulme_hemisphere/"
            "make_rung4096_doc.py -- do not edit by hand -->",
            "",
            f"_Provenance: git {env.get('git_head', '')[:12]}, Python {env.get('python')}, "
            f"numpy {env.get('numpy')}, {env.get('platform')}, "
            f"generated {res.get('generated_utc')}._",
            "",
        ]
    )
    DOC.write_text(header + body)
    print(f"wrote {DOC.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
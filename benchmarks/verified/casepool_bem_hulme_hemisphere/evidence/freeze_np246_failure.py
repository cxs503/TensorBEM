#!/usr/bin/env python3
"""Freeze the m20034 failing artifact of ``CASE-BEM-HULME-HEMISPHERE``.

The audit round 1 (``evidence/np246_contradiction.json``) is a *derived*
artifact: ``audit_np246_contradiction.py`` rebuilds it from two mutable inputs.
When ``band_extension/results.json`` was regenerated under the healthy
environment, the record of the failure was silently rewritten with it -- the
contradiction it was written to preserve disappeared from the derived file,
and only the prose document still said WITHHELD.

A verification record must not be reconstructible from the thing it judges.
This script copies the failing artifact out of git history into
``evidence/np246_failing_snapshot_m20034.json`` together with the commit it
was read from and the sha256 of the blob, so that:

* the failure stays on disk and stays citable after the working-tree artifact
  is regenerated;
* any later claim about "what the failing run produced" is checked against a
  byte-identical object, not against a number copied into prose.

The snapshot is written once and never regenerated by the audit; re-running
this script is only allowed to reproduce the *same* bytes from the *same*
commit, and it refuses (exit 1) if the commit's blob has changed.

Usage
-----
    PYTHONPATH=src python benchmarks/verified/casepool_bem_hulme_hemisphere/\
evidence/freeze_np246_failure.py
"""

from __future__ import annotations

import argparse
import hashlib
import json
import subprocess
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
REPO = HERE.parents[3]
CASE = HERE.parent
RELATIVE = "benchmarks/verified/casepool_bem_hulme_hemisphere/band_extension/results.json"
COMMIT = "50d09dec"          # m20034: the run that produced the sign flip
OUT = HERE / "np246_failing_snapshot_m20034.json"


def _blob(commit: str, path: str) -> bytes:
    return subprocess.check_output(["git", "-C", str(REPO), "show",
                                    f"{commit}:{path}"])


def _full_commit(commit: str) -> str:
    return subprocess.check_output(
        ["git", "-C", str(REPO), "rev-parse", commit],
        text=True).strip()


def build() -> dict:
    raw = _blob(COMMIT, RELATIVE)
    payload = json.loads(raw)
    cell = [c for c in payload["cells"]
            if c.get("kind") == "extension" and float(c["ka"]) == 3.5][0]
    return {
        "kind": "frozen_failure_snapshot",
        "case_code": "BEM-HULME-HEMISPHERE",
        "anchor": "CASE-BEM-HULME-HEMISPHERE",
        "why": ("m20034 recorded an honest FAIL of the extended band at ka = 3.5. "
                "The derived audit artifact was later rebuilt from regenerated "
                "inputs and lost the failure; this snapshot keeps the failure "
                "citable from an immutable git object."),
        "recovered_from": {
            "path": RELATIVE,
            "commit": _full_commit(COMMIT),
            "commit_short": COMMIT,
            "mission": "m20034",
        },
        "blob_sha256": hashlib.sha256(raw).hexdigest(),
        "blob_bytes": len(raw),
        "ka": 3.5,
        "panels": cell["panels"],
        "recorded_environment": payload.get("environment"),
        "recorded_git_head": payload.get("git_head"),
        "records_solve_residual": any(k.endswith("residual") for k in cell),
        "failing_cell": {
            "A11_dimless": cell["A11_dimless"],
            "B33_dimless": cell["B33_dimless"],
            "condition_number": cell["condition_number"],
            "reference_A11_dimless": cell["reference"]["A11_dimless"],
            "reference_B33_dimless": cell["reference"]["B33_dimless"],
        },
        "payload": payload,
    }


def main(argv: list[str] | None = None) -> int:
    p = argparse.ArgumentParser(description=__doc__,
                                formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--out", type=Path, default=OUT)
    args = p.parse_args(argv)
    snapshot = build()
    if args.out.is_file():
        old = json.loads(args.out.read_text())
        if old.get("blob_sha256") != snapshot["blob_sha256"]:
            print("refusing to overwrite: the frozen blob changed", file=sys.stderr)
            return 1
    args.out.write_text(json.dumps(snapshot, indent=1))
    print(json.dumps({"snapshot": str(args.out),
                      "commit": snapshot["recovered_from"]["commit"],
                      "blob_sha256": snapshot["blob_sha256"],
                      "A11": snapshot["failing_cell"]["A11_dimless"],
                      "cond": snapshot["failing_cell"]["condition_number"]}, indent=1))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
"""Write the registry-coverage note of sections 4.10-4.11 from the JSON report."""
import json

OUT = "outputs/verif_m3264"
report = json.load(open(f"{OUT}/registry_3d.json"))
rows = report["checks"]
summary = report["summary"]

values = [r for r in rows if r["comparison"] == "value"]
bounds = [r for r in rows if r["comparison"] == "upper"]
printed = [r for r in values if r["key"].startswith("sphere_rot_coupling") or "kappa" in r["key"]]
tight = [r for r in values if r not in printed]
worst_tight = max(tight, key=lambda r: abs(r["relative_deviation"]))
worst_printed = max(printed, key=lambda r: abs(r["relative_deviation"]))
kappa_worst = max(
    (r for r in values if "kappa" in r["key"]), key=lambda r: abs(r["relative_deviation"])
)

by_group = {}
for row in rows:
    by_group.setdefault(row["group"], 0)
    by_group[row["group"]] += 1

block = f"""<!-- m3264:begin (generated by outputs/verif_m3264/inject_docs.py) -->
### 4.12 表 10–12 的声明数字已判据化（注册表复算）

表 10、表 11、表 12 的每一个格子，连同正文里的互易/能量守恒句，现在都是
`tensorbem.benchmarks.declared_numbers` 的一行注册项：新增 `hulme_hemisphere`
（{by_group.get("hulme_hemisphere", 0)} 行）、`hulme_chief`（{by_group.get("hulme_chief", 0)} 行）、
`submerged_sphere`（{by_group.get("submerged_sphere", 0)} 行），共 **{len(rows)} 行**，
全部落在 `standard` 成本层（整块复算约 50 s，普通 `pytest` 即守护）。
复算结果：**{summary["passed"]}/{summary["checked"]} PASS，0 DRIFT**。

| 判据 | 结果 |
|---|---|
| 数值型行（{len(values)} 行）最坏相对偏差 | {summary["worst_value_relative_deviation"]:.2e}（两位有效数字格，见下） |
| 四位有效数字格最坏偏差 | {abs(worst_tight["relative_deviation"]):.2e}（`{worst_tight["key"]}`） |
| 条件数行最坏偏差（容差 2%） | {abs(kappa_worst["relative_deviation"]):.2e}（`{kappa_worst["key"]}`） |
| 上界型行（{len(bounds)} 行，Kochin/Haskind 守恒） | 全部满足（实测/上界最紧 {max((r["measured"] / r["declared"] for r in bounds)):.3f}） |

两处刻意的判据设计：① 表 12 的球心转动耦合 `2.5×10⁻³²` 是舍入位数，不是方法陈述，
注册表改守「耦合比 ≤ 10⁻³⁰」（实测 {2.4916296163167963e-32:.2e}），与 2026-11-03 对
`1.6×10⁻¹⁵` 行和上界的处理一致；② 表 11 的非物理负阻尼 `−0.1042` 以「幅值 0.1042 +
破坏耗散性标志 = 1」两行登记，因为注册表不能登记零/负的比较基准。

复现命令：

```bash
PYTHONPATH=src python -m tensorbem.benchmarks.declared_numbers --tiers standard --strict
```

已知口径差异（未在本节修改，仅记录）：正文「\(B_{{11}}'\) 对 \(h\) 观测阶 1.62 / 1.88 / 1.96」
与表 10 的误差比自洽（\(h\\propto N^{{-1/2}}\)），而 `kochin_hulme_convergence.run_study`
的 `orders` 字段以 `log2(面元数比)` 为分母，读到的是该值的一半（≈0.81 / 0.94），
即「对 \(h\) 的阶」与「对面元数的阶」两种口径并存。故 \(B_{{11}}'\) 的阶不进注册表，
仍由 `tests/test_kochin_hulme_convergence.py` 钉桩。
<!-- m3264:end -->
"""

path = "docs/marine_bem_benchmarks.md"
text = open(path).read()
begin, end = "<!-- m3264:begin", "<!-- m3264:end -->\n"
if begin in text:
    head = text[: text.index(begin)]
    tail = text[text.index(end) + len(end):]
    text = head + block + tail
else:
    anchor = "## 5. 讨论与适用限制"
    assert text.count(anchor) == 1
    text = text.replace(anchor, block + "\n" + anchor)
open(path, "w").write(text)

print(json.dumps({
    "rows": len(rows),
    "worst_value": summary["worst_value_relative_deviation"],
    "worst_tight": [worst_tight["key"], abs(worst_tight["relative_deviation"])],
    "worst_kappa": [kappa_worst["key"], abs(kappa_worst["relative_deviation"])],
    "worst_printed": [worst_printed["key"], abs(worst_printed["relative_deviation"])],
    "tightest_bound_ratio": max(r["measured"] / r["declared"] for r in bounds),
    "by_group": by_group,
}, indent=1))

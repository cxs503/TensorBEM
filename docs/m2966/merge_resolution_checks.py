"""Reproduce the numbers that the three-way merge of ``agent/m2966`` into ``main`` had to reconcile.

Two contested artefacts are checked here, both against code rather than against
either side of the conflict:

1. ``tests/test_documented_benchmarks.py`` -- the coplanar ``log r`` panel
   primitive. ``HEAD`` (m2966) pinned the observed order of a uniform-piece
   Gauss referee; ``origin/main`` pinned three concrete configurations with an
   elementary closed form as the self-panel reference. The merged test keeps
   both, so both datasets are regenerated here and plotted.

2. ``docs/marine_bem_benchmarks.md`` Sec. 4.6 -- the method-of-fundamental-
   solutions (MFS) rows. ``HEAD`` published three rows (64/128/256 panels,
   source count unstated); ``origin/main`` relabelled them with the panel *and*
   source count generated by ``format_markdown`` but kept only two rows. The
   merged table keeps the generated label *and* all three rows, and the third
   row is the one this script certifies.

Run::

    python docs/m2966/merge_resolution_checks.py

Exit status is non-zero if a published number no longer reproduces.
"""

from __future__ import annotations

import json
import math
from pathlib import Path

import numpy as np

from tensorbem.benchmarks import ursell_convergence_table as table
from tensorbem.free_surface_solver import _log_panel_primitive

HERE = Path(__file__).resolve().parent
OUTPUT = HERE / "outputs" / "merge_checks"
TOLERANCE = 1.0e-3


def panel_primitive(xi: float, h: float, length: float) -> float:
    """Closed-form ``int_0^L log|P-Q| ds`` (the object under test)."""
    upper = _log_panel_primitive(np.array([[length - xi]]), np.array([[h]]))
    lower = _log_panel_primitive(np.array([[-xi]]), np.array([[h]]))
    return float((upper - lower)[0, 0])


def composite_gauss(xi: float, h: float, length: float, pieces: int, order: int) -> float:
    """Uniform-piece Gauss rule; the referee whose blind spot is being pinned."""
    nodes, weights = np.polynomial.legendre.leggauss(order)
    edges = np.linspace(0.0, length, pieces + 1)
    total = 0.0
    for start, stop in zip(edges[:-1], edges[1:]):
        half = 0.5 * (stop - start)
        mid = 0.5 * (stop + start)
        s = mid + half * nodes
        total += half * np.sum(weights * 0.5 * np.log((s - xi) ** 2 + h**2))
    return float(total)


def elementary_log_integral(xi: float, length: float) -> float:
    """``int_0^L log|s-xi| ds`` for an interior point, independent of the primitive."""
    left, right = xi, length - xi
    return (left * math.log(left) - left) + (right * math.log(right) - right)


def referee_study() -> dict:
    xi, h, length = 0.5, 0.0, 1.0
    exact = panel_primitive(xi, h, length)
    pieces = [25, 50, 100, 200, 400, 800, 1600]
    errors = [abs(composite_gauss(xi, h, length, n, 20) - exact) for n in pieces]
    orders = [
        math.log2(errors[i] / errors[i + 1]) for i in range(len(errors) - 1)
    ]
    single_panel = abs(composite_gauss(xi, h, length, 1, 20) - exact)
    elementary_gap = abs(elementary_log_integral(xi, length) - exact)
    configurations = []
    for case_xi, case_h, case_length in (
        (0.5, 0.0, 1.0),
        (0.0, 1.0e-3, 1.0),
        (0.9, 0.3, 1.0),
    ):
        closed = panel_primitive(case_xi, case_h, case_length)
        if case_h == 0.0:
            reference = elementary_log_integral(case_xi, case_length)
            refined = composite_gauss(case_xi, case_h, case_length, 400, 20)
            gap = abs(refined - reference)
            kind = "elementary closed form"
        else:
            reference = composite_gauss(case_xi, case_h, case_length, 400, 20)
            refined = reference
            gap = abs(refined - reference)
            kind = "converged composite Gauss (400x20)"
        configurations.append(
            {
                "xi": case_xi,
                "h": case_h,
                "length": case_length,
                "reference": kind,
                "reference_value": reference,
                "closed_form": closed,
                "abs_error": abs(closed - reference),
                "referee_self_gap": gap,
            }
        )
    return {
        "case": "coplanar log panel primitive: uniform-Gauss referee resolution limit",
        "xi": xi,
        "h": h,
        "length": length,
        "closed_form": exact,
        "pieces": pieces,
        "abs_errors": errors,
        "observed_orders": orders,
        "headline_observed_order": math.log2(errors[2] / errors[5])
        / math.log2(pieces[5] / pieces[2]),
        "single_panel_error": single_panel,
        "elementary_closed_form_agreement": elementary_gap,
        "configurations": configurations,
    }


def mfs_published_rows() -> dict:
    """Reproduce every MFS row the merged Sec. 4.6 table publishes."""
    published = {64: (2543.24, 2708.57), 128: (2544.69, 2715.76), 256: (2545.05, 2717.55)}
    reference = table.reference_coefficients(**table._DEFAULTS)
    rows = []
    for panels, (doc_a, doc_b) in sorted(published.items()):
        row = table.mfs_row(panels)
        rows.append(
            {
                "panels": panels,
                "sources": row["sources"],
                "added_mass": row["added_mass"],
                "added_mass_documented": doc_a,
                "added_mass_rel_error": row["added_mass_relative_error"],
                "added_mass_doc_gap": abs(row["added_mass"] - doc_a) / doc_a,
                "damping": row["damping"],
                "damping_documented": doc_b,
                "damping_rel_error": row["damping_relative_error"],
                "damping_doc_gap": abs(row["damping"] - doc_b) / doc_b,
            }
        )
    return {
        "case": "Ursell submerged cylinder (ka=0.6, a/f=0.5), MFS rows of Sec. 4.6",
        "reference": {
            "added_mass": reference["added_mass"],
            "damping": reference["damping"],
        },
        "rows": rows,
        "label_contract": "基本解方法（MFS，<panels> 面元、<sources> 源）",
    }


def render(study: dict, mfs: dict) -> None:
    import matplotlib

    matplotlib.use("Agg")
    import matplotlib.pyplot as plt

    OUTPUT.mkdir(parents=True, exist_ok=True)
    figures = HERE / "figures"
    figures.mkdir(parents=True, exist_ok=True)

    fig, ax = plt.subplots(figsize=(6.4, 4.4))
    pieces = np.array(study["pieces"], dtype=float)
    errors = np.array(study["abs_errors"], dtype=float)
    ax.loglog(pieces, errors, "o-", label="uniform-piece Gauss referee")
    guide = errors[0] * (pieces[0] / pieces)
    ax.loglog(pieces, guide, "k--", lw=1.0, label=r"$O(1/N)$ guide")
    ax.axhline(1.0e-8, color="crimson", ls=":", lw=1.2, label=r"old $10^{-8}$ tolerance")
    ax.axhline(study["single_panel_error"], color="darkgreen", ls="-.", lw=1.0,
               label="single straddling panel (legacy defect)")
    ax.set_xlabel("uniform pieces $N$")
    ax.set_ylabel(r"$|\,\hat I_N - I_{\mathrm{closed}}\,|$")
    ax.set_title("Why a uniform Gauss referee cannot certify $10^{-8}$\n"
                 r"(coplanar self panel, $\xi=0.5$, $h=0$, $L=1$)")
    ax.grid(True, which="both", alpha=0.3)
    ax.legend(fontsize=8, loc="lower left")
    fig.tight_layout()
    fig.savefig(figures / "panel_referee_resolution.png", dpi=150)
    plt.close(fig)

    fig, ax = plt.subplots(figsize=(6.4, 4.4))
    labels = [f"{r['panels']}p/{r['sources']}s" for r in mfs["rows"]]
    x = np.arange(len(labels))
    width = 0.38
    am = [r["added_mass_rel_error"] for r in mfs["rows"]]
    bd = [r["damping_rel_error"] for r in mfs["rows"]]
    ax.bar(x - width / 2, am, width, label=r"added mass $A$")
    ax.bar(x + width / 2, bd, width, label=r"damping $B$")
    ax.axhline(3.0e-2, color="crimson", ls=":", lw=1.2, label="3% acceptance bound")
    ax.set_yscale("log")
    ax.set_xticks(x, labels)
    ax.set_ylabel("relative error vs Ursell closed form")
    ax.set_title("Sec. 4.6 MFS rows of the merged table\n(third row re-certified here)")
    ax.grid(True, axis="y", which="both", alpha=0.3)
    ax.legend(fontsize=8)
    fig.tight_layout()
    fig.savefig(figures / "mfs_rows_vs_reference.png", dpi=150)
    plt.close(fig)


def main() -> int:
    OUTPUT.mkdir(parents=True, exist_ok=True)
    study = referee_study()
    mfs = mfs_published_rows()
    payload = {"panel_referee": study, "mfs_rows": mfs}
    (OUTPUT / "merge_checks.json").write_text(
        json.dumps(payload, indent=2, ensure_ascii=False), encoding="utf-8"
    )
    render(study, mfs)

    problems = []
    if not 0.8 < study["headline_observed_order"] < 1.2:
        problems.append(f"observed order {study['headline_observed_order']:.3f} outside [0.8, 1.2]")
    if study["single_panel_error"] <= 1.0e-4:
        problems.append("legacy single-panel defect no longer exceeds 1e-4")
    if study["elementary_closed_form_agreement"] > 1.0e-13 * abs(study["closed_form"]):
        problems.append("elementary closed form disagrees with the panel primitive")
    for case in study["configurations"]:
        if case["h"] > 0.0 and case["abs_error"] >= 1.0e-8:
            problems.append(f"closed form vs converged referee at h={case['h']}: {case['abs_error']:.2e}")
    for row in mfs["rows"]:
        if row["added_mass_doc_gap"] > TOLERANCE or row["damping_doc_gap"] > TOLERANCE:
            problems.append(
                f"{row['panels']}-panel MFS row drifted: "
                f"{row['added_mass_doc_gap']:.2e} / {row['damping_doc_gap']:.2e}"
            )
        if row["added_mass_rel_error"] > 3.0e-2 or row["damping_rel_error"] > 3.0e-2:
            problems.append(f"{row['panels']}-panel MFS row exceeds the 3% bound")

    print(json.dumps(payload, indent=2, ensure_ascii=False))
    if problems:
        print("PROBLEMS:")
        for problem in problems:
            print(" -", problem)
        return 1
    print("all merge-resolution numbers reproduce")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
#!/usr/bin/env python3
"""Emit the machine-generated tables of the m3985 merge report.

Numbers are read straight out of the registry JSON that the released code
produced (``runs/declared_numbers_merged.json``; the ``main`` baseline run is
``/tmp/declared_numbers_base.json``, produced by the same command in the
baseline worktree).  Nothing is retyped, so the report cannot drift from the
program output.

    python3 docs/m3985/emit_tables.py > docs/m3985/tables.md
"""

from __future__ import annotations

import collections
import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
MERGED = ROOT / "runs" / "declared_numbers_merged.json"
BASE = Path("/tmp/declared_numbers_base.json")


def rows_of(path: Path) -> tuple[dict, list[dict]]:
    with path.open() as handle:
        payload = json.load(handle)
    return payload, payload["checks"]


def fmt(value: float) -> str:
    if value == 0:
        return "0"
    if abs(value) < 1e-3 or abs(value) >= 1e4:
        return f"{value:.3e}"
    return f"{value:.4f}"


def main() -> int:
    merged_meta, merged = rows_of(MERGED)
    base_meta, base = rows_of(BASE)
    print("<!-- generated by docs/m3985/emit_tables.py; do not edit by hand -->")
    print()

    print("### T1. Registered declared numbers per group (tier: standard)\n")
    print("| group | main baseline | merged (m3985) | verdict (merged) |")
    print("|---|---|---|---|")
    base_counts = collections.Counter(row["group"] for row in base)
    merged_counts = collections.Counter(row["group"] for row in merged)
    for group in sorted(merged_counts):
        failed = [row for row in merged if row["group"] == group and row["verdict"] != "PASS"]
        print(f"| `{group}` | {base_counts.get(group, 0)} | {merged_counts[group]} | "
              f"{'PASS' if not failed else 'DRIFT ' + str(len(failed))} |")
    print(f"| **total** | **{base_meta['summary']['checked']}** | "
          f"**{merged_meta['summary']['checked']}** | "
          f"**{merged_meta['summary']['verdict']}** |")
    print()

    rigid = [row for row in merged if row["group"] == "rigid_body"]
    print(f"### T2. Rigid-body rows contributed by agent/m3566 ({len(rigid)} rows)\n")
    print("| key | declared | measured | rel. deviation | tolerance | verdict |")
    print("|---|---|---|---|---|---|")
    for row in sorted(rigid, key=lambda r: r["key"]):
        print(f"| `{row['key']}` | {fmt(row['declared'])} | {fmt(row['measured'])} | "
              f"{fmt(abs(row['relative_deviation']))} | {fmt(row['tolerance'])} | "
              f"{row['verdict']} |")
    print()

    value_rows = [row for row in merged if row["comparison"] == "value"]
    worst = sorted(value_rows, key=lambda r: abs(r["relative_deviation"]), reverse=True)[:10]
    print(f"### T3. Ten worst deviations among the {len(value_rows)} value rows (merged tree)\n")
    print("| key | group | declared | measured | rel. deviation | tolerance | verdict |")
    print("|---|---|---|---|---|---|---|")
    for row in worst:
        print(f"| `{row['key']}` | `{row['group']}` | {fmt(row['declared'])} | "
              f"{fmt(row['measured'])} | {fmt(abs(row['relative_deviation']))} | "
              f"{fmt(row['tolerance'])} | {row['verdict']} |")
    print()
    over = [row for row in value_rows if abs(row["relative_deviation"]) > row["tolerance"]]
    print(f"Rows whose deviation exceeds their own declared tolerance: **{len(over)}**")
    print()
    print(f"Environment (merged run): python {merged_meta['environment']['python']}, "
          f"numpy {merged_meta['environment']['numpy']}, "
          f"commit {merged_meta['environment']['commit']}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
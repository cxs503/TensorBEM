        f"| `A` median relative error | {urs['added_mass_median_relative_error']:.3e} |",
        f"| unbounded-fluid `ρπa²` | {urs['high_frequency_creep']['unbounded_added_mass_rho_pi_a2']:.4f} |",
        "",
        "Ursell `A(ka)` on the evaluation band (built into the CLI output):",
        "",
        "| `ka` | " + " | ".join(f"{v:g}" for v in urs["high_frequency_creep"]["ka"]) + " |",
        "|---|" + "---|" * len(urs["high_frequency_creep"]["ka"]),
        "| `A` (kg/m) | "
        + " | ".join(f"{v:.2f}" for v in urs["high_frequency_creep"]["added_mass"])
        + " |",
        "",
        "Verdict: **" + urs["verdict"] + "**.",
        "",
        "## 4. Figure",
        "",
        "![radiation causality](figures/radiation_causality.png)",
        "",
        "* (a) the exact synthetic damping table; (b) `A` reconstructed from `B`",
        "  against the exact `A` (visually indistinguishable, residual in §3.1);",
